package com.newuniverse.nusmp.arc.kakashi;

import com.newuniverse.nusmp.boss.vfx.BossMoveVfx;
import com.newuniverse.nusmp.particle.fx.Fx;
import com.newuniverse.nusmp.particle.fx.FxTone;
import com.newuniverse.nusmp.particle.fx.ThemeKey;
import com.newuniverse.nusmp.perf.PerfBudgets;
import com.newuniverse.nusmp.vfx.VfxShape;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.phys.Vec3;

/**
 * Why: every particle and effect of the Kakashi boss goes through this one place, which takes its count from the shared per-tick particle budget ({@code PerfBudgets.particles}) and sends the
 * big shapes through {@link BossMoveVfx} (the shared per-tick effect budget), so many players and several effects at once can never flood the network (rule 11). Each ability family has its OWN
 * particle theme ({@code boss.kakashi.*} in particle_themes.json, generated by tools/particles/gen_themes.py), so no two of his effects look alike: red eye-motes for the Sharingan, blue
 * crackle for Raikiri and the Fang, violet for Purple Lightning and the Susanoo, a spatial whirl for Kamui, water, smoke, stone, and a pale puff for the clones. Server side only; no client
 * class is involved. Worst case per call: at most {@link KakashiMath#MAX_POINTS} particles (fewer when the budget is spent) and one effect packet.
 */
final class KakashiFx {
    private KakashiFx() {}

    static final ThemeKey KUNAI = ThemeKey.of("boss.kakashi.kunai"), COPY = ThemeKey.of("boss.kakashi.copy"), RAIKIRI = ThemeKey.of("boss.kakashi.raikiri"), FANG = ThemeKey.of("boss.kakashi.fang"),
            PURPLE = ThemeKey.of("boss.kakashi.purple"), WATER = ThemeKey.of("boss.kakashi.water"), NINKEN = ThemeKey.of("boss.kakashi.ninken"), CLONE = ThemeKey.of("boss.kakashi.clone"),
            MIST = ThemeKey.of("boss.kakashi.mist"), EARTH = ThemeKey.of("boss.kakashi.earth"), KAMUI = ThemeKey.of("boss.kakashi.kamui"), SUSANOO = ThemeKey.of("boss.kakashi.susanoo"),
            LOG = ThemeKey.of("boss.kakashi.log");

    /** The colours of the effect packets (0xRRGGBB). */
    static final int RGB_RAIKIRI = 0x8FD8FF, RGB_FANG = 0x6AA8FF, RGB_PURPLE = 0xB070FF, RGB_WATER = 0x3F9FFF, RGB_KAMUI = 0x8F5BFF, RGB_SUSANOO = 0xA89CFF, RGB_EARTH = 0x9A7A4E, RGB_MIST = 0xD8E4F0,
            RGB_COPY = 0xFF3A3A, RGB_CLONE = 0xE8E8F0;

    private static int take(ServerLevel sl, int wanted) { return PerfBudgets.particles(sl.getGameTime(), Math.max(0, Math.min(KakashiMath.MAX_POINTS, wanted))); }

    /** A puff of a theme's particles round a point. */
    static void puff(ServerLevel sl, ThemeKey k, Vec3 at, int count, double spread) {
        int n = take(sl, count);
        if (n > 0) Fx.send(sl, k, at.x, at.y, at.z, n, spread);
    }

    /** A bigger, faster burst of a theme. */
    static void burst(ServerLevel sl, ThemeKey k, Vec3 at, int count, double spread) {
        int n = take(sl, count);
        if (n > 0) Fx.burst(sl, k, at.x, at.y, at.z, n, spread);
    }

    /** A flat ring of a theme's signature particle (a telegraph on the ground, a shock). */
    static void ring(ServerLevel sl, ThemeKey k, Vec3 c, double radius, int points) {
        int n = take(sl, points);
        if (n > 0) Fx.ring(sl, k, c.x, c.y + 0.1, c.z, radius, n);
    }

    /** A line of particles from one point to another (a lane, a thrust, a chain of lightning): at most {@code points} samples. */
    static void line(ServerLevel sl, ThemeKey k, Vec3 from, Vec3 to, int points) {
        int n = take(sl, points);
        if (n <= 0) return;
        Vec3 v = to.subtract(from);
        for (int i = 0; i <= n; i++) {
            Vec3 p = from.add(v.scale(i / (double) Math.max(1, n)));
            Fx.send(sl, k, p.x, p.y, p.z, 1, 0.12);
        }
    }

    /** Motes drawn toward a point (a charge): one call, the count shared over the theme's four particles. */
    static void gather(ServerLevel sl, ThemeKey k, Vec3 at, double radius, int count) { puff(sl, k, at, count, radius); }

    /** The shadowed twin of a theme (the Kamui whirl, smoke). */
    static void dark(ServerLevel sl, ThemeKey k, Vec3 at, int count, double spread) {
        int n = take(sl, count);
        if (n > 0) Fx.send(sl, k, FxTone.DARK, at.x, at.y, at.z, n, spread, 0.05);
    }

    /** A big shape through the shared effect budget: false when the budget of this tick is spent. */
    static boolean shape(ServerLevel sl, VfxShape s, Vec3 from, Vec3 to, int rgb, int ticks, double size) { return BossMoveVfx.plain(sl, s, from, to, rgb, ticks, size); }
}
