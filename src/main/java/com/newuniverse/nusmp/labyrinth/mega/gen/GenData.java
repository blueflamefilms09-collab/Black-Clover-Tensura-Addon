package com.newuniverse.nusmp.labyrinth.mega.gen;

import net.minecraft.core.HolderLookup;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.nbt.ListTag;
import net.minecraft.nbt.Tag;
import net.minecraft.server.MinecraftServer;
import net.minecraft.world.level.saveddata.SavedData;

import java.util.Map;
import java.util.TreeMap;

/**
 * Why: the saved {@code Sector} is the contract every other system reads, so it holds only what they need (rooms, markers, landmarks), not how the sector
 * was made. The generator's own bookkeeping, how many pieces the plan had (door caps included), how many loops, how many tries the solver needed, whether
 * the fallback layout was used, how long it took and how long the tunnel to the Landing is, is kept here in a second, tiny saved-data file of the overworld
 * ({@code data/nusmp_mega_gen.dat}). It is what {@code /multiverse mega status} prints, what the end-of-placement log line reports and what an owner reads
 * when a sector looks thin ("it took the fallback layout"). One compound per sector, numbers only: a hundred sectors are a few kilobytes.
 */
public final class GenData extends SavedData {
    public static final String NAME = "nusmp_mega_gen";

    /** What the generator knew about one sector when it finished placing it. */
    public static final class Stat {
        public int pieces, caps, loops, tries, link;
        public long millis;
        public boolean fallback, deadEnd;
        /** 1.107.0: was gen.clearance7 on when the sector was finished (its doorways, corridors and stairs were cut to 7 x 7)? Written only when true, so an older save is byte for byte the same. */
        public boolean clear7;

        CompoundTag save(int id) {
            CompoundTag t = new CompoundTag();
            t.putInt("id", id);
            t.putInt("pieces", pieces);
            t.putInt("caps", caps);
            t.putInt("loops", loops);
            t.putInt("tries", tries);
            t.putInt("link", link);
            t.putLong("ms", millis);
            t.putBoolean("fallback", fallback);
            t.putBoolean("dead", deadEnd);
            if (clear7) t.putBoolean("c7", true);
            return t;
        }

        static Stat load(CompoundTag t) {
            Stat s = new Stat();
            s.pieces = t.getInt("pieces");
            s.caps = t.getInt("caps");
            s.loops = t.getInt("loops");
            s.tries = t.getInt("tries");
            s.link = t.getInt("link");
            s.millis = t.getLong("ms");
            s.fallback = t.getBoolean("fallback");
            s.deadEnd = t.getBoolean("dead");
            s.clear7 = t.getBoolean("c7");
            return s;
        }
    }

    private final Map<Integer, Stat> stats = new TreeMap<>();

    public GenData() {}

    public static GenData get(MinecraftServer server) {
        return server.overworld().getDataStorage().computeIfAbsent(new SavedData.Factory<>(GenData::new, GenData::load, null), NAME);
    }

    /** The stats of a sector, or null when it was never finished (or was generated by a version that did not record them). */
    public Stat get(int sectorId) { return stats.get(sectorId); }

    public void put(int sectorId, Stat s) {
        stats.put(sectorId, s);
        setDirty();
    }

    public void remove(int sectorId) {
        if (stats.remove(sectorId) != null) setDirty();
    }

    @Override
    public CompoundTag save(CompoundTag tag, HolderLookup.Provider registries) {
        ListTag l = new ListTag();
        for (Map.Entry<Integer, Stat> e : stats.entrySet()) l.add(e.getValue().save(e.getKey()));
        tag.put("stats", l);
        return tag;
    }

    public static GenData load(CompoundTag tag, HolderLookup.Provider registries) {
        GenData d = new GenData();
        ListTag l = tag.getList("stats", Tag.TAG_COMPOUND);
        for (int i = 0; i < l.size(); i++) d.stats.put(l.getCompound(i).getInt("id"), Stat.load(l.getCompound(i)));
        return d;
    }
}
