    /** Takes every trace of the last scenario off the stand-in. */
    private static void clear(Player person) {
        person.removeAllEffects();
        person.setRemainingFireTicks(0);
        person.setTicksFrozen(0);
        person.setDeltaMovement(Vec3.ZERO);
    }

    /** Puts the stand-in {@code d} blocks down the lane from the Guardian, standing on the floor with nothing on it. */
    private static void stand(Player person, LabyrinthGuardianEntity g, int[] lane, double d) {
        clear(person);
        person.setPos(g.getX() + lane[3] * d, lane[1], g.getZ() + lane[4] * d);
    }

    private static void traitScenario(ServerLevel level, LabyrinthGuardianEntity g, Player person, int[] lane, Trait trait, List<String> done) {
        GuardianTraits.State st = new GuardianTraits.State();
        switch (trait) {
            case GRAVITY -> {
                stand(person, g, lane, 2.0);
                GuardianTraits.tick(g, level, new GuardianTraits.State(), trait, false);
                expect(!person.hasEffect(MobEffects.MOVEMENT_SLOWDOWN), "GRAVITY: a person at its feet must not be pulled");
                stand(person, g, lane, 7.0);
                GuardianTraits.tick(g, level, st, trait, false);
                expect(person.hasEffect(MobEffects.MOVEMENT_SLOWDOWN), "GRAVITY: the pulled person is not slowed");
                Vec3 pull = person.getDeltaMovement();
                double along = pull.x * lane[3] + pull.z * lane[4];
                expect(along < -0.3, "GRAVITY: the pull does not point at the Guardian: " + pull);
                expect(st.readyAt > level.getGameTime(), "GRAVITY: no cooldown after the well");
            }
            case BLOOD -> {
                stand(person, g, lane, 2.0);
                expect(g.getAbsorptionAmount() == 0f, "BLOOD: absorption must start at zero");
                GuardianTraits.onHit(g, level, person, false);
                expect(g.getAbsorptionAmount() > 0f, "BLOOD: a hit of its own fed no shield");
                for (int i = 0; i < 40; i++) GuardianTraits.onHit(g, level, person, false);
                expect(g.getAbsorptionAmount() <= g.getMaxHealth() * 0.10f + 0.01f, "BLOOD: the shield passed its ceiling (" + g.getAbsorptionAmount() + ")");
                expect(g.getHealth() <= g.getMaxHealth(), "BLOOD: it must never be healed");
            }
            case SPATIAL -> {
                stand(person, g, lane, 8.0);
                g.setTarget(person);
                Vec3 before = g.position();
                GuardianTraits.tick(g, level, st, trait, false);
                double moved = g.position().distanceTo(before);
                expect(moved > 3.0, "SPATIAL: it did not blink (moved " + moved + ")");
                expect(g.distanceToSqr(person.getX(), person.getY(), person.getZ()) < 16.0, "SPATIAL: it did not land next to its target");
                expect(st.readyAt - level.getGameTime() >= GuardianScaling.BLINK_MIN_COOLDOWN, "SPATIAL: blinks too often (cooldown " + (st.readyAt - level.getGameTime()) + ")");
                g.setTarget(null);
            }
            case FLAME -> {
                for (int i = 0; i < 3; i++) g.tick();
                stand(person, g, lane, 0.0);
                GuardianTraits.tick(g, level, st, trait, false);
                expect(st.trail.size() >= 1, "FLAME: no fire cell where it stands");
                expect(person.getRemainingFireTicks() > 0, "FLAME: a person standing in its trail is not set alight");
                expect(g.fireImmune(), "FLAME: the flame Guardian must not burn");
            }
            case FROST -> {
                stand(person, g, lane, 5.0);
                GuardianTraits.tick(g, level, st, trait, false);
                expect(person.hasEffect(MobEffects.MOVEMENT_SLOWDOWN), "FROST: no slowing pulse");
                expect(person.getTicksFrozen() > 0, "FROST: no frost on the person");
                stand(person, g, lane, 9.5);
                GuardianTraits.tick(g, level, new GuardianTraits.State(), trait, false);
                expect(!person.hasEffect(MobEffects.MOVEMENT_SLOWDOWN), "FROST: the aura ignores its range");
            }
            case VERDANT -> {
                stand(person, g, lane, 6.0);
                expect(g.hasLineOfSight(person), "VERDANT: the test lane has no line of sight (the arena's floor is not clear)");
                BalanceLaw.beginControl(g);                                            // the shared control lock is taken: no root may start
                GuardianTraits.tick(g, level, st, trait, false);
                expect(!person.hasEffect(MobEffects.MOVEMENT_SLOWDOWN), "VERDANT: it rooted a person while the shared control lock was held");
                g.getPersistentData().remove("nusmp_hc_until");                        // the lock is released: now it may
                GuardianTraits.tick(g, level, new GuardianTraits.State(), trait, false);
                MobEffectInstance root = person.getEffect(MobEffects.MOVEMENT_SLOWDOWN);
                expect(root != null && root.getAmplifier() == 9, "VERDANT: no root");
                expect(root.getDuration() <= GuardianScaling.ROOT_MAX_TICKS, "VERDANT: a root longer than one second: " + root.getDuration());
            }
            case STORM -> {
                stand(person, g, lane, 5.0);
                GuardianTraits.onSlam(g, level, false);                                // the chain after a Ground Slam runs against a person without error
                GuardianTraits.onSlam(g, level, true);
                expect(person.isAlive(), "STORM: the stand-in died (it is invulnerable)");
            }
            case SHADOW -> {
                stand(person, g, lane, 8.0);
                GuardianTraits.tick(g, level, new GuardianTraits.State(), trait, false);
                expect(!person.hasEffect(MobEffects.BLINDNESS), "SHADOW: it blinded a person 8 blocks away");
                stand(person, g, lane, 4.0);
                GuardianTraits.tick(g, level, st, trait, false);
                MobEffectInstance blind = person.getEffect(MobEffects.BLINDNESS);
                expect(blind != null, "SHADOW: no darkness pulse at 4 blocks");
                expect(blind.getDuration() <= GuardianScaling.SHADOW_MAX_TICKS, "SHADOW: blindness longer than two seconds: " + blind.getDuration());
            }
            case ASTRAL -> {
                stand(person, g, lane, 6.0);
                g.setTarget(person);
                GuardianTraits.tick(g, level, st, trait, false);
                int count = GuardianScaling.spec(Trait.ASTRAL, false).count();
                expect(st.stars.size() == count, "ASTRAL: " + st.stars.size() + " stars scheduled, expected " + count);
                for (double[] star : st.stars) star[3] = level.getGameTime() - 1;     // let them all land now
                GuardianTraits.tick(g, level, st, trait, false);
                expect(st.stars.isEmpty(), "ASTRAL: the stars did not land");
                g.setTarget(null);
            }
        }
        done.add(trait.name().toLowerCase(Locale.ROOT));
    }

    // ================================================================ guard.core
    private static Result core(MinecraftServer server) {
        World w = world(server);
        Sector s = w.sector();
        ServerLevel level = w.level();
        BlockPos pos = altarPos(w);
        GuardianAltarBlockEntity altar = altarAt(w, pos);
        var access = level.registryAccess();
        CompoundTag snapshot = altar.saveWithoutMetadata(access);
        Sector.State stateBefore = s.state;
        int levelBefore = w.data().expansionLevel;
        Set<UUID> existing = new HashSet<>();
        for (ItemEntity old : coresNear(level, pos, s.id)) existing.add(old.getUUID());   // cores that were here before are not ours: never touched
        LabyrinthGuardianEntity guardian = null;
        try {
            CompoundTag fresh = new CompoundTag();
            fresh.putString("state", "IDLE");
            altar.loadCustomOnly(fresh, access);                                       // a pristine, waiting altar
            guardian = altar.summonNow(level);
            expect(guardian != null, "the altar would not call its Guardian (state " + altar.state() + ")");
            expect(altar.state() == AltarRules.State.ACTIVE, "the altar is not ACTIVE after calling the Guardian: " + altar.state());
            expect(pos.equals(guardian.anchor()) && guardian.sectorId() == s.id, "the Guardian is not bound to this altar and sector");
            expect(newCores(level, pos, s.id, existing).isEmpty(), "a core appeared before the Guardian died");
            guardian.removeTag(LabyrinthGuardianEntity.SECTOR_TAG);                    // the Metal Vessel and the gear drops of the other modules hang on this tag: a test must not make loot
            guardian.die(level.damageSources().genericKill());                         // the death event: the same method the game calls
            altar.pollNow(level);
            expect(altar.state() == AltarRules.State.DONE, "the altar is not DONE after the Guardian's death: " + altar.state());
            List<ItemEntity> cores = newCores(level, pos, s.id, existing);
            expect(cores.size() == 1, "exactly one new Mana Core must exist after the death, found " + cores.size());
            ItemEntity core = cores.get(0);
            SectorCore data = ManaCoreItem.coreOf(core.getItem());
            expect(data != null && data.sector() == s.id && data.theme().equals(s.theme.id()), "the core is not bound to sector " + s.id + " / " + s.theme.id() + ": " + data);
            expect(core.isInvulnerable() && core.hasGlowingTag(), "the core is not indestructible and glowing");
            expect(stateBefore != Sector.State.ACTIVE || s.state == Sector.State.GUARDIAN_DEAD, "the sector did not move to GUARDIAN_DEAD (it is " + s.state + ")");
            guardian.die(level.damageSources().genericKill());                         // a second death (an event delivered twice, a retry)
            altar.pollNow(level);
            expect(newCores(level, pos, s.id, existing).size() == 1, "a second death produced a second Mana Core");
            return Result.ok("a confirmed death made exactly one core of sector " + s.id + " (" + s.theme.id() + "), indestructible and glowing; a second death made none; sector "
                    + stateBefore + " -> " + s.state + " -> restored");
        } finally {
            if (guardian != null) guardian.discard();
            for (ItemEntity c : newCores(level, pos, s.id, existing)) c.discard();
            altar.loadCustomOnly(snapshot, access);
            s.state = stateBefore;
            w.data().expansionLevel = levelBefore;
            w.data().setDirty();
        }
    }

    /** The cores of the sector near the altar that were not there when the test began. */
    private static List<ItemEntity> newCores(ServerLevel level, BlockPos pos, int sectorId, Set<UUID> existing) {
        List<ItemEntity> out = new ArrayList<>();
        for (ItemEntity c : coresNear(level, pos, sectorId)) if (!existing.contains(c.getUUID())) out.add(c);
        return out;
    }

    // ================================================================ the door rig (guard.gatekeeper, guard.idempotent)
    /** The Expander replaced for the length of a test: it only records who it was asked to grow from, so no real sector is ever generated. */
    private static final class Spy implements Expander {
        Expander real;
        final List<Integer> asked = new ArrayList<>();

        @Override public boolean requestFirst(MinecraftServer server) { return false; }

        @Override public boolean requestNext(ServerLevel level, Sector from) { asked.add(from.id); return false; }

        @Override public float progress() { return real == null ? -1f : real.progress(); }
    }

    /** Sector 0's door, closed, its sector as if the Guardian had just fallen, the Expander a spy; {@link #close} puts everything back. */
    private static final class Rig implements AutoCloseable {
        final World w;
        final BlockPos door;
        final Spy spy = new Spy();
        private final Expander real = MegaDungeon.expander();
        private final Sector.State stateBefore;
        private final int levelBefore;
        private final boolean openBefore;
        private final Dummy person;

        Rig(MinecraftServer server) {
            w = world(server);
            door = doorOf(w);
            stateBefore = w.sector().state;
            levelBefore = w.data().expansionLevel;
            openBefore = w.level().getBlockState(door).getValue(GatekeeperDoorBlock.OPEN);
            person = new Dummy(w.level(), "guard_door_tester");
            person.setPos(door.getX() + 0.5, door.getY(), door.getZ() + 2.5);
            spy.real = real;
            try {
                setSlab(w.level(), door, false);
                w.sector().state = Sector.State.GUARDIAN_DEAD;
                MegaDungeon.setExpander(spy);
            } catch (RuntimeException e) {
                close();                                                               // the constructor failed halfway: put back whatever was changed
                throw e;
            }
        }

        Player player() { return person; }

        ItemInteractionResult click(ItemStack stack) {
            BlockState st = w.level().getBlockState(door);
            return st.useItemOn(stack, w.level(), person, InteractionHand.MAIN_HAND, new BlockHitResult(Vec3.atCenterOf(door), Direction.SOUTH, door, false));
        }

        boolean closed() { return openBlocks(w.level(), door) == 0; }

        @Override
        public void close() {
            MegaDungeon.setExpander(real);
            w.sector().state = stateBefore;
            w.data().expansionLevel = levelBefore;
            w.data().setDirty();
            setSlab(w.level(), door, openBefore);
        }
    }

    // ================================================================ guard.gatekeeper
    private static Result gatekeeper(MinecraftServer server) {
        try (Rig r = new Rig(server)) {
            Sector s = r.w.sector();
            int slabSize = slab(r.w.level(), r.door).size();
            expect(slabSize == 24, "the door slab must be 24 blocks, found " + slabSize);
            expect(r.closed(), "the door could not be closed for the test");
            // without a core the door stays shut: an empty hand, a click that asks what the door wants, the Shadow Key, a blank core, another sector's core
            r.click(ItemStack.EMPTY);
            r.w.level().getBlockState(r.door).useWithoutItem(r.w.level(), r.player(), new BlockHitResult(Vec3.atCenterOf(r.door), Direction.SOUTH, r.door, false));
            expect(r.closed(), "an empty hand opened the door");
            ItemStack key = new ItemStack(SealRegistry.SHADOW_KEY.get());
            expect(r.click(key) == ItemInteractionResult.CONSUME && r.closed() && key.getCount() == 1, "the Shadow Key opened the sector door or was spent");
            ItemStack blank = new ItemStack(GuardRegistry.MANA_CORE.get());
            expect(r.click(blank) == ItemInteractionResult.CONSUME && r.closed() && blank.getCount() == 1, "a blank core opened the door or was spent");
            ItemStack other = ManaCoreItem.forSector(s.id + 1, s.theme);
            expect(r.click(other) == ItemInteractionResult.CONSUME && r.closed() && other.getCount() == 1, "a core of sector " + (s.id + 1) + " opened sector " + s.id + "'s door or was spent");
            expect(r.spy.asked.isEmpty() && s.state == Sector.State.GUARDIAN_DEAD, "a refused click unsealed the sector or asked for expansion");
            // with its own core the door opens, the core is spent, the sector is unsealed and the Expander is asked for the next sector
            ItemStack mine = ManaCoreItem.forSector(s.id, s.theme);
            expect(r.click(mine) == ItemInteractionResult.CONSUME, "the sector's own core was refused");
            int open = openBlocks(r.w.level(), r.door);
            expect(open == 24, "only " + open + " of the 24 slab blocks opened");
            expect(mine.isEmpty(), "the core was not spent");
            expect(s.state == Sector.State.UNSEALED, "the sector is " + s.state + ", not UNSEALED");
            expect(r.w.data().expansionLevel >= s.id + 1, "the expansion level did not rise");
            boolean expansion = MegaConfig.get(MegaConfig.EXPANSION);
            expect(r.spy.asked.size() <= 1 && (expansion || r.spy.asked.isEmpty()) && (r.spy.asked.isEmpty() || r.spy.asked.get(0) == s.id),
                    "the Expander was asked " + r.spy.asked + " (at most once, for sector " + s.id + ", and never with mega.expansion off; it is " + expansion + ")");
            return Result.ok("refused: empty hand, Shadow Key, blank core, core of sector " + (s.id + 1) + "; the core of sector " + s.id + " opened all 24 blocks, was spent, sector -> UNSEALED, Expander.requestNext was called "
                    + r.spy.asked.size() + " time(s) inside the click (the test's spy records it: no real sector generated; 0 when the dungeon defers growth to the Crucible or mega.expansion is off)");
        }
    }

    // ================================================================ guard.idempotent
    private static Result idempotent(MinecraftServer server) {
        try (Rig r = new Rig(server)) {
            Sector s = r.w.sector();
            ItemStack first = ManaCoreItem.forSector(s.id, s.theme);
            r.click(first);
            int want = r.spy.asked.size();                                                // what the dungeon does on the first unseal (it asks at most once, or defers); nothing may add to it
            expect(openBlocks(r.w.level(), r.door) == 24 && want <= 1, "the first core did not open the door, or asked more than once (asked " + r.spy.asked + ")");
            // a second core on the now open door: nothing happens, nothing is spent
            ItemStack second = ManaCoreItem.forSector(s.id, s.theme);
            ItemInteractionResult again = r.click(second);
            expect(again == ItemInteractionResult.PASS_TO_DEFAULT_BLOCK_INTERACTION && second.getCount() == 1, "a core used on an open door did something (" + again + ", count " + second.getCount() + ")");
            expect(r.spy.asked.size() == want, "using a core on an open door asked for expansion again (" + r.spy.asked + ")");
            // the door is closed again (a regenerated sector does that) and a second core opens it, but the sector is NOT unsealed twice
            setSlab(r.w.level(), r.door, false);
            ItemStack third = ManaCoreItem.forSector(s.id, s.theme);
            r.click(third);
            expect(openBlocks(r.w.level(), r.door) == 24 && third.isEmpty(), "a core did not open the re-closed door");
            expect(r.spy.asked.size() == want, "a second core generated a second time (asked " + r.spy.asked + ")");
            expect(!MegaDungeon.unseal(r.w.level(), s.id), "MegaDungeon.unseal reported a second first-time unseal");
            expect(r.spy.asked.size() == want, "a repeated unseal asked for expansion again (" + r.spy.asked + ")");
            return Result.ok("three clicks (open door, re-closed door) and a direct unseal asked the Expander " + r.spy.asked.size() + " time(s) in all, the same as the first click alone");
        }
    }

