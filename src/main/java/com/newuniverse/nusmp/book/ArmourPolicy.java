package com.newuniverse.nusmp.book;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.EnumMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * 1.99.0 armour policy: which magics have an armour at all, and what puts it on. Pure (no game classes), data driven ({@code data/nusmp/armour_policy.json}, generated by
 * {@code tools/gen_armour_policy.py} from the table that docs/rebuild/armour_policy.md prints), and unit tested.
 *
 * <p>Why it exists. In the 1.93.0 rebuild every page of 41 magics put a temporary armour on the caster (the render layer {@code Aura}). In the anime only a few magics have an armour
 * or a transformation (Spirit Dive, the Valkyrie Dress, Luck's lightning armour, Yami's Dark Cloaked, the Silver Guardian, Asta's Devil Union ...), and nothing equips by merely casting a
 * bolt. So every magic is classified:
 * <ul>
 *   <li>{@link Kind#NONE}: no armour exists. A cast never creates the armour layer; the magic keeps its effects, props and summons (and, where the armour used to carry its look,
 *       a light shimmer, see {@link Entry#shimmer}). Its painter, models and textures stay on disk and in the aura registry, so old saves and tests still resolve.</li>
 *   <li>{@link Kind#TOGGLE}: an armour exists and is put on and taken off ONLY by its own explicit page ({@link Entry#armourPages}): the page forges it in, it stays until the
 *       same page is cast again, the mana runs out, the wearer is knocked out or dies. Every other page leaves it alone.</li>
 *   <li>{@link Kind#FORM}: a canon transformation with its own gauge (Spirit Dive: ambient mana in, mana upkeep out; Devil Union / Unite). It is entered by the form page
 *       ({@link Entry#formPages}) and ends when the gauge runs dry or the form is left. A FORM can also have a plain armour page (Flame Armour, Valkyrie Dress).</li>
 * </ul>
 * The decision "what may a finished cast do to the armour layer" is {@link #forCast}: it answers {@link Instruction#NONE} for every page that is not an armour or form page, and
 * that single answer is what the game consults after each cast (book.ArmourCast).
 */
public final class ArmourPolicy {
    public enum Kind { NONE, TOGGLE, FORM }

    /** What a finished cast of a page asks of the armour layer. */
    public enum Instruction { NONE, ARMOUR, FORM }

    /**
     * What an armour gives while it is on. {@code cut}: share of every blow removed; {@code attack} / {@code speed}: multiplier added to the base attribute; {@code knockback}:
     * knockback resistance; {@code ward}: a damage family the armour is immune to ("fire", "lightning", "" = none); {@code senses}: hidden night vision; {@code upkeep}: share of
     * the maximum magicule pool paid every second; {@code absorb}: share of the pool taken back every second from the ambient mana (forms); {@code hpUpkeep}: hit points the
     * wearer pays every second (never below six, never in creative; the Silver Guardian's poison).
     */
    public record Bonus(float cut, float attack, float speed, float knockback, String ward, boolean senses, double upkeep, double absorb, double hpUpkeep) {
        public static final Bonus NONE = new Bonus(0f, 0f, 0f, 0f, "", false, 0.0, 0.0, 0.0);
        public boolean isEmpty() { return equals(NONE); }
    }

    /**
     * One magic's entry.
     *
     * @param formAura    the FORM is drawn with the same render layer as the armour (Earth's Gnome Plate); false: the form's look is an older overlay (blackclover.ModeArmor) and the layer is not used
     * @param armourPages page id -> style: the pages that put the armour on (and, cast again while it is worn, take it off)
     * @param formPages   page ids that start the magic's FORM (Spirit Dive)
     * @param externalPages page ids of forms that are drawn and tracked by an older system (blackclover.ModeArmor, shadow.UniteState): listed for the record, the policy engine does nothing for them
     * @param styleBy     "none", "sneak" (style 1 while sneaking) or "mastery" (style 1 from three quarters mastery or in a devil state): how the page's base style is raised
     * @param legacyAuras the render layers (aura.Aura names) this magic's casts used to put on automatically before 1.99.0; the policy maps them back to the magic
     * @param shimmer     for a NONE magic that lost its armour: the VfxShape name of the light effect that carries its look now ("" = none)
     * @param newPages    page ids this release appended to the magic's book (empty: every armour page is an old page)
     */
    public record Entry(String magic, Kind kind, String name, String aura, boolean formAura, Map<String, Integer> armourPages, List<String> formPages, List<String> externalPages,
                        String styleBy, Bonus bonus, Bonus formBonus, List<String> legacyAuras, String shimmer, List<String> newPages, String canon) {
        public boolean armoured() { return kind != Kind.NONE; }
        /** True when the policy engine (ArmourState) owns the armour layer of this magic. */
        public boolean engine() { return kind != Kind.NONE && (!aura.isEmpty() || !formPages.isEmpty()); }
    }

    private final Map<String, Entry> entries;
    private final Map<String, String> auraOwner;
    private final List<String> problems;

    private ArmourPolicy(Map<String, Entry> entries, List<String> problems) {
        this.entries = Collections.unmodifiableMap(entries);
        this.problems = Collections.unmodifiableList(problems);
        Map<String, String> owner = new LinkedHashMap<>();
        for (Entry e : entries.values()) {
            if (!e.aura().isEmpty()) owner.putIfAbsent(e.aura(), e.magic());
            for (String a : e.legacyAuras()) owner.putIfAbsent(a, e.magic());
        }
        this.auraOwner = Collections.unmodifiableMap(owner);
    }

    // ------------------------------------------------------------------ the shipped table
    public static final String RESOURCE = "/data/nusmp/armour_policy.json";

    private static final class Holder { static final ArmourPolicy TABLE = load(); }

    /** The shipped table. A missing or broken file gives the EMPTY policy: no magic has an armour (and nothing is put on by a cast), which is the safe answer. */
    public static ArmourPolicy get() { return Holder.TABLE; }

    private static ArmourPolicy load() {
        try (InputStream in = ArmourPolicy.class.getResourceAsStream(RESOURCE)) {
            if (in == null) return empty("missing resource " + RESOURCE);
            try (Reader r = new InputStreamReader(in, StandardCharsets.UTF_8)) {
                StringBuilder sb = new StringBuilder();
                char[] buf = new char[8192];
                int n;
                while ((n = r.read(buf)) > 0) sb.append(buf, 0, n);
                return parse(sb.toString());
            }
        } catch (IOException | RuntimeException e) {
            return empty("unreadable " + RESOURCE + ": " + e);
        }
    }

    private static ArmourPolicy empty(String problem) {
        List<String> p = new ArrayList<>();
        p.add(problem);
        return new ArmourPolicy(new LinkedHashMap<>(), p);
    }

    // ------------------------------------------------------------------ parsing (public: the unit tests read the shipped file through it)
    public static ArmourPolicy parse(String json) {
        List<String> problems = new ArrayList<>();
        Map<String, Entry> out = new LinkedHashMap<>();
        JsonObject root = JsonParser.parseString(json).getAsJsonObject();
        JsonObject defaults = obj(root, "defaults");
        Bonus defToggle = bonus(obj(defaults, "toggle_bonus"), Bonus.NONE);
        Bonus defForm = bonus(obj(defaults, "form_bonus"), Bonus.NONE);
        JsonObject magics = obj(root, "magics");
        for (Map.Entry<String, JsonElement> me : magics.entrySet()) {
            String key = me.getKey();
            if (!me.getValue().isJsonObject()) { problems.add(key + ": not an object"); continue; }
            JsonObject o = me.getValue().getAsJsonObject();
            Kind kind;
            try { kind = Kind.valueOf(str(o, "kind", "NONE").toUpperCase(Locale.ROOT)); }
            catch (IllegalArgumentException ex) { problems.add(key + ": unknown kind '" + str(o, "kind", "") + "'"); continue; }
            Map<String, Integer> pages = new LinkedHashMap<>();
            JsonObject ap = obj(o, "armour_pages");
            for (Map.Entry<String, JsonElement> pe : ap.entrySet()) pages.put(pe.getKey(), pe.getValue().getAsInt());
            Bonus bonus = o.has("bonus") ? bonus(obj(o, "bonus"), defToggle) : (kind == Kind.NONE ? Bonus.NONE : defToggle);
            Bonus formBonus = o.has("form_bonus") ? bonus(obj(o, "form_bonus"), defForm) : (o.has("form_pages") ? defForm : Bonus.NONE);
            Entry e = new Entry(key, kind, str(o, "name", ""), str(o, "aura", ""), o.has("form_aura") && o.get("form_aura").getAsBoolean(), Collections.unmodifiableMap(pages),
                    strings(o, "form_pages"), strings(o, "external_pages"), str(o, "style_by", "none"), bonus, formBonus, strings(o, "legacy_auras"), str(o, "shimmer", ""),
                    strings(o, "new_pages"), str(o, "canon", ""));
            if (out.put(key, e) != null) problems.add(key + ": listed twice");
            problems.addAll(check(e));
        }
        return new ArmourPolicy(out, problems);
    }

    /** What is wrong with one entry (empty = fine). */
    static List<String> check(Entry e) {
        List<String> p = new ArrayList<>();
        if (e.canon().isBlank()) p.add(e.magic() + ": no canon justification");
        switch (e.kind()) {
            case NONE -> {
                if (!e.armourPages().isEmpty() || !e.formPages().isEmpty() || !e.externalPages().isEmpty()) p.add(e.magic() + ": a NONE magic lists armour or form pages");
                if (!e.aura().isEmpty()) p.add(e.magic() + ": a NONE magic names a live armour layer");
            }
            case TOGGLE -> {
                if (e.armourPages().isEmpty()) p.add(e.magic() + ": TOGGLE without an armour page");
                if (e.aura().isEmpty()) p.add(e.magic() + ": TOGGLE without an armour layer");
                if (e.name().isBlank()) p.add(e.magic() + ": TOGGLE without an armour name");
            }
            case FORM -> {
                if (e.formPages().isEmpty() && e.externalPages().isEmpty()) p.add(e.magic() + ": FORM without a form page");
                if (e.name().isBlank()) p.add(e.magic() + ": FORM without a name");
            }
        }
        for (String id : e.armourPages().keySet()) if (e.formPages().contains(id)) p.add(e.magic() + ": page " + id + " is both an armour page and a form page");
        for (int s : e.armourPages().values()) if (s < 0 || s > 120) p.add(e.magic() + ": style " + s + " does not fit the aura payload");
        if (!List.of("none", "sneak", "mastery").contains(e.styleBy())) p.add(e.magic() + ": unknown style_by '" + e.styleBy() + "'");
        if (!e.shimmer().isEmpty() && e.kind() != Kind.NONE) p.add(e.magic() + ": only a NONE magic has a shimmer");
        return p;
    }

    private static JsonObject obj(JsonObject o, String k) { return o.has(k) && o.get(k).isJsonObject() ? o.getAsJsonObject(k) : new JsonObject(); }

    private static String str(JsonObject o, String k, String d) { return o.has(k) && o.get(k).isJsonPrimitive() ? o.get(k).getAsString() : d; }

    private static List<String> strings(JsonObject o, String k) {
        List<String> l = new ArrayList<>();
        if (o.has(k) && o.get(k).isJsonArray()) for (JsonElement x : (JsonArray) o.get(k)) l.add(x.getAsString());
        return Collections.unmodifiableList(l);
    }

    private static float f(JsonObject o, String k, float d) { return o.has(k) ? o.get(k).getAsFloat() : d; }

    private static double dd(JsonObject o, String k, double d) { return o.has(k) ? o.get(k).getAsDouble() : d; }

    private static Bonus bonus(JsonObject o, Bonus d) {
        return new Bonus(f(o, "cut", d.cut()), f(o, "attack", d.attack()), f(o, "speed", d.speed()), f(o, "knockback", d.knockback()), str(o, "ward", d.ward()),
                o.has("senses") ? o.get("senses").getAsBoolean() : d.senses(), dd(o, "upkeep", d.upkeep()), dd(o, "absorb", d.absorb()), dd(o, "hp_upkeep", d.hpUpkeep()));
    }

    // ------------------------------------------------------------------ queries
    /** The entry of a magic (by its MagicType name), or null when the table does not know it. */
    public Entry entry(String magic) { return magic == null ? null : entries.get(magic.toUpperCase(Locale.ROOT)); }

    public Kind kind(String magic) {
        Entry e = entry(magic);
        return e == null ? Kind.NONE : e.kind();
    }

    public boolean armoured(String magic) { return kind(magic) != Kind.NONE; }

    public Map<String, Entry> entries() { return entries; }

    public List<String> problems() { return problems; }

    public int count(Kind k) {
        int n = 0;
        for (Entry e : entries.values()) if (e.kind() == k) n++;
        return n;
    }

    /** The magic whose armour layer (or former auto-armour layer) is this aura name, or null. */
    public String magicOfAura(String auraName) { return auraName == null ? null : auraOwner.get(auraName); }

    /**
     * THE decision: what a finished cast of {@code pageId} of {@code magic} may do to the armour layer. NONE for every page that is not an armour or form page (always, for a NONE
     * magic); ARMOUR for a page of {@link Entry#armourPages}; FORM for a page of {@link Entry#formPages}.
     */
    public Instruction forCast(String magic, String pageId) {
        Entry e = entry(magic);
        if (e == null || e.kind() == Kind.NONE || pageId == null) return Instruction.NONE;
        if (e.armourPages().containsKey(pageId)) return Instruction.ARMOUR;
        if (e.formPages().contains(pageId)) return Instruction.FORM;
        return Instruction.NONE;
    }

    /** The style the armour page puts on, from its table style and the caster's state (see {@link Entry#styleBy}). */
    public int styleFor(String magic, String pageId, boolean sneaking, boolean mastered) {
        Entry e = entry(magic);
        if (e == null) return 0;
        int base = e.armourPages().getOrDefault(pageId, 0);
        return ArmourRules.style(e.styleBy(), base, sneaking, mastered);
    }

    /** Counts per kind, for the report and the self-test. */
    public Map<Kind, Integer> counts() {
        EnumMap<Kind, Integer> m = new EnumMap<>(Kind.class);
        for (Kind k : Kind.values()) m.put(k, count(k));
        return m;
    }

    /** Static shorthand of {@code get().forCast(...)}. */
    public static Instruction instruction(String magic, String pageId) { return get().forCast(magic, pageId); }
}
