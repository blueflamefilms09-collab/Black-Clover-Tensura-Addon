    /** The lines of a devil (four), or an empty array. */
    public static String[] lines(String devilId) {
        if (devilId != null) for (String[] row : TEXT) if (row[0].equals(devilId)) return java.util.Arrays.copyOfRange(row, 1, row.length);
        return new String[0];
    }

    /** One line of a devil, or "" when there is none. */
    public static String line(String devilId, int i) {
        String[] l = lines(devilId);
        return i >= 0 && i < l.length ? l[i] : "";
    }

    /** The language key of a line. */
    public static String key(String devilId, int i) { return "anime_multiverse.devil.npc.line." + devilId + "." + i; }
