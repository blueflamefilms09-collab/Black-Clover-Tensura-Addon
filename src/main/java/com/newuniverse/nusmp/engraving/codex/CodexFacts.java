package com.newuniverse.nusmp.engraving.codex;

import com.newuniverse.nusmp.franchise.FranchiseData;
import com.newuniverse.nusmp.franchise.FranchiseRules;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;

/**
 * Why: the Engravement Codex says, in plain words, the cooldowns, windows, durations, stack limits and caps of every franchise engraving. They are never typed here: every number is read
 * from the engraving's own effects ({@code data/nusmp/franchise/engravings.json}) or from the constants of {@link FranchiseRules} (the caps the game really applies), so when a number is
 * retuned the Codex follows by itself. Pure (no Minecraft types), unit tested.
 */
public final class CodexFacts {
    private CodexFacts() {}

    /** Effect kinds that add a share of the hit's damage (all together under {@link FranchiseRules#ATTACK_CAP}). */
    private static final Set<String> ATTACK = Set.of("hit_bonus", "anti_ward", "spell_power", "first_strike", "kill_stacks", "charge_hit", "counter", "blood_price", "combo");
    /** Effect kinds that take a share off the damage taken (all together under {@link FranchiseRules#GUARD_CAP}). */
    private static final Set<String> GUARD = Set.of("shield_guard", "ward");
    /** Effect kinds that roll a chance (never above {@link FranchiseRules#CHANCE_CAP}). */
    private static final Set<String> CHANCE = Set.of("dodge", "kill_ally", "debuff", "chance_roll");
    /** Effect kinds that heal (never above {@link FranchiseRules#HEAL_CAP} per proc). */
    private static final Set<String> HEAL = Set.of("kill_heal", "second_wind", "lifesteal");

    /** The scope in plain words: main hand only, either hand, or held / worn anywhere (in either hand, as armour or as a Curio). */
    public static String scopeWords(String scope) {
        return switch (scope == null ? "" : scope) {
            case "main" -> "Main hand only";
            case "held" -> "Either hand";
            case "any" -> "Held or worn anywhere";
            default -> "";
        };
    }

    /** The sentences the language text of a franchise engraving ends with (generated by tools/franchise/gen_engravings.py): the scope sentence and the caps sentence. */
    private static final String[] BOILERPLATE = {
            " Effects are capped; stronger items carry a higher level (+25% per level).",
            " Works while the item is in your main hand.", " Works while the item is in either hand.", " Works while the item is held, worn as armour or worn as a Curio."};

    /**
     * The text of an engraving as the book shows it: the generated closing sentences (where it works, "effects are capped") are dropped when the text ends with them, because the book
     * says the same in its scope line and its fact lines (with the live numbers). Any other text, such as another language's, is shown as it is.
     */
    public static String trimBoilerplate(String text) {
        String t = text == null ? "" : text;
        boolean again = true;
        while (again) {
            again = false;
            for (String b : BOILERPLATE) {
                if (t.endsWith(b) && t.length() > b.length() + 20) {
                    t = t.substring(0, t.length() - b.length());
                    again = true;
                }
            }
        }
        return t;
    }

    /** "5 s", "0.5 s", "1.5 s" for a number of ticks (20 ticks a second). */
    public static String seconds(double ticks) { return trim(ticks / 20.0) + " s"; }

    /** "12%", "1.2%", "0.4%" for a share (0.012 is 1.2%). */
    public static String percent(double share) {
        double v = share * 100.0;
        if (Math.abs(v - Math.round(v)) < 0.05) return Math.round(v) + "%";
        return String.format(Locale.ROOT, "%.1f%%", v);
    }

    /** A number without a useless ".0". */
    public static String trim(double v) {
        if (Math.abs(v - Math.rint(v)) < 1e-9) return Long.toString(Math.round(v));
        return String.format(Locale.ROOT, "%.1f", v);
    }

    private static String ordinal(int n) {
        int m100 = n % 100;
        if (m100 >= 11 && m100 <= 13) return n + "th";
        return switch (n % 10) {
            case 1 -> n + "st";
            case 2 -> n + "nd";
            case 3 -> n + "rd";
            default -> n + "th";
        };
    }

    /** The facts of one franchise engraving, in a stable order and without duplicates: cooldowns, windows, durations, limits, then the caps that apply to it. */
    public static List<String> of(FranchiseData.Engraving en) {
        Set<String> out = new LinkedHashSet<>();
        Set<String> caps = new LinkedHashSet<>();
        for (FranchiseData.Effect e : en.effects()) {
            String kind = e.kind();
            if (e.num().containsKey("cd")) out.add("Cooldown: " + seconds(e.d("cd", 0)));
            if (e.num().containsKey("window")) {
                String w = seconds(e.d("window", 0));
                out.add(switch (kind) {
                    case "spell_power" -> "The bonus counts for " + w + " after the cast";
                    case "first_strike" -> "Needs " + w + " without hitting that foe";
                    case "counter" -> "Your next hit within " + w + " after being hit";
                    case "combo" -> "Hits within " + w + " of each other keep the combo";
                    default -> "Window: " + w;
                });
            }
            if (e.num().containsKey("dur")) {
                String d = seconds(e.d("dur", 0));
                out.add(switch (kind) {
                    case "debuff" -> "The effect on the foe lasts " + d;
                    case "kill_haste" -> "Speed lasts " + d;
                    case "ally_regen" -> "Regeneration lasts " + seconds(FranchiseRules.regenDuration(e.i("dur", 0))) + " (never more than " + seconds(FranchiseRules.REGEN_DURATION_CAP) + ")";
                    default -> "Lasts " + d;
                });
            }
            if (e.num().containsKey("life")) out.add("The ally stays for " + seconds(e.d("life", 0)));
            if (e.num().containsKey("decay")) out.add("The stacks fade " + seconds(e.d("decay", 0)) + " after the last kill");
            if (e.num().containsKey("max")) out.add("Up to " + e.i("max", 0) + " stacks");
            if (e.num().containsKey("hits")) {
                out.add("Fires on every " + ordinal(e.i("hits", 1)) + " hit; the charge is forgotten after " + seconds(FranchiseRules.CHARGE_IDLE_TICKS) + " without a hit");
            }
            if (e.num().containsKey("interval")) out.add("Refreshed every " + seconds(e.d("interval", 0)));
            if (e.num().containsKey("radius")) out.add("Reaches " + e.i("radius", 0) + " blocks");
            if (e.num().containsKey("threshold")) out.add("Triggers at " + percent(e.d("threshold", 0)) + " health or less");
            if (e.num().containsKey("min_hp")) out.add("Never takes you below " + trim(e.d("min_hp", 0)) + " health");
            if (e.num().containsKey("cost")) out.add("Costs you " + trim(e.d("cost", 0)) + " health per hit");
            if (kind.equals("lifesteal") && e.num().containsKey("cap")) out.add("Heals at most " + trim(e.d("cap", 0)) + " per hit");
            if (kind.equals("spell_refund")) caps.add("Magicule back: max " + percent(FranchiseRules.REFUND_PER_MINUTE_CAP) + " of your maximum per minute");
            if (kind.equals("mana_trickle")) caps.add("One pulse returns at most " + percent(FranchiseRules.TRICKLE_CAP) + " of your maximum");
            if (ATTACK.contains(kind) || (kind.equals("chance_roll") && e.num().containsKey("bonus")))
                caps.add("All engraving damage bonuses together: max +" + percent(FranchiseRules.ATTACK_CAP) + " of the hit (half vs players)");
            if (GUARD.contains(kind)) caps.add("All engraving damage reductions together: max " + percent(FranchiseRules.GUARD_CAP));
            if (HEAL.contains(kind) || (kind.equals("chance_roll") && e.num().containsKey("heal"))) caps.add("A heal is never more than " + trim(FranchiseRules.HEAL_CAP) + " health");
            if (CHANCE.contains(kind)) caps.add("A chance never goes above " + percent(FranchiseRules.CHANCE_CAP));
        }
        List<String> all = new ArrayList<>(out);
        all.addAll(caps);
        all.add("Levels 1 to " + FranchiseRules.MAX_LEVEL + ": +" + percent(FranchiseRules.levelMult(2) - 1.0) + " per level; cooldowns and caps do not grow");
        return List.copyOf(all);
    }

    /** Is this fact one of the cap / limit lines (drawn in the tooltip's green) rather than a timing line? */
    public static boolean isCap(String fact) {
        return fact.startsWith("All engraving") || fact.startsWith("A heal is never") || fact.startsWith("A chance never") || fact.startsWith("Magicule back")
                || fact.startsWith("One pulse returns") || fact.startsWith("Levels ") || fact.startsWith("Highest level") || fact.startsWith("Heals at most")
                || fact.contains("never more than");
    }

    /** A short sentence for an engraving whose language text is missing (so the book is never empty): its effect kinds in words. */
    public static String fallbackText(FranchiseData.Engraving en) {
        List<String> kinds = new ArrayList<>();
        for (FranchiseData.Effect e : en.effects()) kinds.add(e.kind().replace('_', ' '));
        return "Effects: " + String.join(", ", kinds) + ". " + scopeWords(en.scope()) + ".";
    }
}
