package com.newuniverse.nusmp.skilltree.unique;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.newuniverse.nusmp.skilltree.rarity.BookRarity;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.regex.Pattern;

/**
 * Why: Tensura's skill list is a ManasCore REGISTRY, and a registry is frozen when the game starts: a unique skill cannot be registered later, when a datapack is read or a Skill Book is opened. So one
 * unique skill per book is registered at mod construction, and for that the code must know every book BEFORE any world exists, before the datapack route files are read (those are server data, loaded at world
 * load). The only list that is part of the jar's plain resources is {@code assets/nusmp/skill_books.json} (generated by {@code tools/lines/gen_book_index.py} from the very same route files and checked
 * against them by a unit test), so this class reads the ids, names, colours, descriptions and the names of the arts (the skill's modes) and passives from it. It is Minecraft-free (Gson only), so the parsing, the id
 * rules and the order are unit tested without a game, and it is the single place that turns a line id into the id of its skill ({@link #skillPath}), so the registry, the lang fragment, the icon generator
 * and the tests can never disagree about it. The order is the id order (a {@link TreeMap}), never the file order, so the registry order is the same on every machine and every build; both sides read the
 * same file, so a client can name a skill's modes without the server's data.
 */
public final class LineIndex {
    private LineIndex() {}

    /** The classpath location of the table (it is an asset, but a plain jar resource on both sides). */
    public static final String RESOURCE = "/assets/nusmp/skill_books.json";
    /** The namespace of every line id: {@code nusmp:oath_of_the_heavy_armor}. */
    public static final String NAMESPACE = "nusmp";
    private static final Pattern SNAKE = Pattern.compile("[a-z0-9_]{1,40}");

    /**
     * One book as the registry needs it: {@code bare} is the file stem ({@code lady_luck}), {@code routeId} the route id ({@code nusmp:lady_luck}), {@code arts} the names of the skill's modes in route-file order,
     * {@code passives} the names of the passives and stat bonuses that work while the skill is on. 3.26.0: {@code rarity} is the book's rarity (the table's {@code rarity} field; a table without it reads as common) and
     * {@code theme} its background theme (one of the 15 backgrounds, "" when the table has none), which the themed Guardian drop matches against the dungeon sector's theme.
     */
    public record Line(String bare, String routeId, String name, int color, String franchise, String book, String bookName, String desc, String lore,
                       List<String> arts, List<String> passives, BookRarity rarity, String theme) {
        public Line {
            arts = List.copyOf(arts);
            passives = List.copyOf(passives);
            rarity = rarity == null ? BookRarity.COMMON : rarity;
            theme = theme == null ? "" : theme;
        }

        /** The eleven-argument form of 3.25 (no rarity, no theme: common); kept so old callers and tests compile. */
        public Line(String bare, String routeId, String name, int color, String franchise, String book, String bookName, String desc, String lore,
                    List<String> arts, List<String> passives) {
            this(bare, routeId, name, color, franchise, book, bookName, desc, lore, arts, passives, BookRarity.COMMON, "");
        }

        /** The five-argument form of the stand-in era; kept so old callers compile. */
        public Line(String bare, String routeId, String name, int color, String franchise) {
            this(bare, routeId, name, color, franchise, "nusmp:" + bare + "_book", name, "", "", List.of(), List.of());
        }

        /** The path of the skill's id ({@code line_lady_luck}). */
        public String skillPath() { return LineIndex.skillPath(bare); }
    }

    /** The path part of a skill's registry id: {@code line_<bare>}. The prefix keeps it clear of every other skill id of the mod. */
    public static String skillPath(String bare) { return "line_" + bare; }

    /** The route id of a bare line id ({@code nusmp:<bare>}); an id that already has a namespace is returned unchanged. */
    public static String routeId(String bareOrRouteId) { return bareOrRouteId.indexOf(':') >= 0 ? bareOrRouteId : NAMESPACE + ":" + bareOrRouteId; }

    /** The bare id of a route id ({@code nusmp:x} to {@code x}); a bare id is returned unchanged. */
    public static String bare(String routeId) {
        int i = routeId.indexOf(':');
        return i < 0 ? routeId : routeId.substring(i + 1);
    }

    /** True for an id the registry can use as the end of a skill path. */
    public static boolean validBare(String s) { return s != null && SNAKE.matcher(s).matches(); }

    /**
     * Parses the table. Tolerant by design (a bad entry is skipped, never an error, so one typo cannot stop the game from starting): an entry whose key is not a snake-case id, or that is not an
     * object, is dropped. The result is in id order and immutable.
     */
    public static List<Line> parse(JsonObject root) {
        Map<String, Line> sorted = new TreeMap<>();
        if (root != null && root.has("lines") && root.get("lines").isJsonObject()) {
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("lines").entrySet()) {
                if (!validBare(e.getKey()) || !e.getValue().isJsonObject()) continue;
                JsonObject o = e.getValue().getAsJsonObject();
                String name = str(o, "name");
                String book = str(o, "book");
                String bookName = str(o, "book_name");
                String shownName = name.isEmpty() ? e.getKey() : name;
                sorted.put(e.getKey(), new Line(e.getKey(), routeId(e.getKey()), shownName, color(str(o, "color")), str(o, "franchise"),
                        book.isEmpty() ? "nusmp:" + e.getKey() + "_book" : book, bookName.isEmpty() ? shownName : bookName, str(o, "desc"), str(o, "book_lore"),
                        strings(o, "arts"), strings(o, "passives"), BookRarity.fromId(str(o, "rarity")), str(o, "theme")));
            }
        }
        return Collections.unmodifiableList(new ArrayList<>(sorted.values()));
    }

    private static volatile String problem = "";

    /** The reason the last {@link #load} found nothing (empty when it worked), for the caller to log: this class has no logger so it stays free of Minecraft types. */
    public static String problem() { return problem; }

    /** Reads the table from the jar. An unreadable table answers an empty list and sets {@link #problem} (the game still starts; the in-game self-test then reports it). */
    public static List<Line> load() {
        try (InputStream in = LineIndex.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                problem = RESOURCE + " is missing from the jar, so no unique skill book can be registered";
                return List.of();
            }
            List<Line> lines = parse(JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject());
            problem = lines.isEmpty() ? RESOURCE + " lists no book" : "";
            return lines;
        } catch (IOException | RuntimeException e) {
            problem = "could not read " + RESOURCE + ": " + e;
            return List.of();
        }
    }

    private static volatile List<Line> shipped;

    /** The table as shipped in the jar, read once and kept (the registry reads the same one). */
    public static List<Line> shipped() {
        List<Line> s = shipped;
        if (s == null) {
            s = load();
            shipped = s;
        }
        return s;
    }

    /** True when the shipped table has a book with this bare id (or route id): the loot and the shop only hand out books a skill exists for. */
    public static boolean known(String bareOrRouteId) { return byBare(shipped(), bareOrRouteId) != null; }

    /** The line of a book id ({@code nusmp:lady_luck_book}) in a parsed table, or null. */
    public static Line byBook(List<Line> lines, String bookId) {
        if (bookId == null || bookId.isEmpty()) return null;
        for (Line l : lines) if (l.book().equals(bookId)) return l;
        return null;
    }

    /** The line with this bare id (or route id) in a parsed table, or null. */
    public static Line byBare(List<Line> lines, String bareOrRouteId) {
        if (bareOrRouteId == null) return null;
        String b = bare(bareOrRouteId);
        for (Line l : lines) if (l.bare().equals(b)) return l;
        return null;
    }

    private static String str(JsonObject o, String key) { return o.has(key) && o.get(key).isJsonPrimitive() ? o.get(key).getAsString() : ""; }

    private static List<String> strings(JsonObject o, String key) {
        List<String> out = new ArrayList<>();
        if (o.has(key) && o.get(key).isJsonArray()) {
            JsonArray a = o.getAsJsonArray(key);
            for (JsonElement e : a) if (e.isJsonPrimitive()) out.add(e.getAsString());
        }
        return out;
    }

    /** {@code #RRGGBB} to 0xRRGGBB; anything else is white. */
    static int color(String s) {
        String h = s.startsWith("#") ? s.substring(1) : s;
        if (h.length() != 6) return 0xFFFFFF;
        try {
            return Integer.parseInt(h, 16) & 0xFFFFFF;
        } catch (NumberFormatException e) {
            return 0xFFFFFF;
        }
    }
}
