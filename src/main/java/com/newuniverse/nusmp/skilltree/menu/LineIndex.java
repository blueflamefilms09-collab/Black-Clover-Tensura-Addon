package com.newuniverse.nusmp.skilltree.menu;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.regex.Pattern;

/**
 * Why: Tensura's skill list is a ManasCore REGISTRY, and a registry is frozen when the game starts: a Unique Skill Line cannot be registered later, when a datapack is read or a Skill Book is
 * opened. So the menu integration registers one stand-in skill per line at mod construction, and for that it must know the line ids BEFORE any world and before the datapack route files exist
 * (the route files are server data, read at world load; the registry has to be filled long before). The only list of every line that is part of the jar's plain resources is
 * {@code assets/nusmp/skill_books.json} (generated by {@code tools/lines/gen_book_index.py} from the same route files and checked against them by a unit test), so this class reads the ids, names and
 * colours from it. It is Minecraft-free (Gson only), so the parsing, the id rules and the order are unit tested without a game, and it is the single place that turns a line id into the id of its
 * stand-in skill ({@link #skillPath}), so the registry, the lang fragment, the icon generator and the tests can never disagree about it. The order is the id order (a {@link TreeMap}), never the file
 * order, so the registry order of the stand-ins is the same on every machine and every build.
 */
public final class LineIndex {
    private LineIndex() {}

    /** The classpath location of the table (it is an asset, but a plain jar resource on both sides). */
    public static final String RESOURCE = "/assets/nusmp/skill_books.json";
    /** The namespace of every line id: {@code nusmp:fire_dragon_slayer}. */
    public static final String NAMESPACE = "nusmp";
    private static final Pattern SNAKE = Pattern.compile("[a-z0-9_]{1,40}");

    /** One line as the registry needs it: {@code bare} is the file stem ({@code fire_dragon_slayer}), {@code routeId} the route id ({@code nusmp:fire_dragon_slayer}). */
    public record Line(String bare, String routeId, String name, int color, String franchise) {
        /** The path of the stand-in skill's id ({@code line_fire_dragon_slayer}). */
        public String skillPath() { return LineIndex.skillPath(bare); }
    }

    /** The path part of a stand-in skill's registry id: {@code line_<bare>}. The prefix keeps it clear of every other skill id of the mod. */
    public static String skillPath(String bare) { return "line_" + bare; }

    /** The route id of a bare line id ({@code nusmp:<bare>}); an id that already has a namespace is returned unchanged. */
    public static String routeId(String bareOrRouteId) { return bareOrRouteId.indexOf(':') >= 0 ? bareOrRouteId : NAMESPACE + ":" + bareOrRouteId; }

    /** The bare id of a route id ({@code nusmp:x} to {@code x}); a bare id is returned unchanged. */
    public static String bare(String routeId) {
        int i = routeId.indexOf(':');
        return i < 0 ? routeId : routeId.substring(i + 1);
    }

    /** True for an id the registry can use as the end of a skill path. */
    public static boolean validBare(String s) { return s != null && SNAKE.matcher(s).matches(); }

    /**
     * Parses the table. Tolerant by design (a bad entry is skipped, never an error, so one typo cannot stop the game from starting): an entry whose key is not a snake-case id, or that is not an
     * object, is dropped. The result is in id order and immutable.
     */
    public static List<Line> parse(JsonObject root) {
        Map<String, Line> sorted = new TreeMap<>();
        if (root != null && root.has("lines") && root.get("lines").isJsonObject()) {
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("lines").entrySet()) {
                if (!validBare(e.getKey()) || !e.getValue().isJsonObject()) continue;
                JsonObject o = e.getValue().getAsJsonObject();
                String name = str(o, "name");
                sorted.put(e.getKey(), new Line(e.getKey(), routeId(e.getKey()), name.isEmpty() ? e.getKey() : name, color(str(o, "color")), str(o, "franchise")));
            }
        }
        return Collections.unmodifiableList(new ArrayList<>(sorted.values()));
    }

    private static volatile String problem = "";

    /** The reason the last {@link #load} found nothing (empty when it worked), for the caller to log: this class has no logger so it stays free of Minecraft types. */
    public static String problem() { return problem; }

    /** Reads the table from the jar. An unreadable table answers an empty list and sets {@link #problem} (the game still starts; the in-game self-test then reports it). */
    public static List<Line> load() {
        try (InputStream in = LineIndex.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                problem = RESOURCE + " is missing from the jar, so no Unique Skill Line can be shown in Tensura's Ability Selection menu";
                return List.of();
            }
            List<Line> lines = parse(JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject());
            problem = lines.isEmpty() ? RESOURCE + " lists no line" : "";
            return lines;
        } catch (IOException | RuntimeException e) {
            problem = "could not read " + RESOURCE + ": " + e;
            return List.of();
        }
    }

    private static String str(JsonObject o, String key) { return o.has(key) && o.get(key).isJsonPrimitive() ? o.get(key).getAsString() : ""; }

    /** {@code #RRGGBB} to 0xRRGGBB; anything else is white. */
    static int color(String s) {
        String h = s.startsWith("#") ? s.substring(1) : s;
        if (h.length() != 6) return 0xFFFFFF;
        try {
            return Integer.parseInt(h, 16) & 0xFFFFFF;
        } catch (NumberFormatException e) {
            return 0xFFFFFF;
        }
    }
}
