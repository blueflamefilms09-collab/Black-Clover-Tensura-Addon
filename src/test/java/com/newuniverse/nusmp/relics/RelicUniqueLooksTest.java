package com.newuniverse.nusmp.relics;

import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Why: the owner's rule is that relics never look the same. The generated waves (31 and later, tools/relics/gen_relic_waves.py) are made from tables, so a copy-pasted row could
 * quietly give two relics one sprite, one palette or one worn model. This reads the sources and the asset files (no game needed) and fails when two generated relics share a sprite,
 * share a worn ornament, share a palette, or when one has no ornament of its own in the worn catalog.
 */
class RelicUniqueLooksTest {
    private static final Path WAVES = Path.of("src/main/java/com/newuniverse/nusmp/relics/wave");
    private static final Path ASSETS = Path.of("src/main/resources/assets/nusmp");
    private static final Pattern ID = Pattern.compile("RelicDef\\.of\\(\"([a-z0-9_]+)\"");
    private static final Pattern PAL = Pattern.compile("\\.palette\\((0x[0-9A-F]+), (0x[0-9A-F]+), (0x[0-9A-F]+)\\)");

    private static List<String> generatedIds(Map<String, String> palettes) throws IOException {
        List<String> ids = new ArrayList<>();
        for (int n = 31; n < 41; n++) {
            Path p = WAVES.resolve("Wave" + n + ".java");
            if (!Files.exists(p)) continue;
            String t = Files.readString(p);
            if (!t.contains("GENERATED by tools/relics/gen_relic_waves.py")) continue;
            Matcher m = ID.matcher(t);
            while (m.find()) {
                String id = m.group(1);
                ids.add(id);
                int end = t.indexOf("out.accept", m.end());
                Matcher pm = PAL.matcher(t.substring(m.end(), end < 0 ? t.length() : end));
                if (pm.find()) palettes.put(id, pm.group(1) + pm.group(2) + pm.group(3));
            }
        }
        return ids;
    }

    private static String digest(Path p) throws Exception {
        return java.util.HexFormat.of().formatHex(java.security.MessageDigest.getInstance("SHA-256").digest(Files.readAllBytes(p)));
    }

    @Test
    void generatedRelicsNeverShareASpriteAnOrnamentOrAPalette() throws Exception {
        Map<String, String> palettes = new HashMap<>();
        List<String> ids = generatedIds(palettes);
        assertTrue(ids.size() >= 90, "the generated waves should hold at least 90 relics, saw " + ids.size());
        List<String> catalog = Files.readAllLines(ASSETS.resolve("relic_worn/catalog.txt"));
        Map<String, String> sprites = new HashMap<>(), ornaments = new HashMap<>(), pals = new HashMap<>();
        for (String id : ids) {
            String other = sprites.put(digest(ASSETS.resolve("textures/item/" + id + ".png")), id);
            assertEquals(null, other, id + " has the same sprite as " + other);
            Path orn = ASSETS.resolve("relic_worn/uq_" + id + ".txt");
            assertTrue(Files.exists(orn), id + " has no ornament model of its own");
            other = ornaments.put(digest(orn).concat(""), id);
            assertEquals(null, other, id + " has the same ornament as " + other);
            assertTrue(catalog.stream().anyMatch(l -> l.startsWith("relic " + id + " ") && l.contains("uq_" + id)), id + " does not wear its ornament in the worn catalog");
            String pal = palettes.get(id);
            assertTrue(pal != null, id + " has no palette");
            other = pals.put(pal, id);
            assertEquals(null, other, id + " has the same palette as " + other);
        }
    }
}
