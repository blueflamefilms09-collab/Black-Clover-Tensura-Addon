package com.newuniverse.nusmp.vfx;

import org.junit.jupiter.api.Test;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Why (docs/vfx_roblox_pass.md, docs/vfx_square_bug.md): the ten {@code rbx_} textures of the Roblox-style toolkit are generated by tools/gen_roblox_vfx_textures.py and drawn on real meshes and flip-book
 * quads. Nothing can be seen here, so the files are pinned: all there with the size of their name (power of two), a real alpha falloff (visible and fully clear texels, never an all-opaque halo box), alpha EXACTLY 0
 * on the borders that end on air (no square halo, no seam), clear corners on the square sprites and on every flip-book cell, no colour-less (black) clear texel next to a visible one (linear filtering would draw a dark
 * edge), no stray {@code rbx_} file, the generator makes every name. The Time Magic textures are not looked at.
 */
class RobloxStyleAssetTest {
    private static final Path ROOT = Path.of("").toAbsolutePath();
    private static final Path PARTICLE = ROOT.resolve("src/main/resources/assets/anime_multiverse/textures/particle");

    private record Img(int w, int h, int[] px) {
        int a(int x, int y) { return px[y * w + x] >>> 24; }
    }

    private static Img read(String name) throws IOException {
        File f = PARTICLE.resolve(RobloxMath.fileName(name) + ".png").toFile();
        assertTrue(f.isFile(), "missing " + f.getName());
        BufferedImage img = ImageIO.read(f);
        assertNotNull(img, name);
        int w = img.getWidth(), h = img.getHeight();
        int[] px = new int[w * h];
        img.getRGB(0, 0, w, h, px, 0, w);
        return new Img(w, h, px);
    }

    private static boolean pow2(int v) { return v > 0 && (v & (v - 1)) == 0; }

    /** max alpha of one column (col = true) or row of the image, within [from, to). */
    private static int edge(Img i, boolean col, int index, int from, int to) {
        int m = 0;
        for (int k = from; k < to; k++) m = Math.max(m, col ? i.a(index, k) : i.a(k, index));
        return m;
    }

    @Test
    void everyTextureIsThereWithAPowerOfTwoSizeAndARealAlphaFalloff() throws IOException {
        List<String> bad = new ArrayList<>();
        for (String name : RobloxMath.TEXTURE_NAMES) {
            Img i = read(name);
            if (!pow2(i.w) || !pow2(i.h)) bad.add(name + " is " + i.w + "x" + i.h + " (not a power of two)");
            int clear = 0, visible = 0;
            for (int v : i.px) { int a = v >>> 24; if (a == 0) clear++; if (a > 40) visible++; }
            if (visible < i.px.length / 50) bad.add(name + " has almost nothing visible");
            if (!name.equals("rock") && clear < 64) bad.add(name + " has no clear texels (a halo box)");
            if (name.equals("rock") && clear > 0) bad.add("the rock is opaque (it is drawn as stone, not as a sprite)");
        }
        assertTrue(bad.isEmpty(), bad.toString());
    }

    @Test
    void theBordersThatEndOnAirAreExactlyClear() throws IOException {
        List<String> bad = new ArrayList<>();
        // swoosh / bolt: U runs across (left and right edges are clear), V runs along and tiles (top and bottom match, they are not clear)
        for (String n : new String[]{"swoosh", "bolt"}) {
            Img i = read(n);
            if (edge(i, true, 0, 0, i.h) != 0 || edge(i, true, i.w - 1, 0, i.h) != 0) bad.add(n + ": the sides are not clear");
        }
        // ring: U runs round the ring (wraps), V is inner -> outer: top and bottom rows are clear
        Img ring = read("ring");
        if (edge(ring, false, 0, 0, ring.w) != 0 || edge(ring, false, ring.h - 1, 0, ring.w) != 0) bad.add("ring: the inner and outer rows are not clear");
        // square sprites: all four borders clear
        for (String n : new String[]{"decal_ring", "glow"}) {
            Img i = read(n);
            if (edge(i, true, 0, 0, i.h) != 0 || edge(i, true, i.w - 1, 0, i.h) != 0 || edge(i, false, 0, 0, i.w) != 0 || edge(i, false, i.h - 1, 0, i.w) != 0) bad.add(n + ": a border is not clear");
        }
        // streak: V = 0 is the head, the tail row and both sides are clear (the head row may carry a whisper of alpha)
        Img st = read("streak");
        if (edge(st, true, 0, 0, st.h) != 0 || edge(st, true, st.w - 1, 0, st.h) != 0 || edge(st, false, st.h - 1, 0, st.w) != 0) bad.add("streak: sides or tail not clear");
        if (edge(st, false, 0, 0, st.w) > 16) bad.add("streak: the head row is visibly cut");
        assertTrue(bad.isEmpty(), bad.toString());
    }

    @Test
    void everyFlipBookCellHasAClearBorderSoACrossFadeNeverDrawsASquare() throws IOException {
        List<String> bad = new ArrayList<>();
        for (String n : RobloxMath.FLIPBOOKS) {
            Img i = read(n);
            int cw = i.w / RobloxMath.FLIP_COLS, ch = i.h / RobloxMath.FLIP_ROWS;
            for (int r = 0; r < RobloxMath.FLIP_ROWS; r++) for (int c = 0; c < RobloxMath.FLIP_COLS; c++) {
                int x0 = c * cw, y0 = r * ch;
                int m = Math.max(Math.max(edge(i, false, y0, x0, x0 + cw), edge(i, false, y0 + ch - 1, x0, x0 + cw)), Math.max(edge(i, true, x0, y0, y0 + ch), edge(i, true, x0 + cw - 1, y0, y0 + ch)));
                if (m != 0) bad.add(n + " cell " + r + "," + c + " has a visible border (" + m + ")");
                int visible = 0;
                for (int y = y0; y < y0 + ch; y++) for (int x = x0; x < x0 + cw; x++) if (i.a(x, y) > 40) visible++;
                if (r * RobloxMath.FLIP_COLS + c <= 12 && visible < cw * ch / 100) bad.add(n + " cell " + r + "," + c + " is empty");   // the last frames are the dissipated tail, nearly clear on purpose
            }
        }
        assertTrue(bad.isEmpty(), bad.toString());
    }

    @Test
    void aClearTexelNextToAVisibleOneCarriesItsColourSoLinearFilteringDrawsNoDarkEdge() throws IOException {
        List<String> bad = new ArrayList<>();
        for (String name : RobloxMath.TEXTURE_NAMES) {
            Img i = read(name);
            int dark = 0;
            for (int y = 0; y < i.h; y++) for (int x = 0; x < i.w; x++) {
                if (i.a(x, y) != 0) continue;
                boolean near = false;
                for (int dy = -1; dy <= 1 && !near; dy++) for (int dx = -1; dx <= 1; dx++) {
                    int xx = x + dx, yy = y + dy;
                    if (xx >= 0 && yy >= 0 && xx < i.w && yy < i.h && i.a(xx, yy) > 20) { near = true; break; }
                }
                if (near && (i.px[y * i.w + x] & 0xFFFFFF) == 0) dark++;
            }
            if (dark > 0) bad.add(name + " has " + dark + " black clear texels next to visible ones");
        }
        assertTrue(bad.isEmpty(), bad.toString());
    }

    @Test
    void noStrayRbxFileAndTheListIsTheGeneratorsList() throws IOException {
        Set<String> expected = new HashSet<>();
        for (String n : RobloxMath.TEXTURE_NAMES) expected.add(RobloxMath.fileName(n) + ".png");
        Set<String> found = new HashSet<>();
        File[] files = PARTICLE.toFile().listFiles((d, n) -> n.startsWith(RobloxMath.PREFIX));
        assertNotNull(files);
        for (File f : files) found.add(f.getName());
        assertEquals(expected, found, "the rbx_ files and the list in RobloxMath must be the same set");
        String gen = Files.readString(ROOT.resolve("tools/gen_roblox_vfx_textures.py"), StandardCharsets.UTF_8);
        for (String n : RobloxMath.TEXTURE_NAMES) assertTrue(gen.contains("\"" + n + "\""), "the generator does not make " + n);
        assertTrue(gen.contains("rbx_"));
    }

    @Test
    void everyTextureIsDrawnByTheToolkit() throws IOException {
        String style = Files.readString(ROOT.resolve("src/main/java/com/newuniverse/nusmp/vfx/client/RobloxStyle.java"), StandardCharsets.UTF_8);
        for (String n : RobloxMath.TEXTURE_NAMES) assertTrue(style.contains("t(\"" + n + "\")"), "RobloxStyle never loads " + n);
    }

    @Test
    void theOldTexturesAndTheTimeMagicOnesAreStillThere() {
        for (String n : new String[]{"glow", "air_ring", "flamefx_ring", "waterfx_ripple", "earthfam_rock_ring"})
            assertTrue(Files.isRegularFile(PARTICLE.resolve(n + ".png")), "the old " + n + " must stay (rule 2)");
        File[] time = PARTICLE.toFile().listFiles((d, n) -> n.startsWith("time_"));
        assertNotNull(time);
        assertTrue(time.length > 0, "the Time Magic textures are untouched");
    }
}
