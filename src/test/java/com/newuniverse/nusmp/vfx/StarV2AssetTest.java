package com.newuniverse.nusmp.vfx;

import org.junit.jupiter.api.Test;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Why: the 24 textures of the Star V2 look are generated by tools/gen_star_v2_textures.py and read by name, so the files are pinned: all of them exist with the size of their name, some visible and some clear
 * texels, clear corners for the square sprites, no colour-less fringe (a clear texel next to a visible one carries its colour, so linear filtering never draws a dark edge); no stray {@code stv_} file (no dead
 * assets); every texture is drawn by the layer or the painter; the generator's list is the list of the rules; the old star textures and the old layer's sprites are still there (rule 2).
 */
class StarV2AssetTest {
    private static final Path ROOT = Path.of("").toAbsolutePath();
    private static final Path PARTICLE = ROOT.resolve("src/main/resources/assets/nusmp/textures/particle");

    private static BufferedImage image(String file) throws IOException {
        BufferedImage img = ImageIO.read(PARTICLE.resolve(file + ".png").toFile());
        assertNotNull(img, file);
        return img;
    }

    @Test
    void everyTextureIsThereWithItsSizeAndCleanCorners() throws IOException {
        List<String> bad = new ArrayList<>();
        for (String name : StarV2.TEXTURE_NAMES) {
            String file = StarV2.fileName(name);
            assertTrue(Files.isRegularFile(PARTICLE.resolve(file + ".png")), "missing " + file);
            BufferedImage img = image(file);
            int[] px = img.getRGB(0, 0, img.getWidth(), img.getHeight(), null, 0, img.getWidth());
            String problem = StarV2.checkTexture(name, img.getWidth(), img.getHeight(), px);
            if (problem != null) bad.add(file + ": " + problem);
        }
        assertTrue(bad.isEmpty(), bad.toString());
    }

    @Test
    void aClearTexelNextToAVisibleOneCarriesItsColourSoLinearFilteringDrawsNoDarkEdge() throws IOException {
        List<String> bad = new ArrayList<>();
        for (String name : StarV2.TEXTURE_NAMES) {
            BufferedImage img = image(StarV2.fileName(name));
            int w = img.getWidth(), h = img.getHeight();
            int[] px = img.getRGB(0, 0, w, h, null, 0, w);
            int dark = 0;
            for (int y = 0; y < h; y++) for (int x = 0; x < w; x++) {
                if ((px[y * w + x] >>> 24) != 0) continue;
                boolean nearVisible = false;
                for (int dy = -1; dy <= 1 && !nearVisible; dy++) for (int dx = -1; dx <= 1; dx++) {
                    int xx = x + dx, yy = y + dy;
                    if (xx >= 0 && yy >= 0 && xx < w && yy < h && (px[yy * w + xx] >>> 24) > 20) { nearVisible = true; break; }
                }
                if (nearVisible && (px[y * w + x] & 0xFFFFFF) == 0) dark++;
            }
            if (dark > 0) bad.add(name + " has " + dark + " black clear texels next to visible ones");
        }
        assertTrue(bad.isEmpty(), bad.toString());
    }

    @Test
    void noStrayStvFileAndTheListIsTheGeneratorsList() throws IOException {
        Set<String> expected = new HashSet<>();
        for (String p : StarV2.allTextures()) expected.add(p.substring(p.lastIndexOf('/') + 1));
        Set<String> found = new HashSet<>();
        File[] files = PARTICLE.toFile().listFiles((d, n) -> n.startsWith(StarV2.PREFIX));
        assertNotNull(files);
        for (File f : files) found.add(f.getName());
        assertEquals(expected, found, "the stv_ files and the list in StarV2 must be the same set");
        String gen = Files.readString(ROOT.resolve("tools/gen_star_v2_textures.py"), StandardCharsets.UTF_8);
        for (String n : StarV2.TEXTURE_NAMES) assertTrue(gen.contains("\"" + n + "\""), "the generator does not make " + n);
        assertTrue(gen.contains("PREFIX = \"stv_\""));
    }

    @Test
    void everyTextureIsDrawnByTheLayerOrThePainter() throws IOException {
        String layer = Files.readString(ROOT.resolve("src/main/java/com/newuniverse/nusmp/vfx/client/layer/StarMagicLayer.java"), StandardCharsets.UTF_8);
        String painter = Files.readString(ROOT.resolve("src/main/java/com/newuniverse/nusmp/client/prop/StarPropPainter.java"), StandardCharsets.UTF_8);
        layer = layer.replaceAll("(?s)/\\*.*?\\*/", "").replaceAll("//[^\n]*", "");
        painter = painter.replaceAll("(?s)/\\*.*?\\*/", "").replaceAll("//[^\n]*", "");
        // the layer's constants name the texture groups by their index in TEXTURE_NAMES; the painter names its textures
        String[][] layerGroups = {{"a_star4", "STAR4"}, {"a_spark", "SPARK"}, {"a_line", "LINE"}, {"a_ring", "RING"}, {"a_shard", "SHARD"}, {"a_burst", "BURST"}, {"a_whip", "WHIP"}, {"a_beam", "BEAM"},
                {"a_crack", "CRACK"}, {"a_rays", "RAYS"}, {"b_glow", "GLOW"}, {"b_glow_blue", "GLOW_BLUE"}, {"b_flare", "FLARE"}, {"b_star", "BSTAR"}, {"b_beam", "BBEAM"}, {"b_ring", "BRING"},
                {"b_rays", "BRAYS"}, {"b_dust_a", "DUST"}, {"b_trail", "TRAIL"}, {"b_sigil", "BSIGIL"}};
        for (String[] g : layerGroups) {
            assertTrue(layer.contains("TEX[" + g[1] + "]") || layer.contains("TEX[" + g[1] + " +"), g[0] + " is generated but the layer never draws it (a dead asset)");
            int idx = java.util.Arrays.asList(StarV2.TEXTURE_NAMES).indexOf(g[0]);
            assertTrue(layer.matches("(?s).*\\b" + g[1] + " = " + idx + "\\b.*") || layer.matches("(?s).*[ ,]" + g[1] + " = " + idx + "[,;].*"), g[1] + " must be index " + idx + " of TEXTURE_NAMES");
        }
        assertTrue(layer.contains("DUST + (i % 3)"), "the three dust sprites are all drawn");
        for (String own : new String[]{"a_pane", "a_sigil"}) assertTrue(painter.contains("StarV2.fileName(\"" + own + "\")"), own + " is drawn by the prop painter");
        for (String shared : new String[]{"a_star4", "a_spark", "b_glow", "b_star"}) assertTrue(painter.contains("StarV2.fileName(\"" + shared + "\")"), shared + " is drawn by the prop painter too");
    }

    @Test
    void theOldStarTexturesAndTheOldSpritesAreAllStillThere() {
        for (String old : new String[]{"glow", "spark", "shard", "magic_explosion", "magic_circle", "star4_0", "star4_1", "star4_2", "star4_3", "star4_4", "star4_5"})
            assertTrue(Files.isRegularFile(PARTICLE.resolve(old + ".png")), old + " was deleted (rule 2: keep the old)");
    }
}
