package com.newuniverse.nusmp.vfx;

import org.junit.jupiter.api.Test;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Why: the textures and the mesh files of the Water hybrid are generated by tools/gen_water_bc_textures.py and tools/gen_water_bc_meshes.py and read by the painter by name, so the files are pinned: every
 * sprite exists and is a sprite (some opaque, some clear texels, clear corners for the round ones), every grey twin has the silhouette of its colour original and only grey texels, no stray {@code wbc_}
 * file is in the folder (no dead assets), the old water textures are all still there (rule 2); every mesh file parses with the quad counts the caps are built on (a light variant is lighter than its full
 * piece), the quads are well formed (finite, with a real area, winding that agrees with the stored normal), the pieces stay inside the sizes the scene scales them for, and the Valkyrie wings are NOT shipped.
 */
class WaterBcAssetTest {
    private static final Path ROOT = Path.of("").toAbsolutePath();
    private static final Path PARTICLE = ROOT.resolve("src/main/resources/assets/nusmp/textures/particle");
    private static final Path MESHES = ROOT.resolve("src/main/resources/assets/nusmp/" + WaterBc.MESH_FOLDER);

    private static BufferedImage image(String file) throws IOException {
        BufferedImage img = ImageIO.read(PARTICLE.resolve(file + ".png").toFile());
        assertNotNull(img, file);
        return img;
    }

    private static int[] argb(BufferedImage img) { return img.getRGB(0, 0, img.getWidth(), img.getHeight(), null, 0, img.getWidth()); }

    @Test
    void everySpriteIsThereAndIsASprite() throws IOException {
        List<String> bad = new ArrayList<>();
        for (int i = 0; i < WaterBc.SPRITES.length; i++) {
            for (int twin = 0; twin < (WaterBc.hasTwin(i) ? 2 : 1); twin++) {
                String file = WaterBc.fileName(WaterBc.SPRITES[i], twin == 1);
                assertTrue(Files.isRegularFile(PARTICLE.resolve(file + ".png")), "missing " + file);
                BufferedImage img = image(file);
                String problem = WaterBc.checkTexture(file, twin == 1, img.getWidth(), img.getHeight(), argb(img));
                if (problem != null) bad.add(file + ": " + problem);
            }
        }
        assertTrue(bad.isEmpty(), bad.toString());
        BufferedImage solid = image(WaterBc.fileName(WaterBc.SOLID, false));
        for (int p : argb(solid)) assertEquals(0xFFFFFFFF, p, "the solid cell of the mesh quads is white and opaque");
    }

    @Test
    void theGreyTwinHasTheSilhouetteOfItsColourOriginal() throws IOException {
        for (int t : WaterBc.TINT_TWINS) {
            BufferedImage a = image(WaterBc.fileName(WaterBc.SPRITES[t], false)), b = image(WaterBc.fileName(WaterBc.SPRITES[t], true));
            assertEquals(a.getWidth(), b.getWidth());
            assertEquals(a.getHeight(), b.getHeight());
            int[] pa = argb(a), pb = argb(b);
            long lum = 0;
            int live = 0;
            for (int i = 0; i < pa.length; i++) {
                assertEquals(pa[i] >>> 24, pb[i] >>> 24, WaterBc.SPRITES[t] + ": the twin has another silhouette at texel " + i);
                if ((pb[i] >>> 24) > 8) { live++; lum += pb[i] & 255; }
            }
            assertTrue(live > 0 && lum / live > 90, WaterBc.SPRITES[t] + ": the twin is too dark to carry a tint (mean grey " + (live == 0 ? 0 : lum / live) + ")");
        }
    }

    @Test
    void noStrayWbcFileAndEveryOldWaterTextureIsStillThere() throws IOException {
        Set<String> want = new HashSet<>();
        for (String p : WaterBc.allTextures()) want.add(p.substring(p.lastIndexOf('/') + 1));
        try (Stream<Path> s = Files.list(PARTICLE)) {
            for (Path p : (Iterable<Path>) s.filter(x -> x.getFileName().toString().startsWith(WaterBc.PREFIX))::iterator)
                assertTrue(want.contains(p.getFileName().toString()), "a wbc_ file nothing reads: " + p.getFileName());
        }
        for (String old : new String[]{"waterfx_stream", "waterfx_ripple", "waterfx_drop", "waterfx_sigil", "waterfx_wave", "waterfx_spray", "water_splash", "glow"})
            assertTrue(Files.isRegularFile(PARTICLE.resolve(old + ".png")), "the old texture " + old + " is gone");
    }

    private record Quad(int layer, float[] p, float[] n) {}

    private static List<Quad> read(String name) throws IOException {
        Path f = MESHES.resolve(name + ".txt");
        assertTrue(Files.isRegularFile(f), "missing mesh " + name);
        List<Quad> out = new ArrayList<>();
        for (String line : Files.readAllLines(f, StandardCharsets.UTF_8)) {
            if (!line.startsWith("q ")) continue;
            String[] v = line.trim().split("\\s+");
            assertEquals(28, v.length, name + ": a quad line has 28 fields");
            float[] row = new float[26];
            for (int i = 0; i < 26; i++) row[i] = Float.parseFloat(v[2 + i]);
            float[] p = new float[12];
            for (int k = 0; k < 4; k++) { p[k * 3] = row[k * 5]; p[k * 3 + 1] = row[k * 5 + 1]; p[k * 3 + 2] = row[k * 5 + 2]; }
            out.add(new Quad(Integer.parseInt(v[1]), p, new float[]{row[20], row[21], row[22]}));
        }
        return out;
    }

    @Test
    void everyMeshFileParsesWellFormedAndInsideItsSizes() throws IOException {
        for (int piece = 0; piece < WaterBc.PIECES.length; piece++) {
            int full = 0;
            for (int lo = 0; lo < 2; lo++) {
                String name = WaterBc.meshFile(piece, lo == 1);
                List<Quad> quads = read(name);
                WaterBcMeshes.Piece parsed = WaterBcMeshes.get(piece, lo == 1);
                assertEquals(quads.size(), parsed.quads, name + ": the parser reads every quad");
                assertTrue(quads.size() >= 5 && quads.size() <= 100, name + " has " + quads.size() + " quads");
                if (lo == 0) full = quads.size();
                else assertTrue(quads.size() < full, name + " is not lighter than its full piece");
                int agree = 0, solidLayer = 0;
                for (Quad q : quads) {
                    assertTrue(q.layer >= 0 && q.layer < 3, name);
                    float max = 0f;
                    for (float x : q.p) { assertTrue(Float.isFinite(x), name + " has a non finite vertex"); max = Math.max(max, Math.abs(x)); }
                    assertTrue(max <= 80f, name + " has a vertex " + max + " px from its origin (more than five blocks)");
                    float nx = (q.p[7] - q.p[1]) * (q.p[11] - q.p[5]) - (q.p[8] - q.p[2]) * (q.p[10] - q.p[4]);
                    float ny = (q.p[8] - q.p[2]) * (q.p[9] - q.p[3]) - (q.p[6] - q.p[0]) * (q.p[11] - q.p[5]);
                    float nz = (q.p[6] - q.p[0]) * (q.p[10] - q.p[4]) - (q.p[7] - q.p[1]) * (q.p[9] - q.p[3]);
                    float len = (float) Math.sqrt(nx * nx + ny * ny + nz * nz);
                    if (len < 1e-3f) continue;                                          // a triangle written as a quad has a real area too; only a point or a line has none
                    if ((nx * q.n[0] + ny * q.n[1] + nz * q.n[2]) / len > 0.5f) agree++;
                    solidLayer++;
                }
                assertTrue(solidLayer * 100 >= quads.size() * 95, name + ": quads with no area");
                assertEquals(solidLayer, agree, name + ": the winding of a quad disagrees with its stored normal");
            }
        }
    }

    @Test
    void theQuadCountsTheCapsAreBuiltOnAreExactlyThePreviewSet() {
        // water_bc.md section 4 (counts_bc.txt): the pieces of the shipped set have the preview's quad counts
        int[][] expect = {{67, 37}, {24, 15}, {32, 16}, {15, 7}, {21, 11}, {16, 12}, {20, 12}, {44, 24}, {50, 30}, {80, 48}, {96, 55}};
        for (int p = 0; p < expect.length; p++) {
            assertEquals(expect[p][0], WaterBcMeshes.get(p, false).quads, WaterBc.meshFile(p, false));
            assertEquals(expect[p][1], WaterBcMeshes.get(p, true).quads, WaterBc.meshFile(p, true));
        }
    }

    @Test
    void noValkyrieWingIsShippedAndNothingElseIsInTheFolder() throws IOException {
        Set<String> want = new HashSet<>();
        for (String m : WaterBc.allMeshes()) want.add(m.substring(m.lastIndexOf('/') + 1));
        try (Stream<Path> s = Files.list(MESHES)) {
            for (Path p : (Iterable<Path>) s::iterator) {
                String n = p.getFileName().toString();
                assertTrue(!n.contains("wing"), "the Valkyrie wings are deferred: " + n);
                assertTrue(want.contains(n), "a mesh file nothing reads: " + n);
            }
        }
        assertEquals(22, want.size());
    }
}
