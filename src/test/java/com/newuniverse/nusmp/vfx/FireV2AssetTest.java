package com.newuniverse.nusmp.vfx;

import org.junit.jupiter.api.Test;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Why: the 66 textures of the Fire V2 look are generated by tools/gen_fire_v2_textures.py and read by the painter by name, so the files are pinned: all of them exist with the size of their name, some visible
 * and some clear texels, clear corners for the square sprites, no colour-less fringe (a texel with no alpha next to a visible one carries a colour, so linear filtering never draws a dark edge), every grey twin
 * has exactly the silhouette of its baked texture and red = green = blue; no stray {@code fnw_} file is in the folder (no dead assets); every texture group is drawn by the painter; the generator lists the
 * names; the old fire textures (and the Flame Fx sigils the kept parts draw) are all still there (rule 2).
 */
class FireV2AssetTest {
    private static final Path ROOT = Path.of("").toAbsolutePath();
    private static final Path PARTICLE = ROOT.resolve("src/main/resources/assets/nusmp/textures/particle");

    private static BufferedImage image(String file) throws IOException {
        BufferedImage img = ImageIO.read(PARTICLE.resolve(file + ".png").toFile());
        assertNotNull(img, file);
        return img;
    }

    private static int[] argb(String file) throws IOException {
        BufferedImage img = image(file);
        return img.getRGB(0, 0, img.getWidth(), img.getHeight(), null, 0, img.getWidth());
    }

    @Test
    void everyTextureIsThereWithItsSizeAndCleanCornersAndTwinsAreGrey() throws IOException {
        List<String> bad = new ArrayList<>();
        for (String name : FireV2.TEXTURE_NAMES) for (int t = 0; t < 2; t++) {
            if (t == 1 && FireV2.noTwin(name)) continue;
            String file = FireV2.fileName(name, t == 1);
            assertTrue(Files.isRegularFile(PARTICLE.resolve(file + ".png")), "missing " + file);
            BufferedImage img = image(file);
            int[] px = img.getRGB(0, 0, img.getWidth(), img.getHeight(), null, 0, img.getWidth());
            String problem = FireV2.checkTexture(name, t == 1, img.getWidth(), img.getHeight(), px);
            if (problem != null) bad.add(file + ": " + problem);
        }
        assertTrue(bad.isEmpty(), bad.toString());
    }

    @Test
    void aClearTexelNextToAVisibleOneCarriesItsColourSoLinearFilteringDrawsNoDarkEdge() throws IOException {
        List<String> bad = new ArrayList<>();
        for (String name : FireV2.TEXTURE_NAMES) {
            String file = FireV2.fileName(name, false);
            BufferedImage img = image(file);
            int w = img.getWidth(), h = img.getHeight();
            int[] px = img.getRGB(0, 0, w, h, null, 0, w);
            int dark = 0;
            for (int y = 0; y < h; y++) for (int x = 0; x < w; x++) {
                if ((px[y * w + x] >>> 24) != 0) continue;
                boolean nearVisible = false;
                for (int dy = -1; dy <= 1 && !nearVisible; dy++) for (int dx = -1; dx <= 1; dx++) {
                    int xx = x + dx, yy = y + dy;
                    if (xx >= 0 && yy >= 0 && xx < w && yy < h && (px[yy * w + xx] >>> 24) > 60) { nearVisible = true; break; }
                }
                if (nearVisible && (px[y * w + x] & 0xFFFFFF) == 0) dark++;
            }
            if (dark > 0) bad.add(file + " has " + dark + " black clear texels next to visible ones");
        }
        assertTrue(bad.isEmpty(), bad.toString());
    }

    @Test
    void theGreyTwinHasTheSilhouetteOfItsBakedTexture() throws IOException {
        for (String name : FireV2.TEXTURE_NAMES) {
            if (FireV2.noTwin(name)) continue;
            int[] a = argb(FireV2.fileName(name, false)), b = argb(FireV2.fileName(name, true));
            assertEquals(a.length, b.length);
            for (int i = 0; i < a.length; i++) assertEquals(a[i] >>> 24, b[i] >>> 24, name + " pixel " + i);
        }
    }

    @Test
    void noStrayFnwFileAndTheFlipBookFramesDiffer() throws IOException {
        Set<String> expected = new HashSet<>();
        for (String p : FireV2.allTextures()) expected.add(p.substring(p.lastIndexOf('/') + 1));
        Set<String> found = new HashSet<>();
        File[] files = PARTICLE.toFile().listFiles((d, n) -> n.startsWith(FireV2.PREFIX));
        assertNotNull(files);
        for (File f : files) found.add(f.getName());
        assertEquals(expected, found, "the fnw_ files and the list in FireV2 must be the same set");
        for (String[] pair : new String[][]{{"a_tongue_a", "a_tongue_b"}, {"a_tongue_b", "a_tongue_c"}, {"a_ball_a", "a_ball_b"}, {"a_body_a", "a_body_b"}, {"a_lion_a", "a_lion_b"}, {"a_orb_a", "a_orb_b"},
                {"a_swoosh_a", "a_swoosh_b"}})
            assertTrue(!java.util.Arrays.equals(argb(FireV2.fileName(pair[0], false)), argb(FireV2.fileName(pair[1], false))), pair[0] + " and " + pair[1] + " are identical: no flip-book");
    }

    @Test
    void everyTextureGroupIsDrawnByThePainterAndTheGeneratorMakesIt() throws IOException {
        String layer = Files.readString(ROOT.resolve("src/main/java/com/newuniverse/nusmp/vfx/client/layer/FireV2Layer.java"), StandardCharsets.UTF_8);
        layer = layer.replaceAll("(?s)/\\*.*?\\*/", "").replaceAll("//[^\n]*", "");
        String gen = Files.readString(ROOT.resolve("tools/gen_fire_v2_textures.py"), StandardCharsets.UTF_8) + Files.readString(ROOT.resolve("tools/gen_fire_new_textures.py"), StandardCharsets.UTF_8);
        // texture group -> the constant the painter draws it with (a group is a flip-book or a set of variants)
        String[][] groups = {{"a_tongue", "TONGUE"}, {"a_ball", "BALL"}, {"a_body", "BODY"}, {"a_lion", "LION"}, {"a_swoosh", "SWOOSH"}, {"a_ring", "RING"}, {"a_rays", "RAYS"}, {"a_flash", "FLASH"},
                {"a_smoke", "SMOKE"}, {"a_chip", "CHIP"}, {"a_orb", "ORB"}, {"a_beam", "BEAM"}, {"a_floor", "FLOOR"}, {"a_swirl", "SWIRL"}, {"b_ember", "EMBER"}, {"b_halo", "HALO"}, {"b_puff", "PUFF"},
                {"b_rays", "BRAYS"}, {"b_ring", "BRING"}, {"b_streak", "BSTREAK"}};
        Set<String> covered = new HashSet<>();
        for (String[] g : groups) {
            assertTrue(layer.contains("tex(" + g[1]) || layer.contains("texT(" + g[1]) || layer.contains("rays(" + g[1]), g[0] + " is generated but the painter never draws it (a dead asset)");
            for (String n : FireV2.TEXTURE_NAMES) if (n.startsWith(g[0])) covered.add(n);
        }
        assertEquals(new HashSet<>(List.of(FireV2.TEXTURE_NAMES)), covered, "every texture name belongs to a group the painter draws");
        for (String n : FireV2.TEXTURE_NAMES) {
            String stem = n.substring(2);
            assertTrue(gen.contains("\"" + n + "\"") || gen.toLowerCase().contains(stem.replaceAll("_[a-d]$", "").toLowerCase()), "the generators do not make " + n);
        }
    }

    @Test
    void theOldFireTexturesAndTheKeptSigilsAreAllStillThere() {
        for (String old : new String[]{"fire_tongue", "fire_band", "fire_ribbon", "fire_lion", "flamefx_flame", "flamefx_tongue", "flamefx_ring", "flamefx_ember", "flamefx_lion", "flamefx_burst", "flamefx_smoke",
                "flame_trail", "glow", "spark", "magic_explosion"})
            assertTrue(Files.isRegularFile(PARTICLE.resolve(old + ".png")), old + " was deleted (rule 2: keep the old)");
    }
}
