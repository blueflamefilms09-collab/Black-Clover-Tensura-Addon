package com.newuniverse.nusmp.vfx;

import org.junit.jupiter.api.Test;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Why: the 32 pixel textures of the Wind look are generated by tools/gen_wind_mc_textures.py and read by the painter by name, so the files are pinned: all of them exist with the size of their name, hard
 * alpha, only their five palette colours (the pack palette, or the five greys of the twin that takes the tint), clear corners for the ring and spark sprites; every pack-palette file has a grey twin of the
 * same silhouette; no stray {@code wmc_} file is in the folder (no dead assets); every name is used by the painter; the old wind textures (the swallow among them) are all still there (rule 2).
 */
class WindMcAssetTest {
    private static final Path ROOT = Path.of("").toAbsolutePath();
    private static final Path PARTICLE = ROOT.resolve("src/main/resources/assets/nusmp/textures/particle");

    private static int[] argb(String file) throws IOException {
        BufferedImage img = ImageIO.read(PARTICLE.resolve(file + ".png").toFile());
        assertNotNull(img, file);
        return img.getRGB(0, 0, img.getWidth(), img.getHeight(), null, 0, img.getWidth());
    }

    private static BufferedImage image(String file) throws IOException { return ImageIO.read(PARTICLE.resolve(file + ".png").toFile()); }

    @Test
    void everyTextureIsThereWithItsSizeHardAlphaAndFiveColours() throws IOException {
        List<String> bad = new ArrayList<>();
        Set<Integer> packColours = new HashSet<>(), greyColours = new HashSet<>();
        for (String name : WindMc.TEXTURE_NAMES) for (int f = 0; f < WindMc.FRAMES; f++) for (int t = 0; t < 2; t++) {
            String file = WindMc.fileName(name, f, t == 1);
            assertTrue(Files.isRegularFile(PARTICLE.resolve(file + ".png")), "missing " + file);
            BufferedImage img = image(file);
            int[] px = img.getRGB(0, 0, img.getWidth(), img.getHeight(), null, 0, img.getWidth());
            String problem = WindMc.checkTexture(name, t == 1, img.getWidth(), img.getHeight(), px);
            if (problem != null) bad.add(file + ": " + problem);
            for (int p : px) if ((p >>> 24) != 0) (t == 1 ? greyColours : packColours).add(p & 0xFFFFFF);
        }
        assertTrue(bad.isEmpty(), bad.toString());
        assertTrue(packColours.size() <= 5 && greyColours.size() <= 5, "at most five colours per set: " + packColours.size() + " / " + greyColours.size());
        for (int c : packColours) assertTrue(java.util.Arrays.stream(WindMc.PACK_PALETTE).anyMatch(x -> x == c));
        for (int c : greyColours) assertTrue(java.util.Arrays.stream(WindMc.GREY_PALETTE).anyMatch(x -> x == c));
    }

    @Test
    void theGreyTwinHasTheSilhouetteOfItsPackPaletteTexture() throws IOException {
        for (String name : WindMc.TEXTURE_NAMES) for (int f = 0; f < WindMc.FRAMES; f++) {
            int[] a = argb(WindMc.fileName(name, f, false)), b = argb(WindMc.fileName(name, f, true));
            assertEquals(a.length, b.length);
            for (int i = 0; i < a.length; i++) assertEquals(a[i] >>> 24, b[i] >>> 24, name + "_" + f + " pixel " + i);
        }
    }

    @Test
    void noStrayWmcFileAndTheTwoFramesDiffer() throws IOException {
        Set<String> expected = new HashSet<>();
        for (String p : WindMc.allTextures()) expected.add(p.substring(p.lastIndexOf('/') + 1));
        Set<String> found = new HashSet<>();
        File[] files = PARTICLE.toFile().listFiles((d, n) -> n.startsWith(WindMc.PREFIX));
        assertNotNull(files);
        for (File f : files) found.add(f.getName());
        assertEquals(expected, found, "the wmc_ files and the list in WindMc must be the same set");
        for (String name : WindMc.TEXTURE_NAMES) {
            if (name.equals("streak")) continue;                             // the streak is one shape in both frames (the flip only swaps the neighbours)
            assertTrue(!java.util.Arrays.equals(argb(WindMc.fileName(name, 0, false)), argb(WindMc.fileName(name, 1, false))), name + ": the two flip-book frames are identical");
        }
    }

    @Test
    void everyNameIsUsedByThePainterAndTheGeneratorMakesIt() throws IOException {
        String layer = Files.readString(ROOT.resolve("src/main/java/com/newuniverse/nusmp/vfx/client/layer/WindMcLayer.java"), StandardCharsets.UTF_8);
        layer = layer.replaceAll("(?s)/\\*.*?\\*/", "").replaceAll("//[^\n]*", "");
        String gen = Files.readString(ROOT.resolve("tools/gen_wind_mc_textures.py"), StandardCharsets.UTF_8);
        for (String name : WindMc.TEXTURE_NAMES) {
            String constant = name.toUpperCase();
            int uses = layer.split("tex\\(" + constant + ",", -1).length - 1;
            assertTrue(uses >= 1, name + " is generated but the painter never draws it (a dead asset)");
            assertTrue(gen.contains("\"" + name + "\""), "the generator does not list " + name);
        }
    }

    @Test
    void theOldWindTexturesAreAllStillThere() {
        for (String old : new String[]{"wind_slash", "wind_streak", "wind_band", "wind_swallow", "wind_leaf"})
            assertTrue(Files.isRegularFile(PARTICLE.resolve(old + ".png")), old + " was deleted (rule 2: keep the old)");
    }
}
