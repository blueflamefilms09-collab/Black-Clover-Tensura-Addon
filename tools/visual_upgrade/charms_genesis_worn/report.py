"""report: measures the upgraded items with the same code as the baseline and writes docs/visual_upgrade/charms_genesis_worn_after.json (per item: the same fields,
the component ratios and V) plus the ratio table of the doc (docs/visual_upgrade/charms_genesis_worn_ratios.md).

    python3 -B tools/visual_upgrade/charms_genesis_worn/report.py

The baseline file is read, never recomputed (the baseline is what the files were before the upgrade, measured once in the first commit of the slice).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import metrics as MT  # noqa: E402
import roster as R  # noqa: E402

BASE = os.path.join(MT.ROOT, "docs", "visual_upgrade", "charms_genesis_worn_baseline.json")
AFTER = os.path.join(MT.ROOT, "docs", "visual_upgrade", "charms_genesis_worn_after.json")
TABLE = os.path.join(MT.ROOT, "docs", "visual_upgrade", "charms_genesis_worn_ratios.md")
TARGET = {"GOD": 5.0, "GENESIS": 20.0}


def compute():
    with open(BASE, encoding="utf8") as fh:
        base = json.load(fh)
    cats = MT.Catalogs(upgrade=True)
    before = {i["id"]: i for i in base["items"]}
    items = []
    for it in R.ITEMS:
        a = MT.measure_item(it, cats, upgrade=True)
        b = before[it[0]]
        comp, v = MT.ratios(b, a)
        a["components"] = {k: round(x, 2) for k, x in comp.items()}
        a["V_before"] = 1.0
        a["V_after"] = round(v, 2)
        a["target"] = TARGET[a["grade"]]
        a["meets_target"] = v >= TARGET[a["grade"]]
        # the per-view mesh ratio, the numbers the brief asks for item by item
        a["mesh_ratio"] = {"hand": round(a["hand"]["quads"] / max(1, b["hand"]["quads"]), 2), "worn": round(a["worn"]["quads"] / max(1, b["worn"]["quads"]), 2)}
        a["texel_ratio"] = {"hand": round(a["hand"]["painted_texels"] / max(1, b["hand"]["painted_texels"]), 1), "worn": round(a["worn"]["painted_texels"] / max(1, b["worn"]["painted_texels"]), 1)}
        items.append(a)
    return base, items


def main():
    base, items = compute()
    summary = {}
    for g in ("GOD", "GENESIS"):
        xs = [i for i in items if i["grade"] == g]
        summary[g] = {"items": len(xs), "V_after_mean": round(sum(i["V_after"] for i in xs) / len(xs), 2), "V_after_min": min(i["V_after"] for i in xs),
                      "meeting_target": sum(1 for i in xs if i["meets_target"]), "target": TARGET[g]}
    doc = {"slice": "charms_genesis_worn", "what": "measured from the files of the visual upgrade (tools/visual_upgrade/charms_genesis_worn/report.py), same code as the baseline",
           "weights": MT.WEIGHTS, "summary": summary, "items": items}
    with open(AFTER, "w", newline="\n") as fh:
        json.dump(doc, fh, indent=1)
        fh.write("\n")
    lines = ["# charms_genesis_worn: measured ratios (generated by tools/visual_upgrade/charms_genesis_worn/report.py)", "",
             "V = 0.35 mesh + 0.20 texture + 0.15 passes + 0.20 ambient + 0.10 animation, each component = (after summed over the hand and the worn view) / max(before summed, 1); V_before = 1.",
             "These are proxy counts from the model files and textures, not a judgement of how the items look.", "",
             "| item | grade | quads before (hand/worn) | quads after (hand/worn) | texels after (hand) | passes | ambient layers | groups | mesh x | texture x | passes x | ambient x | anim x | V after | target |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    bmap = {i["id"]: i for i in base["items"]}
    for a in items:
        b = bmap[a["id"]]
        c = a["components"]
        lines.append("| %s | %s | %d / %d | %d / %d | %d | %d / %d | %d / %d | %d / %d | %.1f | %.1f | %.1f | %.1f | %.1f | **%.1f** | %.0f%s |" % (
            a["id"], a["grade"], b["hand"]["quads"], b["worn"]["quads"], a["hand"]["quads"], a["worn"]["quads"], a["hand"]["painted_texels"], b["hand"]["passes"], a["hand"]["passes"],
            b["hand"]["ambient_layers"] + b["worn"]["ambient_layers"], a["hand"]["ambient_layers"] + a["worn"]["ambient_layers"], b["hand"]["groups"] + b["worn"]["groups"],
            a["hand"]["groups"] + a["worn"]["groups"], c["mesh"], c["texture"], c["passes"], c["ambient"], c["animation"], a["V_after"], a["target"], "" if a["meets_target"] else " (not met)"))
    lines += ["", "| grade | items | mean V after | lowest V after | items at the target | target |", "|---|---|---|---|---|---|"]
    for g, s in summary.items():
        lines.append("| %s | %d | %.2f | %.2f | %d | %.0f |" % (g, s["items"], s["V_after_mean"], s["V_after_min"], s["meeting_target"], s["target"]))
    with open(TABLE, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    for g, s in summary.items():
        print(g, s)
    for a in items:
        print("%-42s %-8s V %6.2f  mesh %5.1f tex %6.1f pass %4.1f amb %4.1f anim %5.1f %s" % (a["id"], a["grade"], a["V_after"], a["components"]["mesh"], a["components"]["texture"], a["components"]["passes"],
                                                                                           a["components"]["ambient"], a["components"]["animation"], "" if a["meets_target"] else "  <-- below target"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
