"""build: bakes the items of the slice `charms_genesis_worn`.

    python3 -B tools/visual_upgrade/charms_genesis_worn/build.py [id ...] [--preview]      build the given items (default: all) and, with --preview, a quick sheet each

The registration hook for the shared generator entry points is one line at the end of tools/relics/gen_worn_all.py (`main`): it calls `build.main([])` of this directory.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import metrics as MT  # noqa: E402
import roster as R  # noqa: E402
import spec as SP  # noqa: E402
import vupreview as VP  # noqa: E402

PREVIEW_DIR = os.path.join(MT.ROOT, "build", "vu_preview")


def all_items():
    out = []
    import items_stones
    out += items_stones.ITEMS
    for modname in ("items_stones2", "items_stones3", "items_god_a", "items_god_b", "items_god_c", "items_genesis", "items_genesis2", "items_genesis3"):
        try:
            mod = __import__(modname)
        except ImportError:
            continue
        out += mod.ITEMS
    return out


def quick_preview(item, outdir=PREVIEW_DIR):
    info = R.BY_ID[item.rid]
    pal = info[4]
    path = os.path.join(MT.VU_MODELS, item.rid + ".txt")
    pieces = [(path, "body", False)]
    zoom = (-14, 14, -14, 14)
    rows = []
    for t in (0.0, 40.0):
        row = []
        for label, view in (("front", (0, 0)), ("three", (35, 14)), ("side", (90, 0))):
            row.append(("%s t=%d" % (label, t), VP.tile(pieces, pal, view, zoom, (300, 300), t=t, figure=False)))
        rows.append(row)
    os.makedirs(outdir, exist_ok=True)
    return VP.sheet(rows, os.path.join(outdir, item.rid + ".png"), title=item.rid)


def write_data(items):
    """overrides.txt, the fx jsons, act_vfx.txt and the caps table of the slice (rewritten from the full item list when no id was named)."""
    import json
    os.makedirs(MT.VU_FX, exist_ok=True)
    lines = ["# visual upgrade override table (client/relics/vu/VuOverrides): the models an upgraded relic is held and worn as.",
             "# generated by tools/visual_upgrade/charms_genesis_worn/build.py, do not edit. visual.upgrade=false (nusmp-visual-charms-client.toml) ignores this file."]
    acts = ["# visual upgrade act effects (relics/vu/VuActTable): act <relic id> <act key | *> SHAPE:RRGGBB:power:duration:where ...",
            "# generated by tools/visual_upgrade/charms_genesis_worn/build.py, do not edit."]
    for it in items:
        if not os.path.exists(os.path.join(MT.VU_MODELS, it.rid + ".txt")):
            continue                                                                   # not baked yet (a partial run while developing)
        h, w = SP.hand_line(it)
        lines += [h, w]
        with open(os.path.join(MT.VU_FX, it.rid + ".json"), "w", newline="\n") as fh:
            json.dump(SP.fx_json(it), fh, indent=1)
            fh.write("\n")
        acts += SP.act_lines(it)
    with open(os.path.join(MT.VU_DIR, "overrides.txt"), "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    act_dir = os.path.join(MT.ROOT, "src", "main", "resources", "data", "nusmp", "visual_upgrade")
    os.makedirs(act_dir, exist_ok=True)
    with open(os.path.join(act_dir, "act_vfx.txt"), "w", newline="\n") as fh:
        fh.write("\n".join(acts) + "\n")
    caps = ["# per-grade caps of the visual upgrade models of the slice charms_genesis_worn (tests: VuCharmsBudgetTest). Documented in docs/visual_upgrade/charms_genesis_worn.md.",
            "# grade mesh_vertices drawn_vertices lod_percent", ]
    for g, c in SP.CAPS.items():
        caps.append("%s %d %d %d" % (g, c["mesh_vertices"], c["drawn_vertices"], int(c["lod_ratio"] * 100)))
    with open(os.path.join(MT.VU_DIR, "caps_charms_genesis_worn.txt"), "w", newline="\n") as fh:
        fh.write("\n".join(caps) + "\n")


def wave_acts():
    """relic id -> the act keys its RelicDef declares, read from the wave sources (the generator checks its act effects against them)."""
    import glob
    import re
    root = os.path.join(MT.ROOT, "src", "main", "java", "com", "newuniverse", "nusmp", "relics", "wave")
    src = {f: open(f, encoding="utf8").read() for f in glob.glob(root + "/*.java")}
    consts = {}
    for t in src.values():
        for m in re.finditer(r'(ID_[A-Z]+)\s*=\s*"([a-z0-9_]+)"', t):
            consts.setdefault(m.group(1), m.group(2))
    out = {}
    for t in src.values():
        for m in re.finditer(r'RelicDef\.of\((?:\w+Tune\.)?(ID_[A-Z]+|"[a-z0-9_]+"),', t):
            rid = consts.get(m.group(1)) if m.group(1).startswith("ID_") else m.group(1).strip('"')
            end = t.find("out.accept", m.end())
            body = t[m.end():end if end > 0 else m.end() + 4000]
            out[rid] = re.findall(r'Act\.of\("([^"]+)"', body)
    return out


def verify_acts(items):
    acts = wave_acts()
    bad = []
    for it in items:
        have = acts.get(it.rid)
        if have is None:
            bad.append("%s: no RelicDef found in the wave sources" % it.rid)
            continue
        for k in it.acts:
            if k != "*" and k not in have:
                bad.append("%s: act %s is not one of %s" % (it.rid, k, have))
        for k in have:
            if k not in it.acts and "*" not in it.acts:
                bad.append("%s: act %s has no effect" % (it.rid, k))
    if bad:
        raise SystemExit("act effects do not match the relics:\n  " + "\n  ".join(bad))


def main(argv):
    import fxtex
    import vu
    fxtex.save_fx(os.path.join(vu.TEX_DIR, "vu_fx.png"))
    only = [a for a in argv if not a.startswith("--")]
    items = [i for i in all_items() if not only or i.rid in only]
    for it in items:
        SP.bake(it)
        if "--preview" in argv:
            print("  preview", quick_preview(it))
    verify_acts(all_items())
    write_data(all_items())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
elif __name__ == "vu_charms_genesis_worn":                  # run by the one hook line at the end of tools/relics/gen_worn_all.py main()
    main([])
