def strokes(ch):
    """The line segments ((x0, y0), (x1, y1)) of a letter (unknown characters give none)."""
    out = []
    for poly in _L.get(ch.upper(), []):
        for a, b in zip(poly, poly[1:]):
            out.append((a, b))
    return out
