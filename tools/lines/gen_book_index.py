#!/usr/bin/env python3
"""Generate assets/nusmp/skill_books.json: the table of every unique skill book: the registry reads it at start-up (one Unique skill per line), and both sides use it to name and describe the book, the skill, its modes (arts) and its passives.

usage: python3 tools/lines/gen_book_index.py [--check] [--rows-dir DIR] [--routes-dir DIR] [--out FILE]

WHY: the server syncs a client only the lines that player owns (docs/skillbooks_unique.md, scale rule). A Skill Book of a line the player has not unlocked yet (found in a chest,
dropped by a boss, bought) must still show the right cover colour, the right franchise cover and the line's name, and the registry on the client has no such route. So the
assets ship a small table (a few dozen bytes a line, about 30 KB for 283 lines): line id -> book id, name, book name, colour, franchise. It is generated from the SAME sources as
the routes themselves (the hand-built route json files plus the generated rows, see route_sources.py), so it cannot drift from them; a unit test (LineAssetsTest) fails when a shipped
route is missing from it. 'franchises' fixes the order of the item property nusmp:franchise (index + 1) / 20: append only.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import route_sources as RS  # noqa: E402
from lines_lib import FRANCHISES  # noqa: E402

OUT = os.path.join(RS.ROOT, "src", "main", "resources", "assets", "nusmp", "skill_books.json")
PROP_STEPS = 20


def build(lines):
    franchises = list(FRANCHISES.keys())
    table = {}
    for lid, l in lines.items():
        table[lid] = {"book": l["book"], "name": l["name"], "book_name": l["book_name"], "color": l["color"],
                      "franchise": l["franchise"] if l["franchise"] in franchises else "",
                      "desc": l.get("desc", ""), "book_lore": l.get("book_lore", ""), "arts": l.get("arts", []), "passives": l.get("passives", [])}
    return {"_comment": "GENERATED by tools/lines/gen_book_index.py from the route files and rows. Do not edit by hand.", "franchises": franchises, "prop_steps": PROP_STEPS, "lines": table}


def main():
    args = sys.argv[1:]
    rows_dir = args[args.index("--rows-dir") + 1] if "--rows-dir" in args else None
    routes_dir = args[args.index("--routes-dir") + 1] if "--routes-dir" in args else None
    out = args[args.index("--out") + 1] if "--out" in args else OUT
    lines = RS.collect(rows_dir, routes_dir)
    data = build(lines)
    text = json.dumps(data, indent=1, ensure_ascii=False) + "\n"
    if "--check" in args:
        if not os.path.exists(out) or open(out, encoding="utf-8").read() != text:
            print("skill_books.json is stale: run python3 tools/lines/gen_book_index.py")
            sys.exit(1)
        print("ok: skill_books.json is current (%d lines)" % len(lines))
        return
    os.makedirs(os.path.dirname(out), exist_ok=True)
    if not os.path.exists(out) or open(out, encoding="utf-8").read() != text:
        open(out, "w", encoding="utf-8", newline="\n").write(text)
    unknown = [lid for lid, l in lines.items() if l["franchise"] not in FRANCHISES]
    print("ok: %d lines written%s" % (len(lines), ("; no franchise cover for: " + ", ".join(unknown)) if unknown else ""))


if __name__ == "__main__":
    main()
