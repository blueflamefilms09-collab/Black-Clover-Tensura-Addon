#!/usr/bin/env python3
"""Writes ONE placeholder tree background (assets/nusmp/textures/gui/skill_trees/fire_dragon_slayer.png) so the engine's background loader can be seen working.

WHY: the 283 real backgrounds are generated by another job (tools/lines/gen_backgrounds.py); this engine only loads them. A placeholder for one existing route proves the whole path (default file name
from the route id, PNG header read, cover scaling, veil) in the game. When the real generator runs it overwrites this file. usage: python3 tools/lines/placeholder_bg.py
"""
import math
import os
import random

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src/main/resources/assets/nusmp/textures/gui/skill_trees")


def main():
    w, h = 512, 320
    img = Image.new("RGB", (w, h))
    px = img.load()
    rnd = random.Random(7)
    flames = [(rnd.uniform(0, w), rnd.uniform(40, 120), rnd.uniform(18, 60)) for _ in range(28)]
    for y in range(h):
        for x in range(w):
            t = y / h
            r, g, b = 22 + 70 * t, 8 + 14 * t, 10 + 8 * t                     # a dark red sky
            for fx, fh, fw in flames:                                         # tongues of flame rising from the bottom
                d = abs(x - fx) / fw
                top = h - fh * (1.0 - d * d) * (0.8 + 0.2 * math.sin(fx + y * 0.05))
                if d < 1.0 and y > top:
                    k = (y - top) / max(1.0, h - top)
                    r, g, b = max(r, 120 + 120 * k), max(g, 30 + 90 * k * k), max(b, 10)
            px[x, y] = (int(min(255, r)), int(min(255, g)), int(min(255, b)))
    os.makedirs(OUT, exist_ok=True)
    img.save(os.path.join(OUT, "fire_dragon_slayer.png"))
    print("ok")


if __name__ == "__main__":
    main()
