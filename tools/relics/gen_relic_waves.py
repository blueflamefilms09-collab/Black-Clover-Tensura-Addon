#!/usr/bin/env python3
"""Writes the generated relic waves (1.70.0 and later) from the row tables: the Java defs, the sprites, the item models and the language lines.

    python3 tools/relics/gen_relic_waves.py            # writes everything
    python3 tools/relics/gen_relic_waves.py --check    # exit 1 when a file on disk differs

For each batch module `relic_rows_<name>.py` (BATCHES below) it writes `relics/wave/Wave<N>.java` (a def list with the same shape as the older waves, so RelicRenderCoverageTest, relic_inventory.py and
gen_curios_tags.py read it unchanged), `textures/item/<id>.png`, `models/item/<id>.json` (builtin/entity, the hand renderer draws it) and `<id>_icon.json` (the flat sprite for the inventory), and
a marked block of lang lines in en_us.json (`item.nusmp.<id>`, `.card`, `.desc`). Run gen_curios_tags.py afterwards. Why generated: hundreds of relics from one table of names, colours,
passives and ability shapes (Wave31Acts) cannot sensibly be hand-written Java, and this keeps every one of them in the same, tested form."""
import importlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import relic_icon_lib as ICONS  # noqa: E402
import relic_rows_lib as RL  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
RES = os.path.join(ROOT, "src", "main", "resources", "assets", "nusmp")
WAVE_DIR = os.path.join(ROOT, "src", "main", "java", "com", "newuniverse", "nusmp", "relics", "wave")
LANG = os.path.join(RES, "lang", "en_us.json")
BEGIN, END = "_generated.relic_waves.begin", "_generated.relic_waves.end"

# (wave number, batch module, title of the wave in the Javadoc)
BATCHES = [(31, "relic_rows_rezero", "Re:Zero"), (32, "relic_rows_abyss", "Made in Abyss"), (33, "relic_rows_trk", "Tomb Raider King"),
           (34, "relic_rows_jjk", "Jujutsu Kaisen"), (35, "relic_rows_fate", "the Fate series"), (36, "relic_rows_rift", "the dimensional rifts and the waypoint")]


def all_rows():
    """Every row of every batch module that exists, in wave order (the worn-model catalog and the uniqueness check read this)."""
    out = []
    for _n, mod, title in BATCHES:
        try:
            rows = importlib.import_module(mod).ROWS
        except ModuleNotFoundError:
            continue
        for r in rows:
            r["series"] = title
        out += rows
    return out


def hexc(c):
    return "0x" + c.lstrip("#").upper()


def java_for(n, title, rows):
    lines = []
    for r in rows:
        chain = 'RelicDef.of("%s", "%s", Grade.%s, RelicSlot.%s)' % (r["id"], RL.jesc(r["name"]), r["grade"], r["slot"])
        if r["att"]:
            chain += ".attune()"
        chain += "\n                .palette(%s, %s, %s).look(Look.%s)" % (hexc(r["pal"][0]), hexc(r["pal"][1]), hexc(r["pal"][2]), r["look"])
        chain += '\n                .desc("%s")' % RL.jesc(r["desc"])
        for tok in r["passives"].split():
            chain += "\n                .passive(%s)" % RL.passive_java(tok)
        for i, a in enumerate(r["acts"]):
            chain += "\n                .act(%s)" % RL.act_java(a, i)
        lines.append("        out.accept(%s);\n" % chain)
    body = "\n".join(lines)
    return '''package com.newuniverse.nusmp.relics.wave;

import com.newuniverse.nusmp.relics.Act;
import com.newuniverse.nusmp.relics.Grade;
import com.newuniverse.nusmp.relics.Look;
import com.newuniverse.nusmp.relics.Passive;
import com.newuniverse.nusmp.relics.RelicDef;
import com.newuniverse.nusmp.relics.RelicSlot;
import net.minecraft.world.entity.ai.attributes.AttributeModifier.Operation;

import java.util.function.Consumer;

/**
 * Relics of Many Worlds, generated wave %d (1.70.0 and later): %d relics inspired by %s. GENERATED by tools/relics/gen_relic_waves.py from tools/relics/%s.py: edit the table, not this file.
 * Every ability is one of the shapes of {@link Wave31Acts}; the passives are attribute modifiers, resistances, standing effects and lent Tensura skills of the older waves' own kinds. The names
 * and places are inspired by the work, the rules text is the mod's own; none is a weapon (no mesh) or a consumable (no hand model).
 */
public final class Wave%d {
    private Wave%d() {}

    public static void defs(Consumer<RelicDef> out) {
%s    }

    /** No game-bus listeners: everything these relics do is a passive or an act of the relic core. */
    public static void hooks() {}
}
''' % (n, len(rows), title, [b for b in BATCHES if b[0] == n][0][1], n, n, body)


def write(path, data, check, binary=False):
    mode = "rb" if binary else "r"
    cur = None
    if os.path.exists(path):
        with open(path, mode, **({} if binary else {"encoding": "utf-8"})) as f:
            cur = f.read()
    if cur == data:
        return 0
    if check:
        print("STALE", os.path.relpath(path, ROOT))
        return 1
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb" if binary else "w", **({} if binary else {"encoding": "utf-8", "newline": "\n"})) as f:
        f.write(data)
    return 0


def existing_ids():
    sys.path.insert(0, HERE)
    import relic_inventory as RI
    out = set()
    rels = RI.relics()
    rels = rels[0] if isinstance(rels, tuple) else rels
    for d in rels:
        out.add(d["id"])
    return out


def main(check):
    bad = 0
    all_rows = []
    seen = set()
    existing = existing_ids()
    gen_files = {os.path.join(WAVE_DIR, "Wave%d.java" % n) for n, _, _ in BATCHES}
    for n, mod, title in BATCHES:
        try:
            rows = importlib.import_module(mod).ROWS
        except ModuleNotFoundError:
            continue
        for r in rows:
            r["series"] = title
            if r["id"] in seen:
                raise SystemExit("duplicate id " + r["id"])
            seen.add(r["id"])
        all_rows += rows
        bad += write(os.path.join(WAVE_DIR, "Wave%d.java" % n), java_for(n, title, rows), check)
    # ids that an older wave already defines are refused (inventory reads the wave sources, including ours: drop ours first)
    ours = {r["id"] for r in all_rows}
    clash = sorted(i for i in existing & ours if not any(i in open(f, encoding="utf-8").read() for f in gen_files if os.path.exists(f)))
    taken = set()
    for r in all_rows:
        for bump in range(50):                      # no two relics may have the same sprite: the id's seed is bumped until this one is new
            icon = ICONS.render(r["icon"], r["pal"][0], r["pal"][1], r["pal"][2], r["id"], bump)
            if icon not in taken:
                break
        else:
            raise SystemExit("no distinct sprite for " + r["id"])
        taken.add(icon)
        bad += write(os.path.join(RES, "textures", "item", r["id"] + ".png"), icon, check, binary=True)
        model = json.dumps({"parent": "minecraft:builtin/entity", "gui_light": "front", "textures": {"particle": "nusmp:item/" + r["id"]}}, indent=2) + "\n"
        bad += write(os.path.join(RES, "models", "item", r["id"] + ".json"), model, check)
        icon_model = json.dumps({"parent": "minecraft:item/generated", "textures": {"layer0": "nusmp:item/" + r["id"]}}, indent=2) + "\n"
        bad += write(os.path.join(RES, "models", "item", r["id"] + "_icon.json"), icon_model, check)
    bad += write_lang(all_rows, check)
    print("%d generated relics in %d waves" % (len(all_rows), len(BATCHES)))
    return 1 if bad else 0


def write_lang(rows, check):
    with open(LANG, encoding="utf-8") as f:
        text = f.read()
    block = ['  "%s": "",\n' % BEGIN]
    for r in rows:
        d = json.dumps(r["desc"], ensure_ascii=False)
        block.append('  %s: %s,\n  %s: %s,\n  %s: %s,\n' % (json.dumps("item.nusmp." + r["id"]), json.dumps(r["name"], ensure_ascii=False), json.dumps("item.nusmp." + r["id"] + ".card"),
                                                          json.dumps("%s Grade. %s" % (r["grade"].title(), r["desc"]), ensure_ascii=False), json.dumps("item.nusmp." + r["id"] + ".desc"), d))
    block.append('  "%s": ""' % END)
    block = "".join(block)
    if '"%s"' % BEGIN in text:
        a = text.index('  "%s"' % BEGIN)
        b = text.index('  "%s": ""' % END) + len('  "%s": ""' % END)
        new = text[:a] + block + text[b:]
    else:
        i = text.rindex("}")
        head = text[:i].rstrip()
        if not head.endswith(","):
            head += ","
        new = head + "\n" + block + "\n" + text[i:]
    json.loads(new)
    if new == text:
        return 0
    if check:
        print("STALE lang")
        return 1
    with open(LANG, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
