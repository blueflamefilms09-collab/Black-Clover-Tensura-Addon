"""Builds the whole hand model library: every signature hand model, every consumable model, and the catalog that says which relic is held as which.

    python3 tools/relics/gen_hand_all.py [--check] [--only name,name]

Writes src/main/resources/assets/nusmp/relic_hand/<model>.txt and relic_hand/catalog.txt (the `sig <relic id> <model>` lines; transforms.txt is hand-written data and is
never touched). With --check it only reports the vertex count of every model and fails when one is over the cap or when a relic is assigned a model that does not exist.
A new relic gets its hand model with one function in a gen_hand_*.py module and one line in its ASSIGN table (docs/relic_hand_models.md).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_hand_kit as K  # noqa: E402
import gen_hand_sig  # noqa: E402
import gen_hand_trinkets  # noqa: E402
import gen_hand_consumables  # noqa: E402
import gen_hand_garments  # noqa: E402
import relic_inventory as RI  # noqa: E402

MODULES = (gen_hand_sig, gen_hand_trinkets, gen_hand_consumables, gen_hand_garments)
WHOLE = {"suit_astral", "chest_shadow", "chest_mist"}      # worn chest models that are a whole garment already (a long suit, a hooded robe): no garment body goes under them


def collect():
    models, assign = {}, {}
    for mod in MODULES:
        for name, fn in mod.MODELS.items():
            if name in models:
                raise SystemExit("two generators define the hand model " + name)
            models[name] = fn
        for rid, ms in mod.ASSIGN.items():
            if rid in assign:
                raise SystemExit("two generators assign the relic " + rid)
            assign[rid] = ms
    return models, assign


def _worn_catalog():
    relics, looks = {}, {}
    for line in open(os.path.join(K.L.WORN_DIR, "catalog.txt"), encoding="utf8"):
        v = line.split()
        if len(v) >= 3 and v[0] == "relic":
            relics[v[1]] = v[2:]
        elif len(v) >= 4 and v[0] == "look":
            looks[(v[1], v[2])] = v[3:]
    return relics, looks


def _model_verts(name, models):
    """Vertices of a hand model (built on the spot) or of a worn model file."""
    if name in models:
        return models[name]().vertex_count()
    path = os.path.join(K.L.WORN_DIR, name + ".txt")
    return 4 * sum(1 for line in open(path, encoding="utf8") if line.startswith("q "))


def chest_assign(models):
    """The hand form of every chest relic: a garment body of its look (plate, robe, coat, vest) under the relic's own worn ornaments; a chest model that is a whole garment already
    (WHOLE) is held as it is (no line: the worn library draws it)."""
    relics, looks = _worn_catalog()
    out = {}
    rs, _ = RI.relics()
    for r in rs:
        if r["slot"] != "CHEST" or r["adopted"]:
            continue
        pieces = relics.get(r["id"]) or looks.get(("CHEST", r["look"]))
        if not pieces:
            continue
        if any(p.split("@")[0].rstrip("~") in WHOLE for p in pieces):
            continue
        garment = gen_hand_garments.GARMENT_OF_LOOK.get(r["look"], "garment_cuirass")
        assert garment in models, garment
        rest = sum(_model_verts(p.split("@")[0].rstrip("~"), models) for p in pieces)
        for g in (garment, garment + "_lite"):                 # the full body if the relic's ornaments leave room for it, else the light one, else only the ornaments
            if rest + _model_verts(g, models) <= K.MODEL_CAP:
                out[r["id"]] = [g] + pieces
                break
    return out


def catalog_text(assign):
    out = ["# hand catalog: which relic is held as which hand model. generated by tools/relics/gen_hand_all.py, do not edit.",
           "# sig <relic id> <model[@anchor][~]> ...   the models a relic is held as (files relic_hand/<model>.txt, else relic_worn/<model>.txt)"]
    for rid in sorted(assign):
        out.append("sig %s %s" % (rid, " ".join(assign[rid])))
    return "\n".join(out) + "\n"


def main(argv):
    check = "--check" in argv
    only = None
    if "--only" in argv:
        only = set(argv[argv.index("--only") + 1].split(","))
    models, assign = collect()
    for rid, ms in chest_assign(models).items():
        if rid in assign:
            raise SystemExit("two generators assign the relic " + rid)
        assign[rid] = ms
    bad = [(rid, n) for rid, ms in assign.items() for n in ms if n.split("@")[0].rstrip("~") not in models and not os.path.exists(os.path.join(K.L.WORN_DIR, n.split("@")[0].rstrip("~") + ".txt"))]
    if bad:
        print("relics assigned a model that does not exist:", bad)
        return 1
    os.makedirs(K.HAND_DIR, exist_ok=True)
    verts = {}
    used = {n.split("@")[0].rstrip("~") for ms in assign.values() for n in ms}
    unused = sorted(set(models) - used)

    def model_verts(n):
        if n in verts:
            return verts[n]
        path = os.path.join(K.L.WORN_DIR, n + ".txt")
        return 4 * sum(1 for line in open(path, encoding="utf8") if line.startswith("q "))
    for name, fn in sorted(models.items()):
        if (only and name not in only) or name in unused:                  # a model no relic is held as is not written (a garment body that no chest relic had room for)
            continue
        m = fn()
        verts[name] = m.vertex_count()
        if not check:
            K.L.write_model(m, os.path.join(K.HAND_DIR, name + ".txt"))
    if unused:
        print("not written (no relic is held as them):", ", ".join(unused))
    if "--verbose" in argv:
        for n, v in sorted(verts.items()):
            print("  %-28s %5d" % (n, v))
    over = {n: v for n, v in verts.items() if v > K.MODEL_CAP}
    if not only:
        for rid, ms in assign.items():
            total = sum(model_verts(n.split("@")[0].rstrip("~")) for n in ms)
            if total > K.MODEL_CAP:
                over[rid] = total
    print("%d models, %d relics assigned, most vertices %d (%s), cap %d" % (len(verts), len(assign), max(verts.values()), max(verts, key=verts.get), K.MODEL_CAP))
    if over:
        print("over the cap:", over)
        return 1
    if not check and not only:
        with open(os.path.join(K.HAND_DIR, "catalog.txt"), "w", newline="\n") as fh:
            fh.write(catalog_text(assign))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
