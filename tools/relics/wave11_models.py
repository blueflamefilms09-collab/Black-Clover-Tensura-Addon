# ================================================================ shared helpers
def spike(part, origin, direction, length, r, sides=6, belly=0.0):
    """A cone / thorn from `origin` along `direction` (a claw, a horn, a studded point); belly > 0 swells the middle."""
    st = [(0.0, r, r), (length * 0.35, r * (1.0 + belly), r * (1.0 + belly)), (length, 0.0, 0.0)]
    return ml.loft(part, np.asarray(direction, float), origin, st, ml.circle(1.0, sides))


def torus(part, centre, radius, tube, plane="z", n=18, sides=6):
    """A ring (a guard ring, a buckle, a pommel ring) lying in the xy plane ('z': facing the viewer) or the xz plane ('y': a washer)."""
    cx, cy, cz = centre
    path = []
    for i in range(n + 1):
        a = 2 * math.pi * (i % n) / n
        path.append((cx + radius * math.cos(a), cy + radius * math.sin(a), cz) if plane == "z" else (cx + radius * math.cos(a), cy, cz + radius * math.sin(a)))
    return ml.sweep(part, path, ml.circle(tube, sides), caps=(False, False))


def wrap_rings(part, y0, y1, r, n, h=0.45, sides=12, oval=1.0):
    """n thin raised rings between y0 and y1 (a cord or leather binding)."""
    for i in range(n):
        ml.collar(part, y0 + (y1 - y0 - h) * i / max(1, n - 1), r, h, lip=h * 0.3, sides=sides, oval=oval)


def curve(f, y0, y1, n, z=0.0):
    """Path points (f(y), y, z) from y0 to y1."""
    return [(f(y0 + (y1 - y0) * i / n), y0 + (y1 - y0) * i / n, z) for i in range(n + 1)]


def glow_part(atlas, part, rgb, strength=1.0, core=0.3):
    """The whole part also shines on the additive glow skin."""
    w.paint_part(atlas, part, lambda c: w.set_glow(c, rgb, strength, core=core))


def tint_part(atlas, part, rgb, k=0.7):
    w.paint_part(atlas, part, lambda c: w.tint(c.img, rgb, k))


def scale_pattern(c, size, dark=0.82, light=1.12):
    """Fish-scale modulation of a painted patch, drawn from the model coordinates (dominant groups: A across, B along)."""
    row = np.floor(c.B / size)
    col = c.A / size + 0.5 * (row % 2)
    fx = col - np.floor(col) - 0.5
    fy = (c.B / size - row) - 0.5
    d = np.sqrt(fx * fx + (fy * 0.9) ** 2)
    m = np.where(d > 0.42, dark, light - 0.3 * d)
    c.img[..., :3] = np.clip(c.img[..., :3] * m[..., None], 0, 255)


def run(item_id, build):
    m, atlas, kw = build()
    extra = kw.pop("extra", None)
    w.finish(item_id, m, atlas, **kw)
    if extra:
        extra()


def write_state(m, atlas, mesh_id):
    """Writes another mesh of the same weapon (a draw or loaded state) beside the rest mesh: same placement, same skin (the .txt only)."""
    n = m.write_txt(os.path.join(w.MESH_DIR, mesh_id + ".txt"), atlas, normals="vertex", comment="generated by tools/relics/wave11_models.py")
    print(f"{mesh_id}: {n} quads")


w.write_state = write_state


def main(only=None):
    for item_id in MODELS:
        if only and item_id not in only:
            continue
        mod = importlib.import_module(MODULES[item_id])
        run(item_id, getattr(mod, item_id))


if __name__ == "__main__":
    main(sys.argv[1:])
