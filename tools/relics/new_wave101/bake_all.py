"""Bakes the twelve worn / held models of wave 101 (the visual upgrade kit of tools/visual_upgrade/charms_genesis_worn, Genesis caps) and writes the data that wires them in:

    python3 -B tools/relics/new_wave101/bake_all.py [id ...]

  assets/nusmp/visual_upgrade/models/<id>[_worn][_lod].txt, textures/visual_upgrade/<id>[_lod][_glow|_star].png   the models, skins, glow maps and nebulae
  assets/nusmp/visual_upgrade/overrides_genesis_new.txt                                                         the hand / worn lines (read after overrides.txt, like the duel disk file)
  assets/nusmp/visual_upgrade/fx/<id>.json                                                                      the ambient layers (custom particle tokens only)
  data/nusmp/visual_upgrade/act_vfx.txt                                                                         the lines `act <id> <act> ...` of these relics, appended between two marker comments

Nothing of the 27 upgraded relics is touched: their overrides.txt (a test counts its 27 lines) and models stay as they are. Idempotent and deterministic. The hook that runs it with the
shared generators is one line at the end of tools/relics/gen_worn_all.py (main).
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import common as C  # noqa: E402
import metrics as MT  # noqa: E402

BEGIN, END = "# ---- wave 101 (genesis_new) begin ----", "# ---- wave 101 (genesis_new) end ----"


def all_items():
    items = []
    for mod in ("items_a", "items_b", "items_c", "items_d", "items_e", "items_f"):
        try:
            m = __import__(mod)
        except ImportError:
            continue
        items += m.ITEMS
    order = {rid: i for i, rid in enumerate(C.IDS)}
    return sorted(items, key=lambda it: order[it.rid])


def write_overrides(items):
    lines = ["# visual upgrade override table of wave 101 (release 1.111.0), read after overrides.txt (client/relics/vu/VuModels): the models these twelve Genesis relics are held and worn as.",
             "# generated by tools/relics/new_wave101/bake_all.py, do not edit. visual.upgrade=false (nusmp-visual-charms-client.toml) ignores this file."]
    for it in items:
        h, w = C.SP.hand_line(it)
        lines += [h, w]
    with open(os.path.join(MT.VU_DIR, "overrides_genesis_new.txt"), "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


def write_fx(items):
    cp = __import__("runpy").run_path(os.path.join(MT.ROOT, "tools", "visual_upgrade", "custom_particles.py"))["convert"]
    os.makedirs(MT.VU_FX, exist_ok=True)
    for it in items:
        tbl = C.SP.fx_json(it)
        cp(tbl)
        with open(os.path.join(MT.VU_FX, it.rid + ".json"), "w", newline="\n") as fh:
            json.dump(tbl, fh, indent=1)
            fh.write("\n")


def write_acts(items):
    path = os.path.join(MT.ROOT, "src", "main", "resources", "data", "nusmp", "visual_upgrade", "act_vfx.txt")
    text = open(path, encoding="utf-8").read()
    if BEGIN in text:
        text = text[:text.index(BEGIN)].rstrip("\n") + "\n"
    block = [BEGIN]
    for it in items:
        block += C.SP.act_lines(it)
    block.append(END)
    with open(path, "w", newline="\n", encoding="utf-8") as fh:
        fh.write(text + "\n".join(block) + "\n")


def verify(items):
    """The acts of each relic in Wave101.java and the keys of its act effects must be the same set."""
    src = open(os.path.join(MT.ROOT, "src", "main", "java", "com", "newuniverse", "nusmp", "relics", "wave", "Wave101.java"), encoding="utf-8").read()
    bad = []
    for it in items:
        m = re.search(r'RelicDef\.of\("%s",' % it.rid, src)
        if not m:
            bad.append("%s: no RelicDef in Wave101.java" % it.rid)
            continue
        end = src.find("out.accept", m.end())
        have = re.findall(r'Act\.of\("([^"]+)"', src[m.end():end if end > 0 else len(src)])
        if sorted(have) != sorted(it.acts):
            bad.append("%s: acts in the Java %s, act effects %s" % (it.rid, sorted(have), sorted(it.acts)))
    if bad:
        raise SystemExit("act effects do not match the relics:\n  " + "\n  ".join(bad))


def main(argv):
    import fxtex
    only = [a for a in argv if not a.startswith("--")]
    items = all_items()
    verify(items)
    if not os.path.exists(os.path.join(C.V.TEX_DIR, "vu_fx.png")):
        fxtex.save_fx(os.path.join(C.V.TEX_DIR, "vu_fx.png"))
    errors = []
    for it in items:
        if only and it.rid not in only:
            continue
        out = C.SP.bake(it)
        errors += ["%s: %s" % (it.rid, e) for e in out["errors"]]
    if errors:
        raise SystemExit("over the caps:\n  " + "\n  ".join(errors))
    write_overrides(items)
    write_fx(items)
    write_acts(items)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
elif __name__ == "vu_genesis_new":                        # run by the one hook line at the end of tools/relics/gen_worn_all.py main()
    main([])
