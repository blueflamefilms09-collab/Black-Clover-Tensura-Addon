"""Writes the Beast Will forms as geo pieces: per will  bwf_<stem>_arm_<piece>.geo.json (+ animation for the tail / wings), one shared sheet bwf_<stem>.png (+ _glow.png),
and the table docs/beastwill_forms.txt  (stem: pieces).  Usage: python3 forms_export.py [will_id ...]  (all when none)"""
import os, sys, json, math
import numpy as np
from PIL import Image
sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, "..", ".."))
from forms_gen import build, PAL
import firecast_geo_lib as G
from forms_lib import TONES

ROOT = G.ROOT
STEMS = {"shadow_panther": "panther", "elderwood_guardian": "elder", "wind_skimmer": "raptor", "flame_serpent": "serpent", "ridge_wolf": "wolf", "crested_boar": "boar", "thunder_fang_chimera": "chimera"}
ANCHOR = {"acq": "ARM_R", "head": "HEAD", "body": "BODY", "armL": "ARM_L", "armR": "ARM_R", "legL": "LEG_L", "legR": "LEG_R", "tail": "BODY", "wings": "BODY"}
PIVOT = {"tail": (0, 13.0, 2.6), "wingL": (3.4, 21.0, 2.8), "wingR": (-3.4, 21.0, 2.8)}
FACE = {(0, 1): "east", (0, -1): "west", (1, 1): "up", (1, -1): "down", (2, -1): "north", (2, 1): "south"}     # Model names: east = +x side, west = -x side (GeoModelData flips them back)


JAVA = """package com.newuniverse.nusmp.beastwill;

import java.util.Map;

/**
 * Why (3.61.0): which geo pieces each Beast Will form has ({@code bwf_<stem>_arm_<piece>}), so the painter never asks for a file that does not exist (a missing geo file is logged on every reload).
 * GENERATED by tools/beastwill/remake/forms_export.py together with the files and docs/beastwill_forms.txt; BeastWillFormsTest checks the table against the resources. Pure data, no client classes.
 */
public final class BeastWillFormTable {
    private BeastWillFormTable() {}

    private static final Map<String, String> PARTS = Map.ofEntries(
%s);

    /** The pieces of a stem, space separated (head body armL armR legL legR tail wings acq), or an empty string for an unknown stem. */
    public static String parts(String stem) { return PARTS.getOrDefault(stem, ""); }

    public static boolean has(String stem, String piece) { return (" " + parts(stem) + " ").contains(" " + piece + " "); }

    public static java.util.Set<String> stems() { return PARTS.keySet(); }
}
"""


def stem(wid): s = wid[:-5]; return STEMS.get(s, s)


class Shim:
    def __init__(s, sheet): s.w, s.h, s.regions = sheet.W, sheet.H, sheet.reg


def piece_of(b):
    if b.part == "back":
        if b.bone.startswith("tail") or b.bone.startswith("flame"): return "tail"
        return "wings" if b.bone.startswith("wing") else "body"
    return b.part


CLIP_LEN, CLIP_STEPS = 4.8, 24
KIND = {"rot": "rotation", "scale": "scale", "pos": "position"}


def clip_of(sc, bones):
    """the idle clip of a piece: every animated bone is a sum of sines (cycles are whole numbers per clip, so it loops without a seam)"""
    tracks = {}
    for bn in bones:
        d = sc.bonedefs.get(bn)
        if not d or not d["anim"]: continue
        tr = {}
        for kind, axis, amp, cyc, ph in d["anim"]:
            t = tr.setdefault(KIND[kind], {})
            for i in range(CLIP_STEPS + 1):
                u = i / CLIP_STEPS
                v = t.get(u * CLIP_LEN, [1.0, 1.0, 1.0] if kind == "scale" else [0.0, 0.0, 0.0])
                v = list(v); v[axis] += amp * math.sin(math.tau * (cyc * u + ph))
                t[u * CLIP_LEN] = tuple(v)
        tracks[bn] = tr
    return {"idle": {"loop": True, "length": CLIP_LEN, "bones": tracks}} if tracks else None


def export(wid):
    from forms_cube import _tone_k
    sc = build(wid); sh = sc.sh; st = stem(wid); key = "bwf_" + st
    groups = {}
    for b in sc.boxes: groups.setdefault(piece_of(b), []).append(b)
    os.makedirs(os.path.join(ROOT, "textures", "entity"), exist_ok=True)
    Image.fromarray(np.clip(sh.color, 0, 255).astype(np.uint8), "RGBA").save(os.path.join(ROOT, "textures", "entity", key + ".png"), optimize=True)
    gl = np.clip(sh.glow, 0, 255).astype(np.uint8); gl[gl[..., 3] == 0] = 0
    Image.fromarray(gl, "RGBA").save(os.path.join(ROOT, "textures", "entity", key + "_glow.png"), optimize=True)
    shim = Shim(sh)
    parts = []
    groups["acq"] = [b for b in groups.get("armR", []) if b.c[1] < 14.8]                                    # the ONE piece of the Acquire stage: bracer, paw, claws (and the weapon) of the right forearm
    for name in ("head", "body", "armL", "armR", "legL", "legR", "tail", "wings", "acq"):
        boxes = groups.get(name)
        if not boxes: continue
        ident = "%s_arm_%s" % (key, name)
        m = G.Model(ident, shim)
        used = {b.bone for b in boxes if b.bone != "root"}
        bones = []
        def want(bn):
            if bn in bones: return
            d = sc.bonedefs.get(bn)
            if d and d["parent"]: want(d["parent"])
            bones.append(bn)
        for bn in sorted(used): want(bn)
        for bn in bones:
            d = sc.bonedefs.get(bn)
            m.bone(bn, d["pivot"] if d else (0, 0, 0), d["parent"] if d else None)
        for k, b in enumerate(boxes):
            faces = {}
            X, Y, Z = b.R[:, 0], b.R[:, 1], b.R[:, 2]
            size = b.s
            for ai, ax in enumerate((X, Y, Z)):
                for sgn in (1, -1):
                    n = ax * sgn
                    kk = int(np.clip(_tone_k(n) + b.dt, 0, TONES - 1))
                    fw, fh = ((size[2], size[1]), (size[0], size[2]), (size[0], size[1]))[ai]
                    nT = b.mat.size
                    fwn = min(1.0, max(fw * 3.0 / nT, .12)); fhn = min(1.0, max(fh * 3.0 / nT, .12))
                    fi = {(0, 1): 0, (0, -1): 1, (1, 1): 2, (1, -1): 3, (2, 1): 4, (2, -1): 5}[(ai, sgn)]
                    ox = ((k * 37 + fi * 11) % 9) / 9 * (1 - fwn); oy = ((k * 53 + fi * 7) % 9) / 9 * (1 - fhn)
                    faces[FACE[(ai, sgn)]] = ("t_%s_%d" % (b.mat.name, kk), 3.0, False, (ox, oy, ox + fwn, oy + fhn))
            m.box(b.bone if b.bone != "root" else "root", b.c, b.s, b.R, faces)
        m.save()
        clips = clip_of(sc, bones)
        if clips: G.write_animations(ident, clips)
        parts.append(name)
    return st, parts, len(sc.boxes)


if __name__ == "__main__":
    ids = sys.argv[1:] or list(PAL)
    rows = []
    for w in ids:
        st, parts, n = export(w)
        rows.append("%s: %s" % (st, " ".join(parts)))
        print(w, st, n, "cubes", parts)
    if not sys.argv[1:]:
        open(os.path.join(HERE, "..", "..", "..", "docs", "beastwill_forms.txt"), "w", newline="\n").write("\n".join(rows) + "\n")
        ent = ",\n".join('            Map.entry("%s", "%s")' % tuple(r.split(": ")) for r in rows)
        jp = os.path.join(HERE, "..", "..", "..", "src", "main", "java", "com", "newuniverse", "nusmp", "beastwill", "BeastWillFormTable.java")
        open(jp, "w", newline="\n").write(JAVA % ent)
