"""Writes everything TEXT and DATA about the 13 boss weapons of the exclusive pocket tombs (1.99.0, wave 78) from tools/rift/pocket_weapon_roster.py:

    python3 -B tools/rift/gen_pocket_weapons.py            (idempotent)

  src/main/java/com/newuniverse/nusmp/relics/wave/Wave78.java          the relic definitions (GENERATED: edit the roster, not the Java)
  src/main/java/com/newuniverse/nusmp/relics/wave/Wave78Passives.java  the passive rules table
  tools/lang/rift_pockets.json                                          name, tooltip and card text of every weapon (merged into the fragment of the tombs; keys sorted)
  src/main/resources/assets/nusmp/weapon_classes.json + tools/relics/weapon_classes.json   a class row for every weapon (appended)
  src/main/resources/data/nusmp/mega/relic_themes.json                  the dungeon road each weapon leads to (appended)

It reuses the helpers of tools/relics/new197_gen.py (the card text, the passive text, the act and definition writers), so a weapon of a tomb reads and behaves like one of the 35 weapons
of 1.97.0; only the wave number, the passive table and the flag prefix (w78_) are its own. The meshes, skins, icons and item models are built by build_pocket_weapons.py.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "relics"))
import new197_gen as G                                              # noqa: E402
from pocket_weapon_roster import ROSTER, TOMB                       # noqa: E402

ROOT = G.ROOT
JAVA = G.JAVA
RES = G.RES
LANG = os.path.join(ROOT, "tools", "lang", "rift_pockets.json")


def def_java(e):
    """The definition of one weapon, in the text new197_gen writes for the 1.97.0 weapons, with this wave's own passive flag."""
    # not Djinn vessels (.vessel()): a tomb's weapon is the tomb's alone, it is not a body for a Djinn
    return G.def_java(e).replace('Passive.flag("w71_', 'Passive.flag("w78_').replace(".attune().vessel()", ".attune()")


def write_wave():
    out = []
    out.append("""package com.newuniverse.nusmp.relics.wave;

import com.newuniverse.nusmp.relics.Act;
import com.newuniverse.nusmp.relics.Grade;
import com.newuniverse.nusmp.relics.GradeDamage;
import com.newuniverse.nusmp.relics.Look;
import com.newuniverse.nusmp.relics.Passive;
import com.newuniverse.nusmp.relics.RelicDef;
import com.newuniverse.nusmp.relics.RelicSlot;
import com.newuniverse.nusmp.vfx.VfxShape;
import net.minecraft.world.entity.ai.attributes.AttributeModifier.Operation;

import java.util.function.Consumer;

/**
 * Relics of Many Worlds, wave 78 (1.99.0): the 13 boss weapons of the exclusive pocket tombs, 4 Legend, 8 God and 1 Genesis. Each is the drop of ONE tomb's mega-boss and of nothing else
 * (data/nusmp/loot_table/pocket/<tomb>/boss.json, gated by the {@code nusmp:in_pocket} condition and the {@code nusmp:pocket_relic} entry: labyrinth/mega/rift/pocket/PocketGate). GENERATED by
 * tools/rift/gen_pocket_weapons.py from tools/rift/pocket_weapon_roster.py: edit the table, not this file. Every weapon is held in the main hand, drawn as its own 3D model
 * (tools/rift/pocket_weapon_models.py), carries Tensura engravings, a passive ({@link Wave78Passives}, applied by {@link Wave78Events}) and two active abilities (the shapes of
 * {@link Wave71Acts}, the same shapes, the same balance law and the same safe-cast guard as the weapons of wave 71). The base damage is {@link GradeDamage#damage}: the owner's table
 * by grade, placed inside the range by the weapon type.
 */
public final class Wave78 {
    private Wave78() {}
""")
    for e in ROSTER:
        out.append('    static final double %s = GradeDamage.damage("%s", "%s");' % (G.const(e), e["grade"].lower(), G.dtype(e)))
    out.append("")
    out.append("    /** The ids of this wave, in order, and the tomb each one belongs to (the self-test and the tests read them). */")
    out.append("    public static final String[] IDS = {")
    for i in range(0, len(ROSTER), 3):
        out.append("            " + ", ".join(G.jstr(e["id"]) for e in ROSTER[i:i + 3]) + ",")
    out.append("    };")
    out.append("    public static final String[] TOMBS = {")
    for i in range(0, len(ROSTER), 3):
        out.append("            " + ", ".join(G.jstr(TOMB[e["id"]]) for e in ROSTER[i:i + 3]) + ",")
    out.append("    };\n")
    out.append("    public static void defs(Consumer<RelicDef> out) {")
    for e in ROSTER:
        out.append(def_java(e))
        out.append("")
    out.append("    }\n")
    out.append("""    /** Registers the damage rule of the passives (called once from the mod constructor, through the wave registry). */
    public static void hooks() {
        Wave78Events.register();
    }
}""")
    open(os.path.join(JAVA, "Wave78.java"), "w", newline="\n").write("\n".join(out) + "\n")


def write_passives():
    out = ["""package com.newuniverse.nusmp.relics.wave;

import java.util.Map;

/**
 * The passive rule of each weapon of wave 78. GENERATED by tools/rift/gen_pocket_weapons.py from tools/rift/pocket_weapon_roster.py: edit the table, not this file.
 * The rules and their arithmetic are {@link Wave71Rules} (the same rules as the weapons of wave 71); {@link Wave78Events} applies them.
 */
final class Wave78Passives {
    private Wave78Passives() {}

    static final Map<String, Wave71Rules.Rule> RULES = Map.ofEntries("""]
    rows = []
    for e in ROSTER:
        rows.append("            Map.entry(%s, %s)" % (G.jstr(e["id"]), G.rule_java(e["rule"])))
    out.append(",\n".join(rows))
    out.append("    );\n}")
    open(os.path.join(JAVA, "Wave78Passives.java"), "w", newline="\n").write("\n".join(out) + "\n")


def write_lang():
    d = {}
    if os.path.exists(LANG):
        d = json.load(open(LANG, encoding="utf-8"))
    for e in ROSTER:
        d["item.nusmp.%s" % e["id"]] = e["name"]
        d["item.nusmp.%s.desc" % e["id"]] = G.short_desc(e)
        d["item.nusmp.%s.card" % e["id"]] = G.card_text(e)
    with open(LANG, "w", newline="\n", encoding="utf-8") as f:
        json.dump(dict(sorted(d.items())), f, indent=2, ensure_ascii=True)
        f.write("\n")


def write_classes():
    pa = os.path.join(RES, "assets", "nusmp", "weapon_classes.json")
    pt = os.path.join(ROOT, "tools", "relics", "weapon_classes.json")
    a = json.load(open(pa))
    t = json.load(open(pt))
    for e in ROSTER:
        a["weapons"].setdefault(e["id"], e["cls"])
        t["weapons"].setdefault(e["id"], {"class": e["cls"]})
    with open(pa, "w", newline="\n") as f:
        f.write(json.dumps(a, indent=1, ensure_ascii=True) + "\n")
    with open(pt, "w", newline="\n") as f:
        f.write(json.dumps(t, indent=1, ensure_ascii=True))


def write_themes():
    p = os.path.join(RES, "data", "nusmp", "mega", "relic_themes.json")
    raw = open(p).read()
    d = json.loads(raw)
    for e in ROSTER:
        d["explicit"].setdefault(e["id"], e["theme"])
    text = json.dumps(d, indent=2, ensure_ascii=False)
    if raw.endswith("\n"):
        text += "\n"
    open(p, "w", newline="\n").write(text)


def main():
    write_wave()
    write_passives()
    write_lang()
    write_classes()
    write_themes()
    print("wrote Wave78.java, Wave78Passives.java, the lang lines, the class rows and the theme rows for %d weapons" % len(ROSTER))


if __name__ == "__main__":
    main()
