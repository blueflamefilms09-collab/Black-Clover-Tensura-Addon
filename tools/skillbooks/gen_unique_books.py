#!/usr/bin/env python3
"""Writes tools/lang/skillbooks_unique.json: the flat lang fragment of the unique skill books (1.96.0), for the lead to merge into en_us.json.

usage: python3 -B tools/skillbooks/gen_unique_books.py [--check]

WHY: every unique skill (one per Skill Book) shows its name and description in Tensura's own Ability Selection screen, and the Java side reads both through
Component.translatableWithFallback(key, english), where english is built by SkillTexts.description(line) from the shipped table assets/nusmp/skill_books.json. This script writes the very same
words into a flat fragment (key -> text), so the merged language file and the fallback can never differ (SkillBookLangTest compares them line by line). The table itself is generated by
tools/lines/gen_book_index.py from the route files; run that first when a line changes.

It also writes tools/lang/skillbooks_unique.remove.txt: the keys of en_us.json that belonged to the removed Skill Tree, the removed Fairy Tail magics and the Skill Points, which the lead deletes when merging
(this job may not edit en_us.json; a stale key is harmless, the game never asks for it).
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
BOOKS = os.path.join(ROOT, "src", "main", "resources", "assets", "nusmp", "skill_books.json")
LANG = os.path.join(ROOT, "src", "main", "resources", "assets", "nusmp", "lang", "en_us.json")
OUT = os.path.join(ROOT, "tools", "lang", "skillbooks_unique.json")
REMOVE = os.path.join(ROOT, "tools", "lang", "skillbooks_unique.remove.txt")

# the 29 removed magics and the 30 technique ids of their classic routes (the same lists as LegacyIds.java; SkillBookLangTest keeps the two in step)
REMOVED_LINES = ["arc_of_time", "beast_arm_takeover", "card_magic", "celestial_spirit_magic", "crash_magic", "dark_ecriture", "end_demon_awakening", "exceed_aera", "fairy_law",
                 "fire_dragon_slayer", "gravity_change", "heavenly_fire_god_slayer", "ice_make", "iron_dragon_slayer", "lightning_dragon_slayer", "poison_dragon_slayer",
                 "requip_gunslinger", "requip_titania", "satan_soul", "seith_totems", "shadow_dragon_slayer", "sky_dragon_slayer", "solid_script", "telekinesis_mind_hand",
                 "titan_magic", "water_body", "white_dragon_slayer", "wizard_saint_rock_magic", "wood_make"]

STATIC = {
    "item.nusmp.skill_book.faded": "Faded Skill Book",
    "item.nusmp.sp_book.faded": "Faded SP Book",
    "tooltip.nusmp.skill_book.teaches": "Teaches the unique skill: %s",
    "tooltip.nusmp.skill_book.removed": "The magic in this book was removed. Right-click to swap it for another book.",
    "tooltip.nusmp.skill_book.owned": "You already know this skill.",
    "tooltip.nusmp.sp_book.removed": "Skill Points are gone. Right-click to swap this for a Skill Book.",
    "message.nusmp.skillbook.learned": "You have learned the unique skill: %s.",
    "message.nusmp.skillbook.already_owned": "You already know %s. The book stays closed.",
    "message.nusmp.skillbook.blank": "The pages are blank.",
    "message.nusmp.skillbook.replaced": "The old pages crumble and a new book takes their place: %s.",
    "message.nusmp.skillbook.nothing_left": "You already know every skill a book could teach. The book stays closed.",
    "message.nusmp.skillbook.failed": "The book would not open. (A server error was logged.)",
    "message.nusmp.skillbook.guardian_book": "The Guardian lets go of a Skill Book: %s!",
    "message.nusmp.skillbook.migrated": "The Skill Tree is gone: the %s skill line(s) you owned are now unique skills in your Ability Selection.",
    "title.nusmp.skillbook.learned": "UNIQUE SKILL ACQUIRED",
    "msg.nusmp.unique.no_data": "This skill's data is not loaded on the server.",
    "nusmp.skill.legacy": "Forgotten Magic",
    "nusmp.skill.legacy.description": "A magic that was removed from this world. It does nothing and is forgotten when you next log in.",
}


def description(line):
    """The same words as SkillTexts.description(line) in Java."""
    parts = []
    if line.get("desc"):
        parts.append(line["desc"])
    if line.get("arts"):
        parts.append("Arts (press the skill key, scroll to change): " + ", ".join(line["arts"]) + ".")
    if line.get("passives"):
        parts.append("While switched on: " + ", ".join(line["passives"]) + ".")
    return "\n".join(parts)


def engine_texts():
    """The strings of LineText.java (the engine's own messages and the unique skill's)."""
    text = open(os.path.join(ROOT, "src/main/java/com/newuniverse/nusmp/skilltree/line/LineText.java"), encoding="utf-8").read()
    out = {}
    for m in re.finditer(r'def\("([^"]+)",\s*"((?:[^"\\]|\\.)*)"\)', text):
        out[m.group(1)] = json.loads('"%s"' % m.group(2))
    return out


def build():
    table = json.load(open(BOOKS, encoding="utf-8"))
    out = {}
    for bare, line in sorted(table["lines"].items()):
        out["nusmp.skill.line_" + bare] = line["name"]
        out["nusmp.skill.line_" + bare + ".description"] = description(line)
    out.update(engine_texts())
    out.update(STATIC)
    return out


def removed_keys():
    """The keys of en_us.json that only the removed systems used."""
    lang = json.load(open(LANG, encoding="utf-8"))
    removed_line_keys = {"nusmp.skill.line_" + b for b in REMOVED_LINES}
    pats = [r"^tree\.", r"^gui\.nusmp\.skilltree", r"^gui\.nusmp\.lines\.", r"^gui\.nusmp\.tmenu", r"^key\.nusmp\.line_", r"^message\.nusmp\.tree\.", r"^title\.nusmp\.tree\.",
            r"^nusmp\.skill\.ft_", r"^item\.nusmp\.sp_book\.[a-z_]+$", r"^tooltip\.nusmp\.sp_book\.(?!removed)", r"^tooltip\.nusmp\.skill_book\.(opens|duplicate|known)$",
            r"^msg\.nusmp\.line\.(locked|toggle_refused|inspect_refused)$"]
    rx = [re.compile(p) for p in pats]
    keys = [k for k in lang if k in removed_line_keys or any(r.search(k) for r in rx)]
    return sorted(keys)


def main():
    data = build()
    text = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    rem = "\n".join(removed_keys()) + "\n"
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text and os.path.exists(REMOVE) and open(REMOVE, encoding="utf-8").read() == rem
        print("ok: current" if ok else "STALE: run python3 -B tools/skillbooks/gen_unique_books.py")
        sys.exit(0 if ok else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    open(REMOVE, "w", encoding="utf-8", newline="\n").write(rem)
    print("ok: %d keys written, %d keys to remove from en_us.json" % (len(data), len(rem.splitlines())))


if __name__ == "__main__":
    main()
