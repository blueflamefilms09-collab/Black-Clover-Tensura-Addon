#!/usr/bin/env python3
"""Turns the downloaded ElevenLabs takes of the Spirit of Light's spoken lines into the mod's voice files and registers them (docs/magic/spirit_light.md, docs/audio/spoken_voices.md).

usage:  python3 -B tools/audio/spirit_light_voice.py <raw_dir>        convert every <id>.mp3 of tools/audio/spirit_light_lines.json found in <raw_dir>, then refresh the registrations
        python3 -B tools/audio/spirit_light_voice.py --refresh        only refresh the registrations from the files that exist (and list the lines that are missing)

For every line with a take: ffmpeg mono, 32 kHz, leading and trailing silence trimmed, loudnorm about -16 LUFS (true peak <= -1.5 dB), Ogg Vorbis q3 ->
src/main/resources/assets/nusmp/sounds/spirit_light/voice/<id>.ogg (the same chain as tools/audio/voice_convert.py). Then, for exactly the lines whose file exists (nothing is faked, no entry
without a file):
  * assets/nusmp/sounds.json: the event spirit_light.voice.<id> (through tools/audio/sl_sounds_json.py, one block of single-line entries),
  * src/main/java/.../spiritlight/SpiritLightVoiceLines.java: the list of lines that have a file and the text of every manifest line (the registry, the picker and the tests read it),
  * tools/audio/spirit_light_voice_report.json: seconds and bytes per file.
The raw mp3 takes stay outside the repository. A line that is missing is spoken as a synthesised cue instead (the server asks the picker, which answers null for a cue without a line).
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sl_sounds_json as SJ  # noqa: E402

ROOT = SJ.ROOT
OUT = os.path.join(ROOT, "src", "main", "resources", "assets", "nusmp", "sounds", "spirit_light", "voice")
MANIFEST = os.path.join(HERE, "spirit_light_lines.json")
REPORT = os.path.join(HERE, "spirit_light_voice_report.json")
JAVA = os.path.join(ROOT, "src", "main", "java", "com", "newuniverse", "nusmp", "spiritlight", "SpiritLightVoiceLines.java")
CHAIN = ("silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.04,areverse,"
         "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.12,areverse,"
         "loudnorm=I=-16:TP=-1.5:LRA=7")


def convert(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", src, "-af", CHAIN, "-ac", "1", "-ar", "32000", "-c:a", "libvorbis", "-q:a", "3", dst], check=True)


def seconds(path):
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path], capture_output=True, text=True, check=True)
    return float(r.stdout.strip())


def jstr(s):
    return json.dumps(s, ensure_ascii=False)


def write_java(lines, have):
    rows = ",\n".join("            new String[]{%s, %s, %s}" % (jstr(l["id"]), jstr(l["cue"]), jstr(l["text"])) for l in lines)
    ids = ",\n".join("            %s" % jstr(l["id"]) for l in lines if l["id"] in have)
    src = '''package com.newuniverse.nusmp.spiritlight;

import java.util.List;

/**
 * Why: the spoken lines of the seraph form of the Spirit of Light (tools/audio/spirit_light_lines.json), as pure data the registry, the picker and the tests read. {@link #ALL} is every line of the
 * manifest (id, cue, text); {@link #AVAILABLE} is the ids that HAVE an audio file under sounds/spirit_light/voice (a line without a file is never registered and never spoken: the picker answers
 * null and the server plays a synthesised cue instead). GENERATED by tools/audio/spirit_light_voice.py: run it again after adding takes.
 */
public final class SpiritLightVoiceLines {
    private SpiritLightVoiceLines() {}

    /** Every line of the manifest: {id, cue, text}. */
    public static final List<String[]> ALL = List.of(
%s);

    /** The ids that have a file (the ones registered as sound events and spoken). */
    public static final List<String> AVAILABLE = List.of(
%s);

    /** The text of a line (shown on the owner's action bar), or "" for an unknown id. */
    public static String text(String id) {
        for (String[] l : ALL) if (l[0].equals(id)) return l[2];
        return "";
    }

    public static boolean has(String id) { return AVAILABLE.contains(id); }
}
''' % (rows, ids)
    with open(JAVA, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)


def main():
    doc = json.load(open(MANIFEST, encoding="utf-8"))
    lines = doc["lines"]
    report = json.load(open(REPORT, encoding="utf-8")) if os.path.exists(REPORT) else {}
    raw = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("--") else None
    if raw:
        for ln in lines:
            src = os.path.join(raw, ln["id"] + ".mp3")
            if os.path.exists(src):
                dst = os.path.join(OUT, ln["id"] + ".ogg")
                convert(src, dst)
                report[ln["id"]] = {"seconds": round(seconds(dst), 2), "bytes": os.path.getsize(dst)}
    have = {ln["id"] for ln in lines if os.path.exists(os.path.join(OUT, ln["id"] + ".ogg"))}
    report = {k: v for k, v in report.items() if k in have}
    json.dump(report, open(REPORT, "w", encoding="utf-8"), indent=1, sort_keys=True)
    entries = SJ.read_block()
    sfx, _ = SJ.split(entries)
    voice = {"spirit_light.voice." + ln["id"]: {"sounds": [{"name": "nusmp:spirit_light/voice/" + ln["id"], "stream": False, "attenuation_distance": 32}]} for ln in lines if ln["id"] in have}
    SJ.write_block({**sfx, **voice})
    write_java(lines, have)
    total = sum(v["bytes"] for v in report.values())
    missing = [ln["id"] for ln in lines if ln["id"] not in have]
    print("%d of %d lines have a file (%d bytes, %.1f KB); missing: %s" % (len(have), len(lines), total, total / 1024.0, missing))


if __name__ == "__main__":
    main()
