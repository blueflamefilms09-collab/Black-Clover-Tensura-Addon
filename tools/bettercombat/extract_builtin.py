#!/usr/bin/env python3
"""Why: 1.39.0 pointed weapons at animations we authored; 1.46.0 uses ONLY what Better Combat itself ships. To make "only built-in" checkable
(by the generator and by WeaponAttributesTest, offline, without the mod on the class path) this script reads Better Combat's own source tree
once and writes tools/bettercombat/builtin_animations.json: every animation id in assets/bettercombat/player_animations, and every built-in
weapon preset in data/bettercombat/weapon_attributes with its inheritance resolved the way WeaponAttributesHelper.override does it
(a child value of 0 / null keeps the parent's, so the resolved range, hands and animations of each preset are what the generator needs).

Usage:  python tools/bettercombat/extract_builtin.py [path to the Better Combat checkout]
        (default /home/user/zsoltmolnarrr/bettercombat; the checkout is only needed when Better Combat itself changes)
"""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "builtin_animations.json")


def main(argv):
    src = argv[0] if argv else "/home/user/zsoltmolnarrr/bettercombat"
    res = os.path.join(src, "common", "src", "main", "resources")
    anims = sorted("bettercombat:" + os.path.basename(p)[:-5] for p in glob.glob(os.path.join(res, "assets", "bettercombat", "player_animations", "*.json")))
    raw = {}
    for p in glob.glob(os.path.join(res, "data", "bettercombat", "weapon_attributes", "*.json")):
        with open(p, encoding="utf-8") as f:
            raw[os.path.basename(p)[:-5]] = json.load(f)

    def resolve(name):
        chain, cur = [], name
        while cur is not None:
            doc = raw[cur]
            chain.insert(0, doc.get("attributes") or {})
            cur = doc["parent"].split(":", 1)[1] if doc.get("parent") else None
        r = {"range_bonus": 0.0, "two_handed": False, "pose": None, "category": None, "attacks": []}
        for a in chain:
            if a.get("range_bonus", 0) != 0:
                r["range_bonus"] = a["range_bonus"]
            if a.get("two_handed") is not None:
                r["two_handed"] = a["two_handed"]
            for k in ("pose", "category"):
                if a.get(k) is not None:
                    r[k] = a[k] or None
            if a.get("attacks"):
                merged = []
                for i, at in enumerate(a["attacks"]):
                    base = dict(r["attacks"][i]) if i < len(r["attacks"]) else {}
                    base.update({k: v for k, v in at.items() if v not in (None, 0)})
                    merged.append(base)
                r["attacks"] = merged
        r["animations"] = [x.get("animation") for x in r["attacks"]]
        del r["attacks"]
        return r

    presets = {n: resolve(n) for n in sorted(raw)}
    for n, d in presets.items():
        for a in d["animations"]:
            assert a in anims, "%s uses %s which is not an animation file" % (n, a)
    doc = {"_source": "Generated by tools/bettercombat/extract_builtin.py from the Better Combat 2.4.0 (MC 1.21.1) source: animations = "
                      "common/src/main/resources/assets/bettercombat/player_animations/*.json, presets = "
                      "common/src/main/resources/data/bettercombat/weapon_attributes/*.json (parent chain resolved like WeaponAttributesHelper.override). "
                      "Ids starting with bettercombat:pose_ are idle poses, not attack animations.",
           "animations": anims, "presets": presets}
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, indent=1)
        f.write("\n")
    print("wrote %s: %d animations, %d presets" % (OUT, len(anims), len(presets)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
