#!/usr/bin/env python3
"""
A dependency-free NBT writer and reader (standard library only: gzip + struct).

Why our own: the structure templates of the Labyrinth are GENERATED by scripts (see template.py) so they are deterministic and
reviewable in a diff; pulling in nbtlib would add a dependency the CI image does not have, and the format is small. Every tag type of the
Java edition format is covered: End, Byte, Short, Int, Long, Float, Double, ByteArray, String, List, Compound, IntArray, LongArray.
Big-endian, Java "modified UTF-8" strings, gzip on disk (what Minecraft reads).

Values are plain Python objects with thin typed wrappers where Python is ambiguous:
    Byte(1) Short(1) Int(1) Long(1)   int subclasses (a bare int is written as Int, a bool as Byte)
    Float(1.0) Double(1.0)            float subclasses (a bare float is written as Double)
    str                               TAG_String
    ByteArray(b"..") / bytes          TAG_Byte_Array
    IntArray([..]) / LongArray([..])  TAG_Int_Array / TAG_Long_Array
    List([..], tag_type=None) / list  TAG_List (element type inferred from the first element; empty -> TAG_End, as Minecraft writes it)
    Compound({..}) / dict             TAG_Compound (insertion order is kept)

    data = Compound({"DataVersion": Int(3955), "size": List([Int(3), Int(2), Int(3)])})
    dump(path, data)                # gzip file, root name ""
    name, data = load(path)         # gzip or raw, detected by the magic bytes
    raw = dumps(data); loads(raw)   # in-memory
"""
import gzip
import io
import struct

TAG_END, TAG_BYTE, TAG_SHORT, TAG_INT, TAG_LONG, TAG_FLOAT, TAG_DOUBLE = 0, 1, 2, 3, 4, 5, 6
TAG_BYTE_ARRAY, TAG_STRING, TAG_LIST, TAG_COMPOUND, TAG_INT_ARRAY, TAG_LONG_ARRAY = 7, 8, 9, 10, 11, 12

TAG_NAMES = {TAG_END: "TAG_End", TAG_BYTE: "TAG_Byte", TAG_SHORT: "TAG_Short", TAG_INT: "TAG_Int", TAG_LONG: "TAG_Long",
             TAG_FLOAT: "TAG_Float", TAG_DOUBLE: "TAG_Double", TAG_BYTE_ARRAY: "TAG_Byte_Array", TAG_STRING: "TAG_String",
             TAG_LIST: "TAG_List", TAG_COMPOUND: "TAG_Compound", TAG_INT_ARRAY: "TAG_Int_Array", TAG_LONG_ARRAY: "TAG_Long_Array"}


class Byte(int):
    tag = TAG_BYTE


class Short(int):
    tag = TAG_SHORT


class Int(int):
    tag = TAG_INT


class Long(int):
    tag = TAG_LONG


class Float(float):
    tag = TAG_FLOAT


class Double(float):
    tag = TAG_DOUBLE


class String(str):
    tag = TAG_STRING


class ByteArray(bytes):
    tag = TAG_BYTE_ARRAY


class IntArray(list):
    tag = TAG_INT_ARRAY


class LongArray(list):
    tag = TAG_LONG_ARRAY


class List(list):
    """A TAG_List. tag_type pins the element type (needed for an empty list that must not be TAG_End, e.g. an empty list of compounds
    a reader insists on); None infers it from the first element."""
    tag = TAG_LIST

    def __init__(self, items=(), tag_type=None):
        super().__init__(items)
        self.tag_type = tag_type


class Compound(dict):
    tag = TAG_COMPOUND


def tag_of(value):
    """The tag id a Python value is written as."""
    if isinstance(value, bool):
        return TAG_BYTE
    t = getattr(type(value), "tag", None)
    if t is not None:
        return t
    if isinstance(value, int):
        return TAG_INT
    if isinstance(value, float):
        return TAG_DOUBLE
    if isinstance(value, str):
        return TAG_STRING
    if isinstance(value, (bytes, bytearray)):
        return TAG_BYTE_ARRAY
    if isinstance(value, dict):
        return TAG_COMPOUND
    if isinstance(value, (list, tuple)):
        return TAG_LIST
    raise TypeError("cannot write %r as NBT" % (value,))


def _wrap(v, bits):
    """Two's-complement wrap into a signed field of `bits`, as a Java cast would."""
    v = int(v)
    m = 1 << bits
    v %= m
    return v - m if v >= (m >> 1) else v


# ---- modified UTF-8 (Java DataOutput.writeUTF): NUL as C0 80, astral characters as CESU-8 surrogate pairs ----

def _mutf8_encode(s):
    out = bytearray()
    for ch in s:
        cp = ord(ch)
        if cp == 0:
            out += b"\xc0\x80"
        elif cp < 0x80:
            out.append(cp)
        elif cp < 0x800:
            out += bytes((0xC0 | (cp >> 6), 0x80 | (cp & 0x3F)))
        elif cp < 0x10000:
            out += bytes((0xE0 | (cp >> 12), 0x80 | ((cp >> 6) & 0x3F), 0x80 | (cp & 0x3F)))
        else:
            cp -= 0x10000
            for sur in (0xD800 | (cp >> 10), 0xDC00 | (cp & 0x3FF)):
                out += bytes((0xE0 | (sur >> 12), 0x80 | ((sur >> 6) & 0x3F), 0x80 | (sur & 0x3F)))
    return bytes(out)


def _mutf8_decode(b):
    text = bytes(b).replace(b"\xc0\x80", b"\x00").decode("utf-8", "surrogatepass")
    # rejoin surrogate pairs into real code points
    return text.encode("utf-16", "surrogatepass").decode("utf-16")


# ---- writer ----

def _write_string(out, s):
    data = _mutf8_encode(s)
    if len(data) > 0xFFFF:
        raise ValueError("NBT string too long (%d bytes)" % len(data))
    out.write(struct.pack(">H", len(data)))
    out.write(data)


def _list_type(value):
    t = getattr(value, "tag_type", None)
    if t is None:
        t = tag_of(value[0]) if len(value) else TAG_END
    for i, item in enumerate(value):
        if tag_of(item) != t:
            raise ValueError("TAG_List element %d is %s, list is %s" % (i, TAG_NAMES[tag_of(item)], TAG_NAMES[t]))
    return t


def _write_payload(out, tag, value):
    if tag == TAG_BYTE:
        out.write(struct.pack(">b", _wrap(value, 8)))
    elif tag == TAG_SHORT:
        out.write(struct.pack(">h", _wrap(value, 16)))
    elif tag == TAG_INT:
        out.write(struct.pack(">i", _wrap(value, 32)))
    elif tag == TAG_LONG:
        out.write(struct.pack(">q", _wrap(value, 64)))
    elif tag == TAG_FLOAT:
        out.write(struct.pack(">f", float(value)))
    elif tag == TAG_DOUBLE:
        out.write(struct.pack(">d", float(value)))
    elif tag == TAG_BYTE_ARRAY:
        data = bytes(value)
        out.write(struct.pack(">i", len(data)))
        out.write(data)
    elif tag == TAG_STRING:
        _write_string(out, value)
    elif tag == TAG_LIST:
        t = _list_type(value)
        out.write(struct.pack(">bi", t, len(value)))
        for item in value:
            _write_payload(out, t, item)
    elif tag == TAG_COMPOUND:
        for k, v in value.items():
            vt = tag_of(v)
            out.write(struct.pack(">b", vt))
            _write_string(out, str(k))
            _write_payload(out, vt, v)
        out.write(b"\x00")
    elif tag == TAG_INT_ARRAY:
        out.write(struct.pack(">i", len(value)))
        out.write(struct.pack(">%di" % len(value), *[_wrap(v, 32) for v in value]))
    elif tag == TAG_LONG_ARRAY:
        out.write(struct.pack(">i", len(value)))
        out.write(struct.pack(">%dq" % len(value), *[_wrap(v, 64) for v in value]))
    elif tag == TAG_END:
        raise ValueError("TAG_End has no payload")
    else:
        raise ValueError("unknown tag %r" % tag)


def dumps(compound, name="", compress=False):
    """Serialise a root compound (named `name`, Minecraft uses "") to bytes; gzip when compress=True."""
    if tag_of(compound) != TAG_COMPOUND:
        raise TypeError("the root of an NBT file must be a compound")
    out = io.BytesIO()
    out.write(struct.pack(">b", TAG_COMPOUND))
    _write_string(out, name)
    _write_payload(out, TAG_COMPOUND, compound)
    raw = out.getvalue()
    return gzip.compress(raw, mtime=0) if compress else raw


def dump(path, compound, name="", compress=True):
    """Write a root compound to a file, gzipped (deterministic: mtime 0) unless compress=False."""
    with open(path, "wb") as f:
        f.write(dumps(compound, name, compress))


# ---- reader ----

class _Reader:
    def __init__(self, data):
        self.data = data
        self.pos = 0

    def take(self, n):
        if self.pos + n > len(self.data):
            raise ValueError("truncated NBT at byte %d (wanted %d more)" % (self.pos, n))
        b = self.data[self.pos:self.pos + n]
        self.pos += n
        return b

    def unpack(self, fmt):
        return struct.unpack(fmt, self.take(struct.calcsize(fmt)))[0]

    def string(self):
        n = self.unpack(">H")
        return _mutf8_decode(self.take(n))

    def payload(self, tag):
        if tag == TAG_BYTE:
            return Byte(self.unpack(">b"))
        if tag == TAG_SHORT:
            return Short(self.unpack(">h"))
        if tag == TAG_INT:
            return Int(self.unpack(">i"))
        if tag == TAG_LONG:
            return Long(self.unpack(">q"))
        if tag == TAG_FLOAT:
            return Float(self.unpack(">f"))
        if tag == TAG_DOUBLE:
            return Double(self.unpack(">d"))
        if tag == TAG_BYTE_ARRAY:
            return ByteArray(self.take(self.unpack(">i")))
        if tag == TAG_STRING:
            return self.string()
        if tag == TAG_LIST:
            t = self.unpack(">b")
            n = self.unpack(">i")
            if n < 0:
                raise ValueError("negative list length")
            if t == TAG_END and n > 0:
                raise ValueError("TAG_List of TAG_End with %d elements" % n)
            return List([self.payload(t) for _ in range(n)], tag_type=t)
        if tag == TAG_COMPOUND:
            c = Compound()
            while True:
                t = self.unpack(">b")
                if t == TAG_END:
                    return c
                k = self.string()
                c[k] = self.payload(t)
        if tag == TAG_INT_ARRAY:
            n = self.unpack(">i")
            return IntArray(struct.unpack(">%di" % n, self.take(4 * n)))
        if tag == TAG_LONG_ARRAY:
            n = self.unpack(">i")
            return LongArray(struct.unpack(">%dq" % n, self.take(8 * n)))
        raise ValueError("unknown tag id %r at byte %d" % (tag, self.pos))


def loads(data):
    """Parse bytes (gzip or raw, detected by the 1F 8B magic). Returns (root_name, Compound)."""
    if data[:2] == b"\x1f\x8b":
        data = gzip.decompress(data)
    r = _Reader(data)
    t = r.unpack(">b")
    if t != TAG_COMPOUND:
        raise ValueError("root tag is %s, not TAG_Compound" % TAG_NAMES.get(t, t))
    name = r.string()
    root = r.payload(TAG_COMPOUND)
    if r.pos != len(data):
        raise ValueError("%d trailing bytes after the root compound" % (len(data) - r.pos))
    return name, root


def load(path):
    with open(path, "rb") as f:
        return loads(f.read())


# ---- debugging ----

def snbt(value, indent=0):
    """A readable SNBT-like rendering (for previews and --check output; not a parser-grade SNBT emitter)."""
    tag = tag_of(value)
    pad = "  " * indent
    if tag == TAG_BYTE:
        return "%db" % int(value)
    if tag == TAG_SHORT:
        return "%ds" % int(value)
    if tag == TAG_INT:
        return "%d" % int(value)
    if tag == TAG_LONG:
        return "%dL" % int(value)
    if tag == TAG_FLOAT:
        return "%gf" % float(value)
    if tag == TAG_DOUBLE:
        return "%gd" % float(value)
    if tag == TAG_STRING:
        return '"%s"' % str(value).replace("\\", "\\\\").replace('"', '\\"')
    if tag == TAG_BYTE_ARRAY:
        return "[B;" + ",".join("%db" % b for b in bytes(value)) + "]"
    if tag == TAG_INT_ARRAY:
        return "[I;" + ",".join("%d" % v for v in value) + "]"
    if tag == TAG_LONG_ARRAY:
        return "[L;" + ",".join("%dL" % v for v in value) + "]"
    if tag == TAG_LIST:
        if not value:
            return "[]"
        if all(tag_of(v) not in (TAG_LIST, TAG_COMPOUND) for v in value):
            return "[" + ",".join(snbt(v) for v in value) + "]"
        return "[\n" + ",\n".join(pad + "  " + snbt(v, indent + 1) for v in value) + "\n" + pad + "]"
    if tag == TAG_COMPOUND:
        if not value:
            return "{}"
        return "{\n" + ",\n".join(pad + "  " + str(k) + ": " + snbt(v, indent + 1) for k, v in value.items()) + "\n" + pad + "}"
    raise ValueError(tag)


if __name__ == "__main__":
    import sys
    for p in sys.argv[1:]:
        n, root = load(p)
        print("# %s (root name %r)" % (p, n))
        print(snbt(root))
