"""Why: the Mob Foundry's people on the player model. For each of the roster's mobs that is a person (foundry_class.py) this writes
  * the skin `textures/entity/playermodel/foundry_<id>.png` (+ `_glow`), painted by the player-model kit's painter from the very row the mob's art-kit model was built from, weathered by the
    wear recipe of its family (recipes.py);
  * the extras `geo|animations|textures/entity/pmx_foundry_<id>` cut out of the mob's art-kit model by the player-model kit's extractor (wings, tails, horns, halos, capes, hats, the
    held weapon, anything that is not the body), with the clips of the mob's shared animation class (only the extras' tracks), plus the head parts the art kit drew on its head box (ears);
  * the look entry `foundry_<id>` of looks_dungeon.json: skin, arm width, scale (the model's height times the mob's size over the kit's 1.875), hair style and colour, glow, extras, the arm
    raised to hold the weapon, and the stance of the family (a goblin hunches, a ghoul reaches).
The creatures (slimes, insects, dragons, spirits, wisps ... foundry_class.LEGACY) get nothing: they keep the art-kit renderer. Deterministic: the same row always gives the same bytes.
"""
import os

import common as CM
import foundry_class as FC
import painter as P
import recipes as RC
import foundry_kit as FK
import extract_extras as EX
import characters as CH

HOLD = {"arm_r": "hold_r", "arm_l": "hold_l"}


def anim_path(idx):
    return os.path.join(CM.ANIM, "foundry_anim_%s.animation.json" % idx["anim"])


def prop_kinds(spec):
    props = spec.get("props") or {}
    return {"prop_r": (props.get("right") or {}).get("kind"), "prop_l": (props.get("left") or {}).get("kind")}


def look_for(row, idx, with_files=True):
    """Writes the files of one mob and returns (look id, look entry dict)."""
    rid = row["id"]
    name = "foundry_" + rid
    fam = FC.family_of(row)
    spec, img, glow, hair_style, hair_rgb, slim = P.paint(row, name, RC.foundry_recipe(fam))
    if with_files:
        os.makedirs(CM.SKINS, exist_ok=True)
        img.save(os.path.join(CM.SKINS, name + ".png"), optimize=True)
        gp = os.path.join(CM.SKINS, name + "_glow.png")
        if glow is not None:
            glow.save(gp, optimize=True)
        elif os.path.isfile(gp):
            os.remove(gp)
    height = idx["height"] * idx["size"]
    entry = {"skin": name, "slim": bool(slim), "scale": CM.look_scale(height)}
    extras = []
    info = None
    stem = "pmx_foundry_" + rid
    if with_files:
        info = EX.extract(rid, out_name=stem, height=idx["height"], src="foundry_" + rid, anim_src=anim_path(idx), tex_src="foundry_" + rid, kinds=prop_kinds(spec), compact=True)
    else:
        info = {"holds": {}} if os.path.isfile(os.path.join(CM.GEO, stem + ".geo.json")) else None
    if info is not None:
        extras.append({"model": stem, "texture": stem, "glow": os.path.isfile(os.path.join(CM.TEX, stem + "_glow.png"))})
        for anchor, v in (info.get("holds") or {}).items():
            entry[HOLD[anchor]] = v
    extras += P.part_extras(row, spec, hair_rgb)
    if glow is not None:
        entry["glow"] = True
    if hair_style and hair_style != "bald":
        entry["hair"] = hair_style
        entry["hair_color"] = CM.hexrgb(hair_rgb)
    if extras:
        entry["extras"] = extras
    st = FC.stance_of(row)
    if st:
        entry["stance"] = st
    return name, entry


def build(rows, only=None, with_files=True, log=print):
    """Looks of every person among `rows` (or of `only`): {look id: entry}."""
    index = CM.foundry_index()
    out = {}
    persons, creatures = FC.partition(rows)
    for r in persons:
        if only and r["id"] not in only:
            continue
        try:
            lid, entry = look_for(r, index[r["id"]], with_files)
            out[lid] = entry
        except Exception as ex:                      # one bad sheet must not stop the others
            import traceback
            log("FAILED %s: %r" % (r["id"], ex))
            traceback.print_exc()
    log("foundry: %d persons painted, %d creatures keep their own model" % (len(out), len(creatures)))
    return out


def write_legacy(rows):
    """assets/nusmp/playermodel/dungeon_legacy.json: the mobs that keep the art-kit renderer and why (the Java audit checks that every mob of the asset index is a person with a look or listed here)."""
    persons, creatures = FC.partition(rows)
    doc = {"version": 1, "note": "generated by tools/gen_dungeon_skins.py (tools/dungeon_skins/foundry_class.py): the Mob Foundry's mobs that are creatures, spirits or wisps, not people, and keep their own model",
           "people": len(persons), "creatures": {r["id"]: FC.legacy_reason(r) for r in creatures}}
    CM.write_json(os.path.join(CM.ASSETS, "playermodel", "dungeon_legacy.json"), doc)
