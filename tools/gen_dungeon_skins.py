"""Why: phase 2 of the player-model kit (docs/playermodel_phase2.md): every humanoid of the dungeon is drawn on the vanilla player model with an HD skin of its own. This script writes all of them
procedurally, so any skin can be redone by changing a row, a recipe or a number and running it again:

    python3 -B tools/gen_dungeon_skins.py                 every step
    python3 -B tools/gen_dungeon_skins.py parts           the head parts (ears, tusks, beards, snout, crown): pmx_dg_<part>
    python3 -B tools/gen_dungeon_skins.py archetypes      the 55 named families: dg_<id> (skin, glow, extras)
    python3 -B tools/gen_dungeon_skins.py special         Living Armor, Floor Warden, Goliath (two forms), the three soul-corpse puppets in four decay stages
    python3 -B tools/gen_dungeon_skins.py foundry         the Mob Foundry's people: foundry_<id> (skin, glow, extras); `--only a,b` for some of them
    python3 -B tools/gen_dungeon_skins.py --list          what is a person and what stays a creature

Every skin is a 64x64 player-layout PNG (the second layer, the hat / jacket / sleeve / pants layer, carries the armour plates, cloth, hoods and tears; a `_glow` map next to it where eyes, runes,
cracks or veins shine), wide or slim arms as the build asks. The data goes to assets/nusmp/playermodel/looks_dungeon.json (same format as looks.json, plus `stance`), which the game's loader reads
after looks.json and looks_abyssal.json (client/playermodel/PlayerLookTables). Existing entries of other tables are never touched. A step run with `--only` merges into the table.
Needs numpy and Pillow. Python as `python3 -B`.
"""
import json
import os
import sys
import time

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "dungeon_skins"))

import common as CM  # noqa: E402


def load_table():
    if os.path.isfile(CM.LOOKS_DUNGEON):
        with open(CM.LOOKS_DUNGEON) as f:
            return json.load(f).get("looks", {})
    return {}


def save_table(looks, only=False):
    doc = {"version": 1, "note": "generated by tools/gen_dungeon_skins.py (tools/dungeon_skins/*): the dungeon's humanoids in the format of playermodel/looks.json (skin, slim, glow, hair, scale, "
                                  "extras, arm hold) plus `stance`; do not edit by hand", "looks": looks}
    CM.write_json(CM.LOOKS_DUNGEON, doc)


def main(argv):
    steps = [a for a in argv if not a.startswith("--")]
    only = None
    if "--only" in argv:
        i = argv.index("--only")
        only = set(argv[i + 1].split(","))
        steps = [a for a in steps if a != argv[i + 1]]
    rows = CM.foundry_rows()
    if "--list" in argv:
        import foundry_class as FC
        persons, creatures = FC.partition(rows)
        print("%d people (player model), %d creatures (own model)" % (len(persons), len(creatures)))
        for r in creatures:
            print("  keeps its model: %-44s %s" % (r["id"], FC.legacy_reason(r)))
        return
    steps = steps or ["parts", "archetypes", "special", "foundry"]
    t0 = time.time()
    table = load_table() if only else {}
    if only is None and "all" not in steps and len(steps) < 4:
        table = load_table()                          # a partial run keeps the entries of the steps it does not run
    new = {}
    if "parts" in steps:
        import parts
        print("parts:", ", ".join(parts.write_all()))
    if "archetypes" in steps:
        import archetypes_gen
        new.update(archetypes_gen.build(only))
    if "special" in steps:
        import special
        new.update(special.arc_looks())
        new.update(special.puppet_looks())
    if "foundry" in steps:
        import foundry
        new.update(foundry.build(rows, only))
        foundry.write_legacy(rows)
    table.update(new)
    # a stable order: archetypes, the dungeon's own bodies, the puppets, then the foundry in roster order
    order = [k for k in table if k.startswith("dg_")] + [k for k in ("living_armor", "floor_warden", "goliath", "goliath_form2") if k in table] \
        + [k for k in table if k.startswith("corpse_")] + [k for k in table if k.startswith("foundry_")]
    rest = [k for k in table if k not in set(order)]
    save_table({k: table[k] for k in order + rest})
    print("wrote %s: %d looks in %.1fs" % (os.path.relpath(CM.LOOKS_DUNGEON, CM.ROOT), len(table), time.time() - t0))


if __name__ == "__main__":
    main(sys.argv[1:])
