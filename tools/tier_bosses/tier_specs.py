    outfit = {"top": top, "sleeves": sleeves or {"kind": "long", "cuff": top.get("trim")}, "legs": legs, "boots": {"kind": boots, "color": boots_color, "height": "calf"}}
    if inner: outfit["inner"] = inner
    if belt: outfit["belt"] = belt
    if gloves: outfit["gloves"] = gloves
    s = {"id": cid, "name": name, "role": "boss", "build": build, "height": height, "skin": skin, "face": face, "hair": hair, "outfit": outfit,
         "accessories": accessories or [], "glow": glow or {"color": None, "eyes": False, "props": False, "trim": False}}
    if cape: s["cape"] = cape
    if armor: s["armor"] = armor
    return s


