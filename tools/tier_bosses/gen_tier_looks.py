#!/usr/bin/env python3
"""3.33.0: paints the Tier List bosses on the player-model kit (docs/playermodel.md), the way every other humanoid of the mod is drawn: the vanilla player model with a 64x64 skin
of its own (+ a glow map), the hair layer, wide or slim arms, scaled to the boss's height.

    python3 -B tools/tier_bosses/gen_tier_looks.py [--flat] [--plain] [--sheet out.png] [id ...]

3.37: the default is the anime skin style v2 (volume mode: the kit's volumetric anime_* hair + armour and costume pieces on the overlay layers, see docs/bosses/anime_style_v2.md);
`--flat` repaints the 3.33.1 look (hair painted flat on the skin, hair style "bald"); `--plain` is the first kit painter.

Reads the sheets of tier_specs.py (the art kit's vocabulary), paints each with tools/playermodel/gen_skins.paint_character, writes
assets/nusmp/textures/entity/playermodel/<id>.png (+ _glow.png) and assets/nusmp/playermodel/looks_tier.json (same format as looks.json; merged add-only by PlayerLookTables).
Ids that are not listed here are never touched. Needs numpy and Pillow.
"""
import json
import os
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.abspath(os.path.join(HERE, ".."))
for p in (HERE, os.path.join(TOOLS, "playermodel"), TOOLS, os.path.join(TOOLS, "arc")):
    if p not in sys.path:
        sys.path.insert(0, p)

import gen_hair  # noqa: E402
import gen_skins as GS  # noqa: E402
from arc_kit import spec as S  # noqa: E402
from tier_specs import SHEETS  # noqa: E402
import anime_skin  # noqa: E402

def light_post(cv, spec, seed, glow):
    """3.36.0: Light Yagami's own notebook motif: a small teal notebook in the breast pocket (white page edge on top, a gold bookmark ribbon) and a thin teal page-edge line on the left cuff.
    An original design (no copied prop); the owner may replace the whole skin PNG."""
    def book(face, lx, ly, lz, w, h, d):
        if face != "front" or lx not in (5, 6) or ly < 2 or ly > 5:
            return None
        if ly == 2:
            return (236, 234, 224, 255)                          # the pages
        if lx == 6 and ly >= 3:
            return (214, 176, 64, 255) if ly == 5 else (22, 92, 88, 255)   # the ribbon hangs from the spine edge
        return (31, 122, 116, 255) if ly < 5 else (22, 92, 88, 255)
    cv.paint("body", book, overlay=True, faces=("front",))
    cv.paint("body", book, overlay=False, faces=("front",))

    def cuff(face, lx, ly, lz, w, h, d):
        if face != "front" or ly != 9:
            return None
        return (53, 208, 181, 255)
    cv.paint("arm_l", cuff, overlay=True, faces=("front",))
    return False


POSTS = {"light_yagami": light_post}
OUT_LOOKS = os.path.join(GS.ASSETS, "playermodel", "looks_tier.json")


def main(argv):
    ids = [a for a in argv if not a.startswith("--") and a in SHEETS]
    sheet_out = argv[argv.index("--sheet") + 1] if "--sheet" in argv else None
    gen_hair.build()
    masks = {sid: getattr(st, "mask", None) for sid, st in gen_hair.STYLES.items()}
    os.makedirs(GS.SKINS, exist_ok=True)
    looks = {}
    if os.path.isfile(OUT_LOOKS):
        looks = json.load(open(OUT_LOOKS)).get("looks", {})
    painted = []
    for cid in ids or list(SHEETS):
        raw = dict(SHEETS[cid])
        v2 = raw.pop("_v2", None)                       # the optional style-v2 block is not part of the art kit's vocabulary: kept outside normalize, handed to the painter
        spec = S.normalize(raw, cid)
        if v2:
            spec["_v2"] = v2
        if "--plain" in argv:
            img, glow, hs, hrgb, slim = GS.paint_character(spec, cid, masks, POSTS.get(cid))          # the first kit painter
        else:
            img, glow, hs, hrgb, slim = anime_skin.paint_character(spec, cid, masks, POSTS.get(cid), volume="--flat" not in argv)
        img.save(os.path.join(GS.SKINS, cid + ".png"))
        if glow is not None:
            glow.save(os.path.join(GS.SKINS, cid + "_glow.png"))
        looks[cid] = GS.look_entry(cid, spec, hs, hrgb, slim, glow is not None, None, None, None)
        if hs == "bald":                                # flat mode: no kit hair (look_entry already leaves hair out for bald; stated here so an old entry is not kept)
            looks[cid].pop("hair", None)
            looks[cid].pop("hair_color", None)
        painted.append((cid, img))
    os.makedirs(os.path.dirname(OUT_LOOKS), exist_ok=True)
    json.dump({"version": 1, "note": "generated by tools/tier_bosses/gen_tier_looks.py (the Tier List bosses) in the format of playermodel/looks.json; do not edit by hand",
               "looks": dict(sorted(looks.items()))}, open(OUT_LOOKS, "w"), indent=1)
    print("painted %d skins, table has %d looks" % (len(painted), len(looks)))
    if sheet_out:
        from PIL import Image
        cols = 8
        S_ = 4
        cell = 64 * S_
        rows = (len(painted) + cols - 1) // cols
        sheet = Image.new("RGBA", (cell * cols, cell * rows), (40, 42, 48, 255))
        for i, (cid, img) in enumerate(painted):
            sheet.alpha_composite(img.resize((cell, cell), Image.NEAREST), ((i % cols) * cell, (i // cols) * cell))
        sheet.save(sheet_out)
        print("sheet", sheet_out)


if __name__ == "__main__":
    main(sys.argv[1:])
